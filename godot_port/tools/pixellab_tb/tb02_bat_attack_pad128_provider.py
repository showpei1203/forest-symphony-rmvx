  for name in keys:
   if jobs[name].get('status')=='completed':continue
   res=api('/background-jobs/'+jobs[name]['job_id']);status=res.get('status');last=res.get('last_response') or {}
   progress=last.get('progress')
   if (status,progress)!=last_states.get(name):print('POLL',name,status,progress,'usage',res.get('usage'),flush=True);last_states[name]=(status,progress)
   if status=='failed':
    jobs[name]['status']='failed';jobs[name]['error']={k:v for k,v in last.items() if k not in ('image','images')};continue
   if status!='completed':continue
   def dec(obj):
    if isinstance(obj,dict):
     for k in ('base64','image','data'):
      if k in obj:return dec(obj[k])
    if isinstance(obj,str):
     if obj.startswith('data:'):obj=obj.split(',',1)[1]
     try:return Image.open(io.BytesIO(base64.b64decode(obj))).convert('RGBA')
     except Exception:return None
    return None
   frames=[]
