#!/usr/bin/env python3
"""M2 private boot-final bundle preflight. Reads files only; never exports FS data.

This validates a candidate generated by the original VX runtime AFTER
FS_DB_AUTOSET.apply_all. It cannot create or authenticate that runtime witness.
Run in an authorized private workspace, never against public GitHub assets.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

NAMES = ("actors", "classes", "skills", "items", "weapons", "armors",
         "enemies", "states", "troops", "system", "animations")
ARRAY_NAMES = tuple(n for n in NAMES if n != "system")


def integral_number(value):
    # JSON numeric values are integer-valued, not strings or booleans.
    return (type(value) is int and abs(value) <= 9007199254740991 or
            type(value) is float and math.isfinite(value) and
            abs(value) <= 9007199254740991 and value.is_integer())

def valid_ref(rows, value):
    return (isinstance(rows, list) and integral_number(value) and
            0 < value < len(rows) and isinstance(rows[int(value)], dict))

def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_bundle(folder):
    folder = Path(folder)
    errors = []
    tables = {}
    manifest_path = folder / "fs_boot_final_authority.json"
    witness_path = folder / "fs_boot_final_runtime_witness.json"
    try:
        manifest = json.loads(manifest_path.read_bytes().decode("utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        return ["invalid provenance JSON: " + str(exc)]
    if not isinstance(manifest, dict):
        return ["provenance must be JSON objects"]
    for key, expected in (
        ("schema", "fs-boot-final-authority-v1"),
        ("stage", "post_FS_DB_AUTOSET.apply_all"),
        ("rgss2_script_sections", 505),
        ("master_setup_pages", 22),
        ("vx_runtime_trace_verified", True),
    ):
        if (manifest.get(key) != expected or
                (type(expected) is bool and type(manifest.get(key)) is not bool) or
                (type(expected) is int and not integral_number(manifest.get(key)))):
            errors.append("manifest mismatch: " + key)
    digest_map = manifest.get("database_sha256")
    if not isinstance(digest_map, dict):
        return errors + ["manifest database_sha256 must be object"]
    # Hash and decode the same immutable bytes, never reopen a verified file.
    try:
        witness_bytes = witness_path.read_bytes()
        if manifest.get("vx_runtime_witness_sha256") != hashlib.sha256(witness_bytes).hexdigest():
            return errors + ["witness bytes SHA256 mismatch"]
        witness = json.loads(witness_bytes.decode("utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        return errors + ["invalid provenance JSON: " + str(exc)]
    if not isinstance(witness, dict):
        return errors + ["provenance must be JSON objects"]
    for name in NAMES:
        try:
            raw = (folder / (name + ".json")).read_bytes()
            if digest_map.get(name) != hashlib.sha256(raw).hexdigest():
                errors.append("table bytes SHA256 mismatch: " + name)
                continue
            tables[name] = json.loads(raw.decode("utf-8"))
        except (OSError, ValueError, UnicodeError) as exc:
            errors.append("invalid JSON " + name + ": " + str(exc))
    if errors:
        return errors
    if witness.get("stage") != "post_FS_DB_AUTOSET.apply_all":
        errors.append("witness not post-Apply")
    if witness.get("engine") != "RPG Maker VX RGSS2":
        errors.append("witness engine mismatch")
    counts = witness.get("table_counts", {})
    if not isinstance(counts, dict):
        counts = {}
        errors.append("witness table_counts is not object")
    for name in ARRAY_NAMES:
        rows = tables[name]
        if not isinstance(rows, list):
            errors.append("table not array: " + name)
            continue
        if not rows or rows[0] is not None:
            errors.append("VX source array index zero not null: " + name)
        actual = sum(row is not None for row in rows)
        if not integral_number(counts.get(name)) or counts.get(name) != actual or actual <= 0:
            errors.append("post-Apply record count mismatch: " + name)
        for index, row in enumerate(rows):
            if row is not None and (not isinstance(row, dict) or
                                    not integral_number(row.get("id")) or row.get("id") != index):
                # Animations and other RPG::BaseItem records carry id too.
                errors.append("record index/id mismatch: %s[%d]" % (name, index))
                break
    system = tables["system"]
    if not isinstance(system, dict):
        errors.append("system must be object")
    else:
        party = system.get("party_members")
        roster = witness.get("party_actor_ids")
        if (not isinstance(party, list) or not party or
                not isinstance(roster, list) or not roster or
                not all(integral_number(v) for v in roster)):
            errors.append("initial party and witness roster must be nonempty numeric arrays")
        else:
            if party != roster:
                errors.append("initial party differs from runtime witness")
            actors = tables.get("actors", [])
            seen_party = set()
            for actor_id in party:
                if not valid_ref(actors, actor_id):
                    errors.append("party actor reference missing")
                elif int(actor_id) in seen_party:
                    errors.append("duplicate initial party actor: " + str(actor_id))
                else:
                    seen_party.add(int(actor_id))
    actors = tables.get("actors", [])
    classes = tables.get("classes", [])
    if isinstance(actors, list) and isinstance(classes, list):
        for actor in actors:
            if not isinstance(actor, dict):
                continue
            cid = actor.get("class_id")
            if not valid_ref(classes, cid):
                errors.append("actor %s has missing class" % actor.get("id"))
            table = actor.get("parameters")
            if not isinstance(table, dict):
                errors.append("actor %s has invalid parameter Table" % actor.get("id"))
                continue
            xsize, ysize, zsize = (table.get("xsize"), table.get("ysize"),
                                     table.get("zsize", 1))
            values = table.get("data_int16")
            if (not integral_number(xsize) or xsize != 6 or
                    not integral_number(ysize) or ysize < 1 or
                    not integral_number(zsize) or zsize != 1 or
                    not isinstance(values, list) or
                    len(values) != xsize * ysize * zsize or
                    any(not integral_number(value) or value < -32768 or value > 32767
                        for value in values)):
                errors.append("actor %s has invalid parameter Table" % actor.get("id"))
                continue
            level = actor.get("initial_level")
            if not integral_number(level) or not 1 <= level < ysize:
                errors.append("actor %s has invalid initial_level" % actor.get("id"))
    # The post-Apply class learnings must point to live Skills; a fabricated
    # witness with correct counts cannot authorize an absent skill.
    skills = tables.get("skills", [])
    if isinstance(classes, list) and isinstance(skills, list):
        for klass in classes:
            if not isinstance(klass, dict):
                continue
            learnings = klass.get("learnings")
            if not isinstance(learnings, list):
                errors.append("class learnings not array: " + str(klass.get("id")))
                continue
            for learning in learnings:
                skill_id = learning.get("skill_id") if isinstance(learning, dict) else None
                if not valid_ref(skills, skill_id):
                    errors.append("class %s learns missing skill %s" %
                                  (klass.get("id"), skill_id))
                    break
    troops = tables.get("troops", [])
    enemies = tables.get("enemies", [])
    if isinstance(troops, list) and isinstance(enemies, list):
        for troop in troops:
            if not isinstance(troop, dict):
                continue
            members = troop.get("members")
            if not isinstance(members, list):
                errors.append("troop members not array: " + str(troop.get("id")))
                continue
            for member in members:
                enemy_id = member.get("enemy_id") if isinstance(member, dict) else None
                if not valid_ref(enemies, enemy_id):
                    errors.append("troop %s references missing enemy" % troop.get("id"))
                    break
    return errors


def _self_test():
    import tempfile
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        data = {}
        for name in NAMES:
            data[name] = {"party_members": [1]} if name == "system" else [None, {"id": 1}]
        data["actors"][1].update({
            "class_id": 1, "initial_level": 1,
            "parameters": {"xsize": 6, "ysize": 2, "zsize": 1, "data_int16": [1]*12}
        })
        data["classes"][1]["learnings"] = []
        data["troops"][1]["members"] = []
        for name, value in data.items():
            (root / (name + ".json")).write_text(
                json.dumps(value), encoding="utf-8")
        witness = {
            "stage": "post_FS_DB_AUTOSET.apply_all",
            "engine": "RPG Maker VX RGSS2",
            "party_actor_ids": [1],
            "table_counts": {name: 1 for name in ARRAY_NAMES},
        }
        wp = root / "fs_boot_final_runtime_witness.json"
        wp.write_text(json.dumps(witness), encoding="utf-8")
        manifest = {
            "schema": "fs-boot-final-authority-v1",
            "stage": "post_FS_DB_AUTOSET.apply_all",
            "rgss2_script_sections": 505,
            "master_setup_pages": 22,
            "vx_runtime_trace_verified": True,
            "vx_runtime_witness_sha256": sha256(wp),
            "database_sha256": {name: sha256(root / (name + ".json")) for name in NAMES},
        }
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert validate_bundle(root) == [], validate_bundle(root)
        # Recompute all digest evidence for a semantic corruption: SHA then
        # matches, so only the new cross-table guard can detect the failure.
        data["classes"][1]["learnings"] = [{"skill_id": 999}]
        (root / "classes.json").write_text(
            json.dumps(data["classes"]), encoding="utf-8")
        manifest["database_sha256"]["classes"] = sha256(root / "classes.json")
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert any("learns missing skill" in e for e in validate_bundle(root))
        data["classes"][1]["learnings"] = []
        (root / "classes.json").write_text(
            json.dumps(data["classes"]), encoding="utf-8")
        manifest["database_sha256"]["classes"] = sha256(root / "classes.json")
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert validate_bundle(root) == [], validate_bundle(root)
        data["troops"][1]["members"] = [{"enemy_id": 999}]
        (root / "troops.json").write_text(json.dumps(data["troops"]), encoding="utf-8")
        assert any("SHA256 mismatch: troops" in e for e in validate_bundle(root))
        manifest["database_sha256"]["troops"] = sha256(root / "troops.json")
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert any("missing enemy" in e for e in validate_bundle(root))
        manifest["database_sha256"] = None
        (root / "fs_boot_final_authority.json").write_text(json.dumps(manifest), encoding="utf-8")
        assert any("database_sha256 must be object" in e for e in validate_bundle(root))
        # A correctly re-hashed malformed Table must still fail safely.
        manifest["database_sha256"] = {
            name: sha256(root / (name + ".json")) for name in NAMES}
        for bad in (None, [], {"xsize": 6, "ysize": "1", "data_int16": [1]*6},
                    {"xsize": 6, "ysize": 1, "data_int16": "123456"},
                    {"xsize": 6, "ysize": 1, "data_int16": [40000]*6}):
            data["actors"][1]["parameters"] = bad
            (root / "actors.json").write_text(json.dumps(data["actors"]), encoding="utf-8")
            manifest["database_sha256"]["actors"] = sha256(root / "actors.json")
            (root / "fs_boot_final_authority.json").write_text(
                json.dumps(manifest), encoding="utf-8")
            assert any("invalid parameter Table" in e for e in validate_bundle(root)), bad
    print("M2 boot-final bundle preflight self-test PASS")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folder", nargs="?", help="Private post-Apply bundle folder")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        _self_test()
        return
    if not args.folder:
        parser.error("folder required unless --self-test")
    problems = validate_bundle(args.folder)
    if problems:
        for problem in problems:
            print("FAIL:", problem)
        raise SystemExit(1)
    print("M2 structural bundle preflight PASS; original VX runtime authenticity still requires independent QA")


if __name__ == "__main__":
    main()
