#!/usr/bin/env python3
"""M2 private boot-final bundle preflight. Reads files only; never exports FS data.

This validates a candidate generated by the original VX runtime AFTER
FS_DB_AUTOSET.apply_all. It cannot create or authenticate that runtime witness.
Run in an authorized private workspace, never against public GitHub assets.
"""
import argparse
import hashlib
import json
from pathlib import Path

NAMES = ("actors", "classes", "skills", "items", "weapons", "armors",
         "enemies", "states", "troops", "system", "animations")
ARRAY_NAMES = tuple(n for n in NAMES if n != "system")


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_bundle(folder):
    folder = Path(folder)
    errors = []
    tables = {}
    hashes = {}
    for name in NAMES:
        path = folder / (name + ".json")
        if not path.is_file():
            errors.append("missing table: " + name)
            continue
        hashes[name] = sha256(path)
        try:
            tables[name] = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeError) as exc:
            errors.append("invalid JSON " + name + ": " + str(exc))
    manifest_path = folder / "fs_boot_final_authority.json"
    witness_path = folder / "fs_boot_final_runtime_witness.json"
    for path in (manifest_path, witness_path):
        if not path.is_file():
            errors.append("missing provenance file: " + path.name)
    if errors:
        return errors
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        witness = json.loads(witness_path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        return ["invalid provenance JSON: " + str(exc)]
    if not isinstance(manifest, dict) or not isinstance(witness, dict):
        return ["provenance must be JSON objects"]
    for key, expected in (
        ("schema", "fs-boot-final-authority-v1"),
        ("stage", "post_FS_DB_AUTOSET.apply_all"),
        ("rgss2_script_sections", 505),
        ("master_setup_pages", 22),
        ("vx_runtime_trace_verified", True),
    ):
        if manifest.get(key) != expected:
            errors.append("manifest mismatch: " + key)
    if manifest.get("vx_runtime_witness_sha256") != sha256(witness_path):
        errors.append("witness bytes SHA256 mismatch")
    for name in NAMES:
        if manifest.get("database_sha256", {}).get(name) != hashes[name]:
            errors.append("table bytes SHA256 mismatch: " + name)
    if witness.get("stage") != "post_FS_DB_AUTOSET.apply_all":
        errors.append("witness not post-Apply")
    if witness.get("engine") != "RPG Maker VX RGSS2":
        errors.append("witness engine mismatch")
    counts = witness.get("table_counts", {})
    if not isinstance(counts, dict):
        counts = {}
        errors.append("witness table_counts is not object")
    for name in ARRAY_NAMES:
        rows = tables[name]
        if not isinstance(rows, list):
            errors.append("table not array: " + name)
            continue
        actual = sum(row is not None for row in rows)
        if counts.get(name) != actual:
            errors.append("post-Apply record count mismatch: " + name)
        for index, row in enumerate(rows):
            if row is not None and (not isinstance(row, dict) or
                                    row.get("id") != index):
                # Animations and other RPG::BaseItem records carry id too.
                errors.append("record index/id mismatch: %s[%d]" % (name, index))
                break
    system = tables["system"]
    if not isinstance(system, dict):
        errors.append("system must be object")
    else:
        if system.get("party_members") != witness.get("party_actor_ids"):
            errors.append("initial party differs from runtime witness")
        for actor_id in system.get("party_members", []):
            actors = tables.get("actors", [])
            if not isinstance(actor_id, int) or not isinstance(actors, list) or (
                    actor_id <= 0 or actor_id >= len(actors) or
                    actors[actor_id] is None):
                errors.append("party actor reference missing")
                break
    actors = tables.get("actors", [])
    classes = tables.get("classes", [])
    if isinstance(actors, list) and isinstance(classes, list):
        for actor in actors:
            if not isinstance(actor, dict):
                continue
            cid = actor.get("class_id")
            if not isinstance(cid, int) or cid <= 0 or cid >= len(classes) or classes[cid] is None:
                errors.append("actor %s has missing class" % actor.get("id"))
            table = actor.get("parameters", {})
            if not isinstance(table, dict) or table.get("xsize") != 6 or (
                    table.get("ysize", 0) < 1) or (
                    len(table.get("data_int16", [])) !=
                    table.get("xsize", 0) * table.get("ysize", 0) * table.get("zsize", 1)):
                errors.append("actor %s has invalid parameter Table" % actor.get("id"))
    troops = tables.get("troops", [])
    enemies = tables.get("enemies", [])
    if isinstance(troops, list) and isinstance(enemies, list):
        for troop in troops:
            if not isinstance(troop, dict):
                continue
            for member in troop.get("members", []):
                enemy_id = member.get("enemy_id") if isinstance(member, dict) else None
                if not isinstance(enemy_id, int) or enemy_id <= 0 or (
                        enemy_id >= len(enemies) or enemies[enemy_id] is None):
                    errors.append("troop %s references missing enemy" % troop.get("id"))
                    break
    return errors


def _self_test():
    import tempfile
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        data = {}
        for name in NAMES:
            data[name] = {"party_members": [1]} if name == "system" else [None, {"id": 1}]
        data["actors"][1].update({
            "class_id": 1,
            "parameters": {"xsize": 6, "ysize": 1, "zsize": 1, "data_int16": [1]*6}
        })
        for name, value in data.items():
            (root / (name + ".json")).write_text(
                json.dumps(value), encoding="utf-8")
        witness = {
            "stage": "post_FS_DB_AUTOSET.apply_all",
            "engine": "RPG Maker VX RGSS2",
            "party_actor_ids": [1],
            "table_counts": {name: 1 for name in ARRAY_NAMES},
        }
        wp = root / "fs_boot_final_runtime_witness.json"
        wp.write_text(json.dumps(witness), encoding="utf-8")
        manifest = {
            "schema": "fs-boot-final-authority-v1",
            "stage": "post_FS_DB_AUTOSET.apply_all",
            "rgss2_script_sections": 505,
            "master_setup_pages": 22,
            "vx_runtime_trace_verified": True,
            "vx_runtime_witness_sha256": sha256(wp),
            "database_sha256": {name: sha256(root / (name + ".json")) for name in NAMES},
        }
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert validate_bundle(root) == [], validate_bundle(root)
        data["troops"][1]["members"] = [{"enemy_id": 999}]
        (root / "troops.json").write_text(json.dumps(data["troops"]), encoding="utf-8")
        assert any("SHA256 mismatch: troops" in e for e in validate_bundle(root))
        manifest["database_sha256"]["troops"] = sha256(root / "troops.json")
        (root / "fs_boot_final_authority.json").write_text(
            json.dumps(manifest), encoding="utf-8")
        assert any("missing enemy" in e for e in validate_bundle(root))
    print("M2 boot-final bundle preflight self-test PASS")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folder", nargs="?", help="Private post-Apply bundle folder")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        _self_test()
        return
    if not args.folder:
        parser.error("folder required unless --self-test")
    problems = validate_bundle(args.folder)
    if problems:
        for problem in problems:
            print("FAIL:", problem)
        raise SystemExit(1)
    print("M2 structural bundle preflight PASS; original VX runtime authenticity still requires independent QA")


if __name__ == "__main__":
    main()
