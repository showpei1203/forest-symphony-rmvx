module ScriptExporter
  def self.export
    File.open("All_Scripts_Export.txt", "w") do |file|
      $RGSS_SCRIPTS.each do |script|
        # script[1] 是腳本分頁名稱, script[3] 是經過壓縮的腳本內容
        name = script[1]
        content = Zlib::Inflate.inflate(script[2])
        
        file.write("-" * 50 + "\n")
        file.write("分頁名稱: #{name}\n")
        file.write("-" * 50 + "\n")
        file.write(content)
        file.write("\n\n")
      end
    end
    print "所有腳本已成功導出至 All_Scripts_Export.txt！"
    exit # 導出後自動關閉遊戲
  end
end

# 立即執行導出
ScriptExporter.export