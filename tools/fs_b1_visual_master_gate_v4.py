def count_diff(a,b):
    assert a.mode==b.mode=="RGBA" and a.size==b.size
    aa=a.getdata();bb=b.getdata()
    n=0;bounds=[W,H,-1,-1];samples=[]
    same_alpha=0
    for y in range(H):
        for x in range(W):
            p,q=aa[y*W+x],bb[y*W+x]
            if p!=q:
                n+=1
                if p[3]==q[3]:same_alpha+=1
                bounds=[min(bounds[0],x),min(bounds[1],y),max(bounds[2],x),max(bounds[3],y)]
                if len(samples)<12:samples.append({"xy":[x,y],"render":p,"visual":q})
    return {"different_pixels":n,"same_alpha_rgb_differences":same_alpha,
            "bbox_xyxy":[bounds[0],bounds[1],bounds[2]+1,bounds[3]+1] if n else None,
            "examples":samples}
def witness(label,a,b):
    metrics=count_diff(a,b)
    overlay=a.copy()
    ap=overlay.load()
    # red audit dots; only visual diagnostic, never source
    for y in range(H):
        for x in range(W):
            if a.getpixel((x,y))!=b.getpixel((x,y)):
                ap[x,y]=(255,22,40,255)
    overlay.save(NEG/(label+"_HEATMAP.png"))
    return metrics

