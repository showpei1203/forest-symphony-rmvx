# ■ RPG
#==============================================================================
module RPG
  #=============================================================================
  # □ ReadNote
  #=============================================================================
  module ReadNote
    def self.read(str, section, mismatch = nil)
      str.each_line do |line|
        ## 不希望忽略大小写,则删掉下一行最后一个i
        eval("#{line}; return #{section}") if line =~ /^\s*#{section}\s*=/i
      end
      return mismatch
    end
  end
  #=============================================================================
  # ■ BaseItem
  #=============================================================================
  class BaseItem
    #-------------------------------------------------------------------------
    # ○ 读取rmvx备注栏指定字段
    #     section  : 字段名
    #     mismatch : 未匹配时的返回值
    #-------------------------------------------------------------------------
    def read_note(section, mismatch = nil)
      ReadNote.read(self.note, section, mismatch)
    end
  end
  #=============================================================================
  # ■ Enemy
  #=============================================================================
  class Enemy
    def read_note(section, mismatch = nil)
      ReadNote.read(self.note, section, mismatch)
    end
  end
  #=============================================================================
  # ■ State
  #=============================================================================
  class State
    def read_note(section, mismatch = nil)
      ReadNote.read(self.note, section, mismatch)
    end
  end
end