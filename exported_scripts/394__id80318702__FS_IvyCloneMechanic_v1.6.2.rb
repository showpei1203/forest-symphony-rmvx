# 【01. 補丁功能總覽】







#==============================================================================







#







# 本補丁完整包含：







#







#  1. 艾薇新版怒氣循環







#     ・戰鬥開始獲得怒氣







#     ・隊友受傷獲得怒氣







#     ・艾薇本人受傷額外獲得怒氣







#     ・主動護衛成功獲得較多怒氣







#







#  2. 艾薇主動護衛







#     ・不必指定單一隊友







#     ・自動攔截任何隊友受到的單體傷害







#     ・可設定護衛次數、持續行動數與減傷比例







#     ・被保護者不承受傷害與技能附加狀態







#     ・真正護衛者依自己的防禦重新計算傷害







#







#  3. 艾薇挑釁







#     ・提高自身被敵人選中的權重







#     ・提供可調整的自身減傷







#     ・護衛減傷與挑釁減傷只取較高值，不相乘







#







#  4. 安全護衛動畫







#     ・艾薇跳到被保護者前方







#     ・承受傷害並跳紅色傷害數字







#     ・敵方行動結束後跳回原位置







#     ・完全不使用 change_base_position







#     ・完全不依賴 Start Pos Return







#     ・只改 Sprite 畫面偏移，不改正式戰鬥座標







#     ・具備超時、死亡、場景結束與 Sprite 遺失復原







#







#  5. 五名人類映體







#     ・映體艾卓：簡化 ATB 干擾







#     ・映體艾薇：低血量緊急護衛







#     ・映體米亞：兩次攻擊後強化下一次治療







#     ・映體維娜：異常補判定與異常數量增傷







#     ・映體泰勒：裂甲與終結循環







#







#  6. 本尊／映體資源隔離







#     ・映體不會取得本尊 OD、Break、魔力層或個人堆疊







#     ・允許本尊與映體同時出場







#     ・Cover 一次最多轉移一次







#







#  7. 戰鬥機制文字圖片







#     ・護衛成功顯示「護衛！」







#     ・ATB 顯示實際變化百分比







#     ・可用 Note 自訂使用者或目標頭上的機制文字







#     ・沿用出招前短句相同的圖片顯示方式







#







#  8. v1.5 護衛顯示同步







#     ・武器 Sprite 跟隨艾薇跳入／跳回







#     ・傷害數字在護衛位置生成，不再留在原站位







#     ・雙武器 Sprite 也會一起跟隨







#     ・一般戰鬥中的武器與傷害數字不受影響







