  #--------------------------------------------------------------------------







  def self.start(target, guard, attacker, serial)







    return false unless ENABLED







    return false if target == nil || guard == nil















    # 同一行動、同一目標已經在護衛，只沿用，不重新起跳。







    if same_action_target?(serial, target)







      return true







    end















    # 不允許不同護衛工作階段互相覆蓋。







    force_cleanup if @session != nil && !@session[:done]















    guard_sprite = sprite_for(guard)







    target_sprite = sprite_for(target)







    attacker_sprite = sprite_for(attacker)















    unless valid_sprite?(guard_sprite) && valid_sprite?(target_sprite)







