  def self.perform_guard_damage(target, guard, kind, user, obj, reduce)







    old_covered = guard.instance_variable_get(:@covered)







    guard.instance_variable_set(:@covered, false)







    guard.instance_variable_set(:@albert_ic_internal_guard_damage, true)







    guard.instance_variable_set(:@albert_ic_skip_personal_reduce, true)















    begin







      if kind == :attack







        guard.make_attack_damage_value(user)







      else







        guard.make_obj_damage_value(user, obj)







      end







    ensure







      guard.instance_variable_set(:@covered, old_covered)







      guard.instance_variable_set(:@albert_ic_internal_guard_damage, false)







      guard.instance_variable_set(:@albert_ic_skip_personal_reduce, false)







    end















    raw_damage = hp_damage(guard)







    highest_reduce = [reduce.to_i, taunt_reduce(guard).to_i].max







    final_damage = (raw_damage.to_f * (100 - highest_reduce) / 100.0).round







    final_damage = 1 if raw_damage > 0 && final_damage < 1







    set_hp_damage(guard, final_damage)















    before_states = state_ids(guard)







    guard.instance_variable_set(:@albert_ic_cover_guard, true)







    guard.execute_damage(user)







    guard.instance_variable_set(:@albert_ic_cover_guard, false)















    if obj != nil && guard.respond_to?(:apply_state_changes)







      guard.apply_state_changes(obj)







      after_skill_effect(guard, user, obj, before_states)







    end







  end















  def self.try_redirect(target, user, obj, kind)







    return false if target == nil || user == nil







    return false unless target.respond_to?(:actor?) && target.actor?







    return false unless user.respond_to?(:actor?) && !user.actor?







    return false unless single_target_object?(obj)







    return false if hp_damage(target) <= 0







    return false if target.instance_variable_get(:@albert_ic_internal_guard_damage)















    serial = self.action_serial.to_i







    return false if (target.instance_variable_get(:@albert_ic_redirected_serial) || -1).to_i == serial















    pair = select_guard(target)







    guard = pair[0]







    guard_type = pair[1]







    return false if guard == nil















    target.instance_variable_set(:@albert_ic_redirected_serial, serial)







    target.instance_variable_set(:@albert_ic_guarded_skill_serial, serial)







    target.instance_variable_set(:@albert_ic_skip_state_serial, serial)







    set_hp_damage(target, 0)















    if guard_type == :main







      charges = (guard.instance_variable_get(:@albert_ic_guard_charges) || 0).to_i - 1







      guard.instance_variable_set(:@albert_ic_guard_charges, [charges, 0].max)







      reduce = (guard.instance_variable_get(:@albert_ic_guard_reduce) || 0).to_i







      gain_od_percent(guard, IVY_ACTIVE_COVER_OD_PERCENT)







      clear_guard(guard) if charges <= 0







    else







      guard.instance_variable_set(:@albert_ic_clone_guard_used, true)







      guard.instance_variable_set(:@albert_ic_clone_ivy_guarded, true)







      reduce = CLONE_IVY_GUARD_REDUCE







    end















    perform_guard_damage(target, guard, kind, user, obj, reduce)







    visual_cover(target, guard)







    log("Cover #{target.name} -> #{guard.name}") rescue nil







    return true







  end















