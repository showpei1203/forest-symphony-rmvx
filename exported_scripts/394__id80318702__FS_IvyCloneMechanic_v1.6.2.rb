    return unless effect_landed?(target)







    role = clone_role(user)







    return if role == nil















    if role == :vina







      text = source_text(user, skill)







      bonus = number(text, ["cvb", "clone_vina_state_bonus"], 0).to_i







      if bonus > 0 && skill.respond_to?(:plus_state_set)







        for state_id in skill.plus_state_set







          next if before_states.include?(state_id)







          next if target.state?(state_id)







          next unless state_can_be_added?(target, state_id)







          target.add_state(state_id) if rand(100) < bonus







        end







      end







    end















    if role == :tyler







      if note(skill) =~ /<\s*(?:ctc|clone_tyler_crack)\s*:\s*(\d+)\s*>/i







        target.add_state($1.to_i)







      end







      if note(skill) =~ /<\s*(?:ctf|clone_tyler_finisher)\s*:\s*(\d+)\s*,\s*(\d+)\s*>/i







        target.remove_state($1.to_i) if target.state?($1.to_i)







      end







    end







  end







