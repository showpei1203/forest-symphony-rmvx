    frame_count = Graphics.frame_count rescue s[:total_frames].to_i







    if s[:last_update_frame].to_i == frame_count.to_i







      return [s[:offset_x].to_f, s[:offset_y].to_f]







    end







    s[:last_update_frame] = frame_count.to_i







    s[:total_frames] = s[:total_frames].to_i + 1















    if s[:total_frames].to_i > WATCHDOG_FRAMES







      force_cleanup







      return [0.0, 0.0]







    end















    # 即使護衛傷害已致死，也要先完成跳入與紅字演出。







    # 正式站位從未改變，死亡後只需在適當時機清除臨時偏移。







    guard_still_exists = existing?(s[:guard])















    case s[:phase]







    when :move_in







      s[:phase_frame] = s[:phase_frame].to_i + 1







      t = s[:phase_frame].to_f / [MOVE_IN_FRAMES, 1].max







      eased = ease_out_quad(t)







      s[:offset_x] = s[:destination_dx].to_f * eased







      s[:offset_y] = s[:destination_dy].to_f * eased - jump_arc(t)















      if s[:phase_frame].to_i >= MOVE_IN_FRAMES







        s[:phase] = :hold







        s[:phase_frame] = 0







        s[:hold_frames] = 0







        s[:offset_x] = s[:destination_dx].to_f







        s[:offset_y] = s[:destination_dy].to_f







        show_cover_text(s)







        trigger_impact_action(s)







        emit_damage_if_ready(s)







      end















    when :hold







      s[:phase_frame] = s[:phase_frame].to_i + 1







      s[:hold_frames] = s[:hold_frames].to_i + 1







      s[:offset_x] = s[:destination_dx].to_f







      s[:offset_y] = s[:destination_dy].to_f







      emit_damage_if_ready(s)















      can_return = !action_still_running?(s[:serial])







      queue_empty = s[:damage_queue].empty?







      held_long_enough = s[:hold_frames].to_i >= MIN_HOLD_FRAMES







      if can_return && queue_empty && held_long_enough







        if guard_still_exists







          s[:phase] = :return







          s[:phase_frame] = 0







        else







          # 致死時不再演跳回，但立即清除偏移，避免死亡 Sprite 卡位。







          complete







          return [0.0, 0.0]







        end







      end















    when :return







      s[:phase_frame] = s[:phase_frame].to_i + 1







      t = s[:phase_frame].to_f / [RETURN_FRAMES, 1].max







      eased = ease_out_quad(t)







      factor = 1.0 - eased







      s[:offset_x] = s[:destination_dx].to_f * factor







      s[:offset_y] = s[:destination_dy].to_f * factor - jump_arc(t)















      if s[:phase_frame].to_i >= RETURN_FRAMES







        complete







        return [0.0, 0.0]







      end















    when :fallback







      show_cover_text(s)







      while !s[:damage_queue].empty?







        fallback_damage_pop(s[:guard], s[:damage_queue].shift)







      end







      complete







      return [0.0, 0.0]







    end















    s[:guard].instance_variable_set(







      :@albert_ic_cover_motion_offset_x, s[:offset_x].to_f







    )







    s[:guard].instance_variable_set(







      :@albert_ic_cover_motion_offset_y, s[:offset_y].to_f







    )







    return [s[:offset_x].to_f, s[:offset_y].to_f]







  end















  def self.complete







    s = @session







    return if s == nil















    guard = s[:guard]







    if guard != nil







      guard.instance_variable_set(:@albert_ic_cover_motion_busy, false)







      guard.instance_variable_set(:@albert_ic_cover_motion_offset_x, 0.0)







      guard.instance_variable_set(:@albert_ic_cover_motion_offset_y, 0.0)







    end















    s[:offset_x] = 0.0







    s[:offset_y] = 0.0







    s[:done] = true







  end















  def self.force_cleanup







    complete







    @session = nil







  end















  def self.clear_finished







    @session = nil if @session != nil && @session[:done]







  end















  #--------------------------------------------------------------------------







  # 行動結束後等待回位







  #--------------------------------------------------------------------------







  def self.finish_action_visual(scene, serial)







    s = session_for(serial)







    return if s == nil















    frames = 0







    while busy? && frames < WAIT_LIMIT_FRAMES







      begin







        scene.send(:wait, 1)







      rescue







        begin







          Graphics.update







          Input.update







          scene.send(:update_basic) if scene.respond_to?(:update_basic, true)







        rescue







          break







        end







      end







      frames += 1







    end















    force_cleanup if busy?







    clear_finished







  end







end















