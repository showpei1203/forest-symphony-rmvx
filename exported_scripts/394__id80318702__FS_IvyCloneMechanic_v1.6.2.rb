# ■ v1.5 傷害數字同步護衛位置







#------------------------------------------------------------------------------







# Sprite_Damage 原本直接使用 battler.position_x／position_y，







# 那是正式站位，不包含護衛動畫的臨時 Sprite 偏移。







#







# 本修正於 damage_pop 建立完數字後：







#   1. 將內部基準 @x／@y 移到護衛位置。







#   2. 將所有 @num1、@num2……傷害數字 Sprite 一次平移。







#   3. 若有文字 Window，也一起平移。







#







# 數字之後仍走原本 move_damage，不會每幀黏著艾薇。







# 這樣即使艾薇開始跳回，紅字仍會在實際受擊位置正常彈跳。







#==============================================================================







if defined?(Sprite_Damage)







  class Sprite_Damage







    unless method_defined?(:albert_ic_v15_position_old_damage_pop)







      alias albert_ic_v15_position_old_damage_pop damage_pop







    end















    def damage_pop(num = nil)







      result = albert_ic_v15_position_old_damage_pop(num)















      battler = @battler







      return result if battler == nil







      return result unless defined?(ALBERT_IVY_CLONE_COVER_MOTION)















      offset = ALBERT_IVY_CLONE_COVER_MOTION.display_offset(battler)







      ox = offset[0].to_i







      oy = offset[1].to_i







      return result if ox == 0 && oy == 0















      # 更新 Sprite_Damage 內部基準，供文字視窗後續 move_window 使用。







      @x = @x.to_i + ox if @x != nil







      @y = @y.to_i + oy if @y != nil















      # 不假設傷害位數。掃描 @num1、@num2……所有數字 Sprite。







      for ivar in instance_variables







        name = ivar.to_s







        next unless name =~ /^@num\d+$/















        sprite = instance_variable_get(ivar)







        next if sprite == nil







        begin







          next if sprite.disposed?







        rescue







        end







        next unless sprite.respond_to?(:x) && sprite.respond_to?(:x=)







        next unless sprite.respond_to?(:y) && sprite.respond_to?(:y=)















        sprite.x += ox







        sprite.y += oy







      end















      # 暴擊、狀態、無傷害等文字可能使用獨立 Window。







      if @window != nil







        window = instance_variable_get(:@window)







        if window != nil &&







           window.respond_to?(:x) && window.respond_to?(:x=) &&







           window.respond_to?(:y) && window.respond_to?(:y=)







          begin







            disposed = window.disposed?







          rescue







            disposed = false







          end







          unless disposed







            window.x += ox







            window.y += oy







          end







        end







      end















      return result







    end







  end







end















