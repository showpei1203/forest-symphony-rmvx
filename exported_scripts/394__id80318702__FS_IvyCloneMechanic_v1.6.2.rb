# 【07. 安全護衛動畫規則】







#==============================================================================







#







# 護衛成立時：







#







#   1. 艾薇從自己的正式位置跳出。







#   2. 落在「敵人與被保護者之間」。







#   3. 顯示「護衛！」。







#   4. 護衛者顯示真正承受的紅色傷害數字。







#   5. 同一敵方行動未結束前，艾薇留在護衛位置。







#   6. 敵方行動結束後，艾薇跳回原位置。







#   7. 回位完成後，下一個戰鬥行動才開始。







#







# 正式的 position_x／position_y 完全不會修改。







#







#------------------------------------------------------------------------------







# 7-1. 多段攻擊







#------------------------------------------------------------------------------







#







# 同一敵方行動連續攻擊同一名隊友：







#







#   ・艾薇只跳入一次







#   ・只消耗一次護衛次數







#   ・每段傷害都由艾薇承受







#   ・每段紅字依序顯示







#   ・技能結束後才返回







#







# 同一敵方行動攻擊不同隊友：







#







#   ・只保護該行動第一名被鎖定的隊友







#   ・其餘不同目標照正常結果處理







#   ・不會在一個技能內讓艾薇滿場瞬移







#







#------------------------------------------------------------------------------







# 7-2. 不可護衛的情況







#------------------------------------------------------------------------------







#







#   ・艾薇死亡或不存在







#   ・艾薇正在詠唱







#   ・艾薇處於不可行動狀態







#   ・艾薇已在另一個護衛工作階段







#   ・全體攻擊







#   ・治療或零傷害







#   ・攻擊者不是敵方







#   ・目標不是我方 Actor







