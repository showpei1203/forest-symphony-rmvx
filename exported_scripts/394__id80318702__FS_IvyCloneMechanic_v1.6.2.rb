      left -= 1







      user.instance_variable_set(:@albert_ic_taunt_actions_left, left)







      clear_taunt(user) if left <= 0







    end















    if clone_role?(user, :ivy)







      user.instance_variable_set(:@albert_ic_clone_guard_used, false)







      user.instance_variable_set(:@albert_ic_clone_ivy_guarded, false)







