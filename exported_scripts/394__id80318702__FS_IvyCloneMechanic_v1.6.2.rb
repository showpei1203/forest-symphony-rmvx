       text =~ /<\s*(?:cit|clone_ivy_taunt)\s*:\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*>/i







      activate_taunt(user, $1.to_i, $2.to_i, $3.to_i)







    end















    if text =~ /<\s*(?:io|ivy_od_percent)\s*:\s*(-?\d+(?:\.\d+)?)\s*>/i







      gain_od_percent(user, $1.to_f) if ivy?(user)







