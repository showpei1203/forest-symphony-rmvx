    destination_x = target_x + direction * FRONT_DISTANCE







    destination_y = target_y















    @session = {







      :serial => serial.to_i,







      :target => target,







      :guard => guard,







      :attacker => attacker,







      :guard_sprite => guard_sprite,







      :phase => :move_in,







      :phase_frame => 0,







      :total_frames => 0,







      :hold_frames => 0,







      :offset_x => 0.0,







      :offset_y => 0.0,







      :destination_dx => destination_x - guard_x,







      :destination_dy => destination_y - guard_y,







      :damage_queue => [],







      :next_damage_frame => 0,







      :cover_pop_shown => false,







      :impact_action_done => false,







      :done => false,







      :fallback => false,







