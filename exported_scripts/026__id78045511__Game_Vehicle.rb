# ** Game_Vehicle
#------------------------------------------------------------------------------
#  這個類用來操控交通工具，這個類作為 Game_Map 類的內部類使用。
#  如果當前地圖上沒有交通工具，則設置他們的地圖座標為（-1,-1）。
#==============================================================================

class Game_Vehicle < Game_Character
  #--------------------------------------------------------------------------
  # * 常數
  #--------------------------------------------------------------------------
  MAX_ALTITUDE = 32                       # 飛艇所在的高度
  #--------------------------------------------------------------------------
  # * 宣告執行個體變數
  #--------------------------------------------------------------------------
  attr_reader   :type                     # 交通工具類型（0..2）
  attr_reader   :altitude                 # 飛行高度（只針對飛艇）
  attr_reader   :driving                  # 判斷交通工具被控制的標幟
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     type : 交通工具類型（0：舟，1：船，2：飛艇）
  #--------------------------------------------------------------------------
  def initialize(type)
    super()
    @type = type
    @altitude = 0
    @driving = false
    @direction = 2
    @walk_anime = false
    @step_anime = false
    load_system_settings
  end
  #--------------------------------------------------------------------------
  # * 載入系統交通工具參數設置
  #--------------------------------------------------------------------------
  def load_system_settings
    case @type
    when 0
      sys_vehicle = $data_system.boat
    when 1
      sys_vehicle = $data_system.ship
    when 2
      sys_vehicle = $data_system.airship
    else
      sys_vehicle = nil
    end
    if sys_vehicle != nil
      @character_name = sys_vehicle.character_name
      @character_index = sys_vehicle.character_index
      @bgm = sys_vehicle.bgm
      @map_id = sys_vehicle.start_map_id
      @x = sys_vehicle.start_x
      @y = sys_vehicle.start_y
    end
  end
  #--------------------------------------------------------------------------
  # * 更新內容資訊
  #--------------------------------------------------------------------------
  def refresh
    if @driving
      @map_id = $game_map.map_id
      sync_with_player
    elsif @map_id == $game_map.map_id
      moveto(@x, @y)
    end
    case @type
    when 0
      @priority_type = 1
      @move_speed = 4
    when 1
      @priority_type = 1
      @move_speed = 5
    when 2
      @priority_type = @driving ? 2 : 0
      @move_speed = 6
    end
    @walk_anime = @driving
    @step_anime = @driving
  end
  #--------------------------------------------------------------------------
  # * 變更位置
  #     map_id : 地圖編號
  #     x      : 地圖X座標
  #     y      : 地圖Y座標
  #--------------------------------------------------------------------------
  def set_location(map_id, x, y)
    @map_id = map_id
    @x = x
    @y = y
    refresh
  end
  #--------------------------------------------------------------------------
  # * 判定座標是否匹配
  #     x : 地圖X座標
  #     y : 地圖Y座標
  #--------------------------------------------------------------------------
  def pos?(x, y)
    return (@map_id == $game_map.map_id and super(x, y))
  end
  #--------------------------------------------------------------------------
  # * 判定交通工具顯示透明度
  #--------------------------------------------------------------------------
  def transparent
    return (@map_id != $game_map.map_id or super)
  end
  #--------------------------------------------------------------------------
  # * 登上交通工具
  #--------------------------------------------------------------------------
  def get_on
    @driving = true
    @walk_anime = true
    @step_anime = true
    if @type == 2               # 空艇？
      @priority_type = 2        # 更改顯示優先順序為[在普通人物上方]
    end
    @bgm.play                   # 播放交通工具專屬BGM
  end
  #--------------------------------------------------------------------------
  # * 登下交通工具
  #--------------------------------------------------------------------------
  def get_off
    @driving = false
    @walk_anime = false
    @step_anime = false
    @direction = 4
  end
  #--------------------------------------------------------------------------
  # * 與玩家主角座標同步移動
  #--------------------------------------------------------------------------
  def sync_with_player
    @x = $game_player.x
    @y = $game_player.y
    @real_x = $game_player.real_x
    @real_y = $game_player.real_y
    @direction = $game_player.direction
    update_bush_depth
  end
  #--------------------------------------------------------------------------
  # * 獲取行駛速度
  #--------------------------------------------------------------------------
  def speed
    return @move_speed
  end
  #--------------------------------------------------------------------------
  # * 獲取螢幕Y座標差量
  #--------------------------------------------------------------------------
  def screen_y
    return super - altitude
  end
  #--------------------------------------------------------------------------
  # * 通行度判定
  #--------------------------------------------------------------------------
  def movable?
    return false if (@type == 2 and @altitude < MAX_ALTITUDE)
    return (not moving?)
  end
  #--------------------------------------------------------------------------
  # * 更新幀
  #--------------------------------------------------------------------------
  def update
    super
    if @type == 2               # 空艇？
      if @driving
        if @altitude < MAX_ALTITUDE
          @altitude += 1        # 高度增加
        end
      elsif @altitude > 0
        @altitude -= 1          # 高度降低
        if @altitude == 0
          @priority_type = 0    # 恢復顯示優先順序為[在普通人物下方]
        end
      end
    end
  end
end
