# ■ [VX] 窗口滑动
#    [VX] WindowSlide
#----------------------------------------------------------------------------
#    使用说明:
#    创建窗口之后，可以使用调整窗口的座标，并且将窗口滑动到指定位置。
#    可用于制作华丽菜单显示效果
#    * 窗口.in(方向[, 移动距离])
#       方向可以为 2(下), 4(左), 6(右), 8(上)
#       移动距离默认为 10
#       将窗口滑动至画面外。
#
#    * 窗口.out(方向[, 移动距离])
#       方向可以为 2(下), 4(左), 6(右), 8(上)
#       移动距离默认为 10
#       将窗口由画面外滑动至原位。
#
#    * 窗口.move_to(目标 X 座标, 目标 Y 座标[, 移动距离])
#       移动距离默认为 10
#       将窗口滑动至指定座标。
#
