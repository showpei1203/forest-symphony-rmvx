class Scene_Base
  #--------------------------------------------------------------------------
  # * 主程式
  #--------------------------------------------------------------------------
  def main
    start                         # 程式開始
    perform_transition            # 執行畫面過渡顯示漸變
    post_start                    # 程式開始後的處理
    Input.update                  # 更新指令輸入資訊
    loop do
      Graphics.update             # 更新螢幕內容
      Input.update                # 更新指令輸入資訊
      update                      # 更新幀
      break if $scene != self     # 當畫面切換的時候，中止一切迴圈處理
    end
    Graphics.update
    pre_terminate                 # 程式終止前的處理
    Graphics.freeze               # 執行畫面過渡顯示漸變
    terminate                     # 程式終止
  end
  #--------------------------------------------------------------------------
  # * 程式開始
  #--------------------------------------------------------------------------
