# 3. 解決 KGC 與 DPS 統計的順序衝突
class Game_Battler
  alias zyy_kgc_dps_fix execute_damage
  def execute_damage(user)
    zyy_kgc_dps_fix(user)
    # 確保 KGC 計算後的真實傷害被記錄
    if $scene.is_a?(Scene_Battle) && @hp_damage > 0
      user.total_damage += @hp_damage if user.respond_to?(:total_damage)
    end
  end
end