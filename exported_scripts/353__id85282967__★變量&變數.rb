# 　处理变量的类。编入的是类 Array 的外壳。本类的实例请参考 $game_variables。
#==============================================================================

class Game_Variables
  #--------------------------------------------------------------------------
  # ● 初始化对像
  #--------------------------------------------------------------------------
  def initialize
    @data = []
  end
  #--------------------------------------------------------------------------
  # ● 获取变量
  #     variable_id : 变量 ID
  #--------------------------------------------------------------------------
  def [](variable_id)
    name = $data_system.variables[variable_id] #获取名称
    if (name || '').include? "#"#如果含有#
      s = name.split("#")[1]
      begin
        n = eval(s)
        return n
      rescue
        p s+" 这个变量产生错误!"
      end
    else
      if @data[variable_id] == nil
        return 0
      else
        return @data[variable_id]
      end
    end
 
  end
  #--------------------------------------------------------------------------
  # ● 设置变量
  #     variable_id : 变量 ID
  #     value       : 变量的值
  #--------------------------------------------------------------------------
  def []=(variable_id, value)
    name = $data_system.variables[variable_id] #获取名称
    if (name || '').include? "#"#如果含有#
      s = name.split("#")[1]
      begin
       s = s + "= #{value}" #生成新的语句
       eval(s) #执行语句
       
      rescue #如果出错
        p s+" 这个变量产生错误!"#产生提示信息
      end
    else
      if variable_id <= 5000  #原有数据方法
        @data[variable_id] = value
      end
    end
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
  end
end