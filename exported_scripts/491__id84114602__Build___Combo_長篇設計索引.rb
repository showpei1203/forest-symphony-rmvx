#  六名主要角色 + 三名召喚物之 Build / Combo 長篇設計索引
#-------------------------------------------------------------------------------
# 【用途】
#  這是一頁純註釋，可直接放進 RPG Maker VX 腳本庫。
#  用來統一目前已經討論、已經腳本化、以及正式推薦採用的 Build / Combo。
#
# 【目前戰鬥基本編制】
#    ・3 名主要人類角色上場
#    ・最多 3 名召喚物上場
#    ・敵方最多 8 名
#    ・等級上限規劃 Lv60
#    ・召喚物槽位隨劇情：1 → 2 → 3
#
# 【整套系統的核心哲學】
#
#    人類角色：做決策、選時機、主動引爆。
#    召喚物：建立條件、維持循環、改變戰場規則。
#
#    Pokémon：製造變數。
#    Robot  ：提供規律。
#    Clone  ：精準決策。
#
#  最成熟的 Build 應該包含：
#
#    1. 主條件：毒、濕潤、麻痺、破勢、怒氣、魔力層等。
#    2. 引擎：誰穩定產生這個條件。
#    3. 加工：誰把條件變得更值錢。
#    4. 爆發：誰決定收割。
#    5. 保底：Build 失敗或 Boss 抗性升高時，隊伍怎麼活。
#
#  最重要原則：
#    Build 應該改變玩家的操作順序，而不只是「同樣按招但數字多 30%」。
