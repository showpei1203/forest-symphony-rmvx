#===============================================================================
# 第一部　核心戰鬥語言
#===============================================================================
#
# 建議把全遊戲主要 Combo State 控制在約 8～12 個核心語彙，避免資料庫最後
# 變成「30 種顏色不同但實際都只是增傷」的狀態博物館。
#
# 【1. 中毒】
#  用途：疊層、DOT、引爆、擴散、飄移、AI 判斷。
#  典型 Note：
#    <detonate_state 31:150>
#    <detonate_state_percent 31:2>
#    <spread_state 31:2>
#    <drift_state 31:1>
#    <ai_prefer_stack_below 31:5>
#
# 【2. 濕潤】
#  用途：雷屬性、麻痺、ATB 削減放大器。
#  典型 Note：
#    <atb_bonus_vs_state 32:50>
#
# 【3. 麻痺】
#  用途：硬控／軟控、ATB 強化條件。
#  Boss 建議套用動態異常抗性，避免永久關機。
#
# 【4. 灼燒】
#  用途：DOT、降攻、轉成脆弱或爆發前置。
#
# 【5. 寄生】
#  用途：吸血、長期戰、腐敗森林型 Build。
#
# 【6. 腐蝕】
#  用途：降 DEF／RES、毒素加工、提高毒爆價值。
#
# 【7. 破勢】
#  用途：泰勒的 Break 進度。
#  預設 State ID 50。
#
# 【8. 崩防】
#  用途：全隊爆發窗口。
#  預設 State ID 51。
#
# 【9. 遲緩】
#  用途：ATB 速度下降、艾卓時間控制。
#
# 【10. 共鳴標記】
#  用途：喬伊與召喚物連結、追擊條件。
#
# 【11. 護盾 / Mana Shield】
#  用途：米亞與 Robot 防守引擎。
#
# 【12. 脆弱】
#  用途：泛用爆發窗口，但不要讓它取代所有專屬 Combo。
#

#===============================================================================
# 第二部　前中後期 Build 成長節奏
#===============================================================================
#
#------------------------------------------------------------------------------
# 【Lv1～10：一個條件 → 一個結果】
#------------------------------------------------------------------------------
#  召喚物槽：1
#
#  目的：讓玩家先理解最小因果。
#
#  範例：
#    毒系 Pokémon 上毒
#      → 維娜攻擊中毒目標更強
#
#    水系 Pokémon 上濕潤
#      → 艾卓 ATB 削減增加
#
#    Break Pokémon 上破勢
#      → 泰勒更快打進崩防
#
#  前期不要同時要求玩家記：毒 ×5、腐蝕、濕潤、麻痺、Break、OD、追擊。
#  教學不是把所有功能丟到玩家臉上，然後怪他沒讀懂。
#
#------------------------------------------------------------------------------
# 【Lv11～15：同一角色開始出現分支】
#------------------------------------------------------------------------------
#  範例：維娜
#    A. 毒爆型：快速疊毒 → 引爆。
#    B. 毒控型：毒層提高其他異常成功率 → 擴散／遲緩／虛弱。
#
#  範例：艾薇
#    A. 堡壘型：保留高 OD，持續減傷。
#    B. 復仇型：Cover 蓄痛 → 爆發技能。
#
#------------------------------------------------------------------------------
# 【Lv16～25：第二召喚物槽，真正 Build 成立】
#------------------------------------------------------------------------------
#  結構：
#    起奏者 → 和聲者
#
#  例：
#    水 Pokémon：上濕潤
#    電 Robot：每第 3 次行動執行電擊協議
#      → 艾卓取得更好的 ATB 打斷窗口
#
#  這時玩家第一次開始思考：
#    「我帶誰，不只是多一個輸出，而是在改變我的主角技能價值。」
#
#------------------------------------------------------------------------------
# 【Lv26～35：循環、疊層、轉換、OD】
#------------------------------------------------------------------------------
#  玩家開始學會三種 Build：
#
#  A. 累積型
#     毒×1 → ×2 → ×3 → ×4 → ×5 → 引爆
#
#  B. 循環型
#     艾卓削 ATB → 得 OD → 高 OD 削更多 ATB
#
#  C. 轉換型
#     米亞治療 → 溢療 → 魔力層 → 法術爆發
#
#------------------------------------------------------------------------------
# 【Lv36～45：第三召喚物槽，三段引擎】
#------------------------------------------------------------------------------
#  完整結構：
#
#    召喚物 A：建立條件
#    召喚物 B：加工條件
#    召喚物 C：維持／引爆／救場
#
#    人類 1：主導 Build
#    人類 2：補上節奏／Break／狀態
#    人類 3：防守或爆發
#
#------------------------------------------------------------------------------
# 【Lv46～55：交叉 Build】
#------------------------------------------------------------------------------
#  開始讓兩名人類的專屬系統互相串接：
#
#    泰勒崩防 → 喬伊召喚鏈 → Robot 終結
#    維娜毒層 → 艾卓高 ATB 打斷 → 毒 AI 繼續加工
#    米亞溢療 → Mana Shield → 艾薇更放心 Cover
#
#------------------------------------------------------------------------------
# 【Lv56～60：Boss 迫使玩家換 Build】
#------------------------------------------------------------------------------
#  Boss 不應該全部只是 HP 更多。
#
#  例：
#    ・毒抗高但 Break 弱
#    ・Break 門檻高但 ATB 慢
#    ・控制會累積動態抗性
#    ・每次被同種引爆後，抗性提高
#    ・召喚小怪逼維娜做擴散
#
#  後期真正的問題應該是：
#    「我要維持引擎，還是現在提前收割？」
#

