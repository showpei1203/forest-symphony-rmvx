# 但一被觀律就完全不能玩，
# 它不是後期成熟Build。
#
# 它只是對木樁非常有自信。

# 第七部　平衡規則
#===============================================================================
#
#  1. 每個 Build 最好只有一個主條件。
#     毒 Build 可以有腐蝕輔助，但不要再同時把濕潤、火、Break、寄生全部
#     當主角。
#
#  2. 每個 Build 最好只有一個主要爆發點。
#     準備 → 爆發 → 重建，比每回合都在爆發更有節奏。
#
#  3. ATB 控制一定要有 Boss 遞減抗性。
#
#  4. 硬控一定要有動態異常抗性。
#
#  5. Break 要由 Enemy 自己決定門檻／抗性／回復。
#
#  6. 召喚追擊要限制每回合／每鏈次數與 OD。
#
#  7. Robot 的穩定必須用協議週期或冷卻換來。
#
#  8. Pokémon 的高自由度要接受 AI 不完全精準。
#
#  9. Clone 若未來正式加入穩定度，精準控制必須付有限資源代價。
#
# 10. 固定傷害爆發要避免前期太強、後期變紙團。
#     可混用固定值 + SPI/ATK 成長 + Boss cap。
#
# 11. 不要讓所有 Boss 都免疫玩家核心機制。
#     最糟糕的難度設計，是花兩百小時做系統，然後 Boss 寫「全部無效」。
#
# 12. 後期 Boss 的挑戰應該是迫使玩家調整隊伍，而不是單純 HP 乘十。
#
#===============================================================================
# 最終一句話
#===============================================================================
#
#  人類決定戰術，刻印決定 Build，召喚物創造戰場條件。
#
#  玩家真正要玩的，不是「六個角色各自按最痛的招」，而是：
#
#    我現在要建立條件？
#    維持引擎？
#    把資源留到下一波？
#    還是就在這一刻引爆？
#
#  當這四個問題都可能有不同答案時，Build 系統才真正活起來。
