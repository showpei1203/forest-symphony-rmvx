#------------------------------------------------------------------------------
# 【Pokémon】製造變數
#------------------------------------------------------------------------------
#  特徵：
#    ・AI 自動行動
#    ・屬性／狀態／成長／進化
#    ・容易建立 Combo 條件
#    ・精準度較低
#
