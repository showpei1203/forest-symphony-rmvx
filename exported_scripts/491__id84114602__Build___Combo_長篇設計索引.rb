#    <ai_bonus_vs_state 31:100>
#    <ai_require_state:31>
#    <ai_prefer_stack_below 31:5>
#
#  典型定位：
#    poison_starter
#    wet_starter
#    breaker
#    parasite_engine
#    fast_resonance
#
#  建議技能數：1～3 招，不要讓 AI 同時面對 12 個情境技能。
#
#------------------------------------------------------------------------------
# 【Robot】提供規律
#------------------------------------------------------------------------------
#  特徵：
#    ・固定節奏
#    ・可預測
#    ・適合做 Build 核心
#    ・變化少，但穩定
#
#  Protocol：
#    <robot_protocol_skill:241>
#    <robot_protocol_interval:3>
#    <robot_protocol_if_state 31:241>
#
#  例：
#    第 1 次行動：一般 AI
#    第 2 次行動：一般 AI
#    第 3 次行動：協議
#      若敵人有 State 31 → Skill 241
#      否則 → 預設協議技能
#
#  典型定位：
#    corrosion_engine
#    atb_controller
#    shield_protocol
#    break_protocol
#    burst_cannon
#
#------------------------------------------------------------------------------
# 【Clone】精準決策
#------------------------------------------------------------------------------
#  特徵：
#    ・玩家手動控制
#    ・精準指定目標
#    ・精準引爆／救場／收割
#
#  目前專案已完成分類層與喬伊 chain type / role 選擇。
#  專屬「穩定度」資源尚未正式腳本化，因此設計時暫時不要假裝它已完成。
#
#  推薦最終方向：
#    Pokémon 免費但不精準。
#    Robot 固定但不靈活。
#    Clone 精準但每場可用資源有限。
#

