#===============================================================================
# # 第六-A部　AntagonistMechanicCore 導入後的 Build 適應層
# #-------------------------------------------------------------------------------
#
# 新反派核心改變了後期Build的評價標準。
#
# 以前成熟Build只需要：
#
#   1. 主條件
#   2. 引擎
#   3. 爆發點
#   4. 防守保底
#
# 現在後期Build還要有第5項：
#
#   5. 適應層
#
# 也就是：
#
#   當Boss懲罰你原本最有效率的做法時，
#   這套Build要怎麼不崩？
#
# ===============================================================================
# 【一、觀律適應】
# ===============================================================================
#
# 受到影響：
#   ・重複同技能
#   ・重複同屬性
#   ・兩者同時重複
#
# 反制方式：
#
# A. 技能輪替
#
# 例如艾卓：
#
#   截流
#   → 雷鎖
#   → 時間斷層
#   → 召喚物接棒
#   → 再回截流
#
# 而不是：
#
#   截流
#   → 截流
#   → 截流
#   → 截流
#
# B. 屬性輪替
#
# 同一Build內至少準備：
#   主屬性
#   次屬性
#   無屬性／功能技
#
# C. 角色輪替
#
# 把「一名角色跑完整引擎」改成：
#
#   Actor A建立
#   → Summon加工
#   → Actor B利用
#   → Actor C爆發
#
# D. 召喚物緩衝
#
# 因：
#   <observe_main_actors_only>
#
# 召喚物可以插入節奏，
# 避免Actor 1～6連續重複。
#
# ===============================================================================
# 【二、雙弦適應】
# ===============================================================================
#
# 最強反制：
#
#   米亞 Mana Shield。
#
# 因為雙弦看：
#   實際 HP 損失。
#
# 盾先吸收，
# 實際HP損失下降，
# 連帶傷害也下降。
#
# 次要反制：
#
#   ・單體大治療
#   ・快速解除121
#   ・避免兩名連結角色同時低HP
#
# 艾薇特殊情況：
#
#   Cover可能救一人，
#   但若艾薇本身被雙弦，
#   大量承傷可能把另一人一起拖下水。
#
# 所以艾薇在雙弦戰不是「自動按Cover」，
# 而是高價值決策。
#
# ===============================================================================
# 【三、改譜適應】
# ===============================================================================
#
# 改譜意味：
#
#   Boss不是上同一個Debuff，
#   而是針對六名主角套不同State。
#
# Build必須保留：
#
#   ・解除State來源
#   ・召喚物補位
#   ・不只一名角色能完成關鍵功能
#
# 例如：
#
#   維娜被改譜
#   → 毒Build不能直接停擺
#   → 毒系Pokémon先維持疊層
#
# 泰勒被改譜
#   → Break機器人先維持Break壓力
#
# 米亞被改譜
#   → 治療Clone／治療Pokémon救場
#
# 這讓召喚物真正成為「備援功能」，
# 而不是三個額外傷害來源。
#
# ===============================================================================
# 【四、大諧律適應】
# ===============================================================================
#
# 大諧律每2次Boss有效行動輪替：
#
#   140
#   → 141
#   → 142
#   → 143
#
# Build必須問：
#
#   哪一律適合累積？
#   哪一律適合爆發？
#   哪一律應該防守？
#   哪一律應該先解除State？
#
# 推薦：
#
# 140 觀測律
#   避免重複。
#   用召喚物與不同技能輪替。
#
# 141 鎮壓律
#   準備Mana Shield。
#   留意ATB與雙弦。
#
# 142 改譜律
#   保留解除／備援角色。
#
# 143 歸一律
#   預先補血、護盾、防禦。
#   不要貪最後一刀。
#
