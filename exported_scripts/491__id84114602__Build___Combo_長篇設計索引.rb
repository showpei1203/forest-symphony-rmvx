#------------------------------------------------------------------------------
# Build 01：雷雨鎖鏈
#------------------------------------------------------------------------------
#  人類：艾卓 + 維娜 + 米亞
#  召喚：水 Pokémon + 電 Robot + 控制 Clone
#
#  流程：
#    水 Pokémon → 濕潤
#    電 Robot → 協議電擊
#    艾卓 → 高幅 ATB 削減
#    維娜 → 擴散濕潤／麻痺
#    Clone → 精準打斷 Boss
#
#  優勢：節奏控制、Boss 截擊。
#  弱點：對 ATB 抗性高、異常抗性高的敵人輸出可能不足。
#
#------------------------------------------------------------------------------
# Build 02：時間監獄
#------------------------------------------------------------------------------
#  人類：艾卓 + 維娜 + 喬伊
#  召喚：濕潤 Pokémon + ATB Robot + 控制 Clone
#
#  流程：
#    濕潤 → 麻痺／遲緩 → 艾卓等待高 ATB 門檻 → 成功打斷
#    → 喬伊追擊延長壓制。
#
#  Boss 必須用動態 ATB 抗性與異常抗性，避免永久關機。
#
#------------------------------------------------------------------------------
# Build 03：腐敗森林
#------------------------------------------------------------------------------
#  人類：維娜 + 喬伊 + 米亞
#  召喚：毒 Pokémon + 寄生 Pokémon + 腐蝕 Robot
#
#  流程：
#    毒 → 寄生 → 腐蝕 → 毒層增加 → 維娜擴散／引爆
#    → 喬伊用 poison_starter / corrosion_engine role 追擊。
