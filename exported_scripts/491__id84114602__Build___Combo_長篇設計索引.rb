#------------------------------------------------------------------------------
# 【喬伊】共鳴／召喚連結／召喚追擊
#------------------------------------------------------------------------------
#  玩家思考：現在場上的召喚物，誰最適合接下一棒？
#
#  核心循環：
#    召喚物正常行動
#      → 喬伊獲 OD
#      → 喬伊技能命中
#      → 指定類型／角色功能自動挑追擊者
#      → 追擊！
#
#  固定 Actor 追擊：
#    <summon_followup 18:241:700:200>
#
#  類型自動追擊：
#    <summon_followup_type pokemon:241:700:200>
#
#  功能角色自動追擊：
#    Actor / Equipment / State：
#      <summon_role:poison_starter>
#
#    Joey Skill：
#      <summon_followup_role poison_starter:241:700:200>
#
#  後期三段鏈：
#    <summon_chain_type 1:pokemon:241:700:0>
#    <summon_chain_type 2:robot:250:700:100>
#    <summon_chain_type 3:clone:260:900:300>
#
#  可加條件：
#    <chain_require 2:state:31>
#    <chain_require 2:stack_up:31>
#    <chain_require 3:broken>
#    <chain_require 3:hp_below:30>
#
#  喬伊 Build A：高速共鳴
#    高速 Pokémon 頻繁行動 → 快速累積 OD → 頻繁召喚追擊。
#
#  喬伊 Build B：條件連鎖
#    Pokémon 上狀態 → Robot 加工 → Clone 終結。
#
#  喬伊 Build C：Boss 收割
#    泰勒先崩防 → 喬伊技能 → 三段召喚鏈。
#
#  平衡原則：
#    ・同一召喚物一條鏈最多追擊一次。
#    ・追擊要有 OD 門檻／消耗／每回合限制。
#    ・追擊不可反過來無限產生正常召喚物行動 OD。
#

#------------------------------------------------------------------------------
# 【艾薇】怒氣坦傷／Cover／蓄痛復仇
#------------------------------------------------------------------------------
#  玩家思考：繼續累積承傷，還是現在復仇？
#
#  核心循環：
#    Cover 承傷
#      → 獲得 OD（怒氣）
#      → 高 OD 增傷／減傷
#      → 同時累積蓄痛
#      → 復仇爆發
#
#  OD：
#    <cc_od_cover:60>
#    <reduce_damage_if_od 50:20>
#    <reduce_damage_per_od_percent:0.2>
#    <bonus_if_od 50:30>
#
#  蓄痛：
#    <store_cover_damage:150>
#    <cover_store_cap_percent:300>
#
#  復仇技能：
#    <revenge_from_cover:50>
#    <consume_stored_cover>
#
#  Build A：堡壘型
#    保留高 OD → 減傷 → 持續 Cover → 米亞補血／護盾。
#
#  Build B：復仇型
#    故意替隊友扛 Boss 大招 → 蓄痛 → 終結技。
#
#  Build C：救場型
#    高怒氣保留減傷，但在危急時消耗 OD 放全體防護技能。
#
#  重要決策：
#    高 OD 是「持有就有價值」；技能消耗 OD 是「現在立刻救場」。
#    蓄痛則是另一種歷史資源，不要和 OD 混成同一件事。
#

#------------------------------------------------------------------------------
# 【艾卓】電荷／ATB 控制／打斷
#------------------------------------------------------------------------------
#  玩家思考：什麼時候出手才最值錢？
#
#  基本 ATB：
#    <atb_shift:-25>
#
#  條件放大：
#    <atb_bonus_vs_state 32:50>         # 濕潤
#    <atb_bonus_vs_state 33:70>         # 麻痺
#    <atb_bonus_per_target_state:10>
#    <atb_bonus_if_od 50:50>
#
#  目標 ATB 高時特別強：
#    <atb_bonus_if_target_atb_above 80:50>
#    <bonus_if_target_atb_above 80:30>
#
#  成功打斷：
#    <atb_interrupt_threshold:80>
#    <atb_interrupt_od:100>
#
#  Build A：雷雨鎖鏈
#    濕潤 → Robot 電擊 → 艾卓高幅 ATB 削減。
#
#  Build B：截擊型
#    等 Boss ATB 80% 以上才出手 → 高額削減 → 成功打斷獎勵 OD。
#
#  Build C：時間監獄
#    維娜麻痺／遲緩 + 艾卓削 ATB + 控制型召喚物。
#
#  Boss 平衡：
#    使用 <atb_dynamic_resist>，每次削減逐步提高抗性；Boss 行動後恢復。
#

