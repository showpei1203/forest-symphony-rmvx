# ■ エネミー行動パターン行動条件追加：対象のポジション・モジュール
#==============================================================================
module EacAdd_Effective_Rank

 # カスタマイズ項目------------------------------------------------------------
  
  TOP_SWITCH = 136
       #↑# 「行動条件追加：対象への有効度」に使用するスイッチ郡の、
          # 最初の番号をここで指定します。
          # 「エネミー行動パターン改良」の元もとのスイッチ郡と
          # つなげる必要はありません。
          # ゲーム中の判定に差し支えない番号にしてください。
          
  SETTING = [2, 3]
       #↑# 有効度を元にした行動条件をここで設定してください。
          # 行動条件の設定数は任意です。 , (半角カンマ)で区切ってください。
          #          
          # ここで指定するのは属性有効度およびステート有効度に対応した数字です。
          #  1 = 有効度Ａ / 2 = 有効度Ｂ / 3 = 有効度Ｃ
          #  4 = 有効度Ｄ / 5 = 有効度Ｅ / 6 = 有効度Ｆ
          # と、対応しています。
          #
          # ここで指定した有効度より対象の設定有効度が大きい場合、
          # 狙う対象から外します。(つまり有効な対象のみが残ります)
          # 例えば 2 と設定すれば、有効度Ｃ～Ｆの者は対象から外され、
          # 有効度Ａ、有効度Ｂの者のみを狙う対象とします。
          # 
          # 属性有効度やステート有効度が複数設定されている場合、
          # それら個別に判定し、相応しくない対象を外していきます。
          # つまり、より有効である対象のみが残ります。
          #
          # 条件を満たす対象がいれば行動条件を満たし、それを狙います。
          # 対象がいなければ行動条件を満たさず、その行動も選ばれません。
          #
          # この行動条件はスキル専用です。
          # スキル以外の行動の条件とすると、一律、条件を満たす扱いになります。
          
=begin

　SETTINGで設定した順番に対応させ、
  TOP_SWITCHから順番に設定数と同じ数のスイッチを用意してください。
  例をあげて説明しますと…

　TOP_SWITCH = 16
　SETTING = [1, 3]
　と設定したのであれば、
　スイッチ16が「有効度Ａ」を対象とする行動条件、
　スイッチ17が「有効度Ａ～Ｃ」を対象とする行動条件
　となります。

　スイッチの名前は任意でかまいません。製作中にわかりやすい名前にしてください。
    
=end         
 # ------------------------------------------------(カスタマイズ項目ここまで)--
 
  SWITCHES_RANGE = TOP_SWITCH...(TOP_SWITCH + SETTING.size)
  
 # ----------------------------------------------------------------------------
end

