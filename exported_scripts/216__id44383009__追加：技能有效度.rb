# ■ Game_Temp
#------------------------------------------------------------------------------
# 　セーブデータに含まれない、一時的なデータを扱うクラスです。このクラスのイン
# スタンスは $game_temp で参照されます。
#==============================================================================

class Game_Temp
  #--------------------------------------------------------------------------
  # ◎ 拡張行動条件に使用するスイッチデータの作成
  #--------------------------------------------------------------------------
  alias tig_eac_er_make_ex_conditions_switches make_ex_conditions_switches
  def make_ex_conditions_switches
    switches = Array.new(EacAdd_Effective_Rank::SETTING.size){|i|i+EacAdd_Effective_Rank::TOP_SWITCH}
    return tig_eac_er_make_ex_conditions_switches + switches
  end
end

#==============================================================================
# ■ Game_Battler
#------------------------------------------------------------------------------
# 　バトラーを扱うクラスです。このクラスは Game_Actor クラスと Game_Enemy クラ
# スのスーパークラスとして使用されます。
#==============================================================================

class Game_Battler
  #--------------------------------------------------------------------------
  # ○ 属性有効度の取得
  #  ※ デフォルトシステムに準じたの有効度取得方法です。
  #     取得方法に変更がある場合、ここを改変します。
  #--------------------------------------------------------------------------
  def element_ranks(element_id)
    if actor?
      rank = self.class.element_ranks[element_id]
    else
      rank = enemy.element_ranks[element_id]
    end
    return rank
  end
  #--------------------------------------------------------------------------
  # ○ ステート有効度の取得
  #  ※ デフォルトシステムに準じたの有効度取得方法です。
  #     取得方法に変更がある場合、ここを改変します。
  #--------------------------------------------------------------------------
  def state_ranks(state_id)
    if actor?
      rank = self.class.state_ranks[state_id]
    else
      rank = enemy.state_ranks[state_id]
    end
    return rank
  end
end

#==============================================================================
# ■ Game_BattleAction
#------------------------------------------------------------------------------
# 　戦闘行動を扱うクラスです。このクラスは Game_Battler クラスの内部で使用され
# ます。
#==============================================================================

class Game_BattleAction
  #--------------------------------------------------------------------------
  # ◎ 条件にあうターゲットグループの取得
  #--------------------------------------------------------------------------
  alias tig_eac_er_conditions_targets conditions_targets
  def conditions_targets(arrays, skill)
    targets = tig_eac_er_conditions_targets(arrays, skill)
    return targets if skill == nil
    for array in arrays ; next if array[0] != 6
      if EacAdd_Effective_Rank::SWITCHES_RANGE.include?(array[1])
        new_targets = []
        index = array[1] - EacAdd_Effective_Rank::TOP_SWITCH
        if EacAdd_Effective_Rank::SETTING[index].is_a?(Array)
          element_e_rank = EacAdd_Effective_Rank::SETTING[index][0]
          state_e_rank = EacAdd_Effective_Rank::SETTING[index][1]
        else
          element_e_rank = EacAdd_Effective_Rank::SETTING[index]
          state_e_rank = EacAdd_Effective_Rank::SETTING[index]
        end
        for target in targets
          next if skill.element_set.any?{|id|target.element_ranks(id) > element_e_rank}
          next if skill.plus_state_set.any?{|id| target.state_ranks(id) > state_e_rank }
          new_targets.push(target)
        end
        targets = new_targets
      end
    end
    return targets
  end
end