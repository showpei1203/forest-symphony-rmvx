class Game_System
  #--------------------------------------------------------------------------
  # * 宣告執行個體變數
  #--------------------------------------------------------------------------
  attr_accessor :timer                 # 計時器
  attr_accessor :timer_working         # 用來判斷計時器是否工作的標幟
  attr_accessor :save_disabled         # 用來判斷是否禁止保存進度的標幟
  attr_accessor :menu_disabled         # 用來判斷是否禁用ESC選單的標幟
  attr_accessor :encounter_disabled    # 用來判斷是否禁用地雷遇敵模式的標幟
  attr_accessor :save_count            # 進度檔位元編號
  attr_accessor :version_id            # 遊戲版本號
  #--------------------------------------------------------------------------
  # * 物件初始化
  #--------------------------------------------------------------------------
  def initialize
    @timer = 0
    @timer_working = false
    @save_disabled = false
    @menu_disabled = false
    @encounter_disabled = false
    @save_count = 0
    @version_id = 0
  end
  #--------------------------------------------------------------------------
  # * 獲取作戰BGM資訊
  #--------------------------------------------------------------------------
  def battle_bgm
    if @battle_bgm == nil
      return $data_system.battle_bgm
    else
      return @battle_bgm
    end
  end
  #--------------------------------------------------------------------------
  # * 設置作戰BGM
  #     battle_bgm : 新的作戰BGM
  #--------------------------------------------------------------------------
  def battle_bgm=(battle_bgm)
    @battle_bgm = battle_bgm
  end
  #--------------------------------------------------------------------------
  # * 獲取作戰結束ME資訊
  #--------------------------------------------------------------------------
  def battle_end_me
    if @battle_end_me == nil
      return $data_system.battle_end_me
    else
      return @battle_end_me
    end
  end
  #--------------------------------------------------------------------------
  # * 設置作戰結束ME
  #     battle_end_me : 新的作戰結束ME
  #--------------------------------------------------------------------------
  def battle_end_me=(battle_end_me)
    @battle_end_me = battle_end_me
  end
  #--------------------------------------------------------------------------
  # * 更新幀
  #--------------------------------------------------------------------------
  def update
    if @timer_working and @timer > 0
      @timer -= 1
      if @timer == 0 and $game_temp.in_battle     # 如果作戰時計時器值為0
        $game_temp.next_scene = "map"             # 中止作戰，返回地圖場景
      end
    end
  end
end
