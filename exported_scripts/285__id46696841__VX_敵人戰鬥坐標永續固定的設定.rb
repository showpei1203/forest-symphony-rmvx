#------------------------------------------------- -------------------------
# ● 敵人的Y坐標改變。
# 順序排列依次：敵人成員一，敵人成員二，敵人成員三等等。
# 擴展請自己添加數組。
#------------------------------------------------- -------------------------
  ENEMY_Y = [130,160,200,230,155,190,220]
#------------------------------------------------- -------------------------
# ● 改變敵人位置的坐標開關
# 設置開關編號。遊戲中用開關控制是否打開功能。
#------------------------------------------------- -------------------------
  ENEMY_XY_SWITCH = 1
end
#================================================= =============================
# ■ Scene_Battle
#------------------------------------------------- -----------------------------
# 處理戰鬥畫面的類。
#================================================= =============================
class Scene_Battle < Scene_Base
  alias :eienshinken_start :start
  def start
    if !$game_switches[Eienshinken::ENEMY_XY_SWITCH]
      for i in 0...$game_troop.members.size
        $game_troop.members[i].screen_x = Eienshinken::ENEMY_X[i]
        $game_troop.members[i].screen_y = Eienshinken::ENEMY_Y[i]
      end
      eienshinken_start
    else
      eienshinken_start
    end
  end
end