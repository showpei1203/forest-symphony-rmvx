# ■ 六、敵人難度分層
#==============================================================================
#
#------------------------------------------------------------------------------
# 【普通小怪】
#------------------------------------------------------------------------------
#
#  建議：
#    - 2～4 種行動。
#    - 只有 1 個核心 gimmick。
#    - 至少 1 個明顯可讀的訊號。
#    - 不要同時硬控、破防、追殺後排、封 MP、驅散、回血。
#
#  玩家應該在 1～2 次交手內理解：
#
#    「牠到底在幹嘛？」
#
#------------------------------------------------------------------------------
# 【功能型小怪】
#------------------------------------------------------------------------------
#
#  專門負責一種工作：
#    - 疊毒者
#    - 治療者
#    - 護衛
#    - 引爆者
#    - ATB 干擾者
#    - 召喚物獵人
#
#  單獨不一定強，混編後產生威脅。
#
#------------------------------------------------------------------------------
# 【菁英怪】
#------------------------------------------------------------------------------
#
#  建議：
#    - 4～6 種行動。
#    - 1 個招牌機制。
#    - 1 個反制行動。
#    - 1 個保命或轉 Phase 手段。
#    - 允許玩家看懂後穩定破解。
#
#------------------------------------------------------------------------------
# 【Boss】
#------------------------------------------------------------------------------
#
#  建議：
#    - 6～10 個實際技能，分 Phase 出現。
#    - 每個 Phase 只有 2～4 個主要決策。
#    - 至少一種可預告攻擊。
#    - 至少一個玩家可創造的爆發窗口。
#    - 不要所有異常都免疫。
#    - 不要所有 Break 都免疫。
#    - 不要 ATB 控制完全無效。
#
#  Boss 的挑戰應該來自：
#    - 抗性遞增
#    - 時機要求
#    - 目標選擇
#    - 狀態轉換
#    - 場上構成
#
#  而不是「這招打你 9999，你沒有答案，感謝遊玩」。
#
