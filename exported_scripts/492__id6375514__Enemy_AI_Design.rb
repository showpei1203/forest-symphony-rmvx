# ■ 二、月紳士 Enemy Action Pattern 核心設定
#==============================================================================
#
# 目前專案：
#
#   TOP_SWITCH = 121
#   ADDITION_CONDITION_SKILL = 83
#   CONDITION_ROULETTE = true
#
#------------------------------------------------------------------------------
# 【十個保留 Switch】
#------------------------------------------------------------------------------
#
#  121：存在「可有效施加／解除效果」的目標
#  122：存在 HP 未滿的目標
#  123：存在 HP <= 1/2 的目標
#  124：存在 HP <= 1/5 的目標
#  125：存在仍有 MP 的目標
#  126：存在可以行動的目標
#  127：存在指定 index 的目標
#  128：存在自己以外的目標
#  129：友軍中沒有戰鬥不能者
#  130：場上只剩自己一人
#
#------------------------------------------------------------------------------
# 【如何串接多條條件】
#------------------------------------------------------------------------------
#
#  使用 Skill 83 作為「＋追加條件」虛擬技能。
#
#  例：想讓敵人只在「HP 50% 以下，而且第 3、6、9... 回合」使用大招。
#
#  敵人行動模式：
#
#    行 1：真正的大招
#          條件 = HP 0%～50%
#          評分 = 8
#
#    行 2：Skill 83「＋追加條件」
#          條件 = Turn 3 + 3X
#
#  腳本會把 Skill 83 後面的條件串到上一個真正行動上。
#
#  可以連續放多個 Skill 83，建立更多 AND 條件。
#
#------------------------------------------------------------------------------
# 【目標消失後的三種個性】
#------------------------------------------------------------------------------
#
#  Enemy Note：
#
#    <無鉄砲>
#      原技能照放；若原單體目標失效，改抓其他合法目標。
#      適合狂獸、狂戰士、不會收手的敵人。
#
#    <好戦的>
#      原技能取消，改成普通攻擊。
#      適合一般戰士、主動進攻型敵人。
#
#    <慎重派>
#      原技能取消，本次觀望。
#      適合法師、狙擊手、精密機械。
#
#  建議：
#    - 狂獸：<無鉄砲>
#    - 近戰菁英：<好戦的>
#    - 施法者／機械炮台：<慎重派>
#
#------------------------------------------------------------------------------
# 【State 改變整套 Enemy Action Pattern】
#------------------------------------------------------------------------------
#
#  State Note：
#
#    <エネミー行動変化:ID>
#
#  這可以讓敵人中了某個 State 後，改用另一個 Enemy ID 的行動模式。
#
#  用法：
#    - 狂暴 Phase
#    - 破防後改成弱化行動
#    - 中毒後開始自療
#    - Boss 進入「覺醒」狀態後換整套招式
#
