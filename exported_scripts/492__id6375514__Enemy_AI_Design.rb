# ■ 五、目標優先、威脅與召喚物獵殺
#==============================================================================
#
#  你的敵人不需要每一隻都懂「誰最危險」。
#  如果每一隻雜魚都精準追殺米亞、維娜、低血角色，玩家只會覺得 AI 作弊。
#
#  建議分三級：
#
#------------------------------------------------------------------------------
# 【Level 1：隨機／自然目標】
#------------------------------------------------------------------------------
#
#  適合：
#    - 一般野獸
#    - 低階小怪
#    - 無腦召喚物
#
#  使用原本隨機目標。
#
#------------------------------------------------------------------------------
# 【Level 2：情境目標】
#------------------------------------------------------------------------------
#
#  適合：
#    - 菁英兵
#    - 控場怪
#    - 獵人型怪
#
#  範例：
#    <state_focus:31>
#    <summon_guard:2>
#    <dps_focus:800>
#
#------------------------------------------------------------------------------
# 【Level 3：柔性威脅】
#------------------------------------------------------------------------------
#
#  適合：
#    - Boss
#    - 戰術型菁英
#    - 追獵者
#
#  技能 Note：
#
#    <threat_target>
#    <state_threat:31,500>
#    <dps_threat:100,10>
#
#  這比「永遠攻擊最高 DPS」好，因為仍有不確定性。
#
#------------------------------------------------------------------------------
# 【推薦使用頻率】
#------------------------------------------------------------------------------
#
#  一般小怪：0～10% 的技能使用特殊鎖定。
#  功能小怪：20～40%。
#  菁英怪：30～60%。
#  Boss：視人格與技能，少數招式 50～100%，其他維持自然目標。
#
