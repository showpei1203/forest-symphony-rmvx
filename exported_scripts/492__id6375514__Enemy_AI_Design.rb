# ■ 八、小怪設計範本
#==============================================================================
#
#------------------------------------------------------------------------------
# 【範本 A：單純攻擊獸】
#------------------------------------------------------------------------------
#
#  目的：提供基準壓力。
#
#  行動：
#    普攻 rating 5
#    重擊 rating 7，Turn 3 + 3X
#
#  個性：<無鉄砲>
#
#  戰術價值：
#    玩家知道每三次節奏會有較大傷害，可以提早防禦或 Cover。
#
#------------------------------------------------------------------------------
# 【範本 B：疊毒小獸】
#------------------------------------------------------------------------------
#
#  行動順序：
#    1. 普攻             rating 4
#    2. 毒牙             rating 6，條件：目標沒有毒
#    3. 劇毒撕咬         rating 8，條件：目標已有毒
#
#  若使用月紳士 State 條件：
#    毒牙 → 使用「沒有 State X」的 Switch。
#    劇毒撕咬 → 使用「有 State X」的 Switch。
#
#  玩家讀法：
#    第一次中毒只是警告。
#    不處理，下一步才真正痛。
#
#------------------------------------------------------------------------------
# 【範本 C：低血收割者】
#------------------------------------------------------------------------------
#
#  行動：
#    普攻       rating 4
#    切割       rating 6
#    處刑       rating 9，Switch 124（存在 HP <=20% 目標）
#
#  處刑技能可搭配：
#    <threat_target>
#  或專門低血目標邏輯。
#
#  戰術：
#    米亞的治療與艾薇 Cover 有明確價值。
#
