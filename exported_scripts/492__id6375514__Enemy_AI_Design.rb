# ■ 一、目前專案可用的 AI 工具
#==============================================================================
#
#  目前 Main 以上的有效腳本，已經提供下列敵方 AI 能力：
#
#------------------------------------------------------------------------------
# 【A. RPG Maker VX 內建敵人行動條件】
#------------------------------------------------------------------------------
#
#  敵人資料庫的每一條「行動模式」可使用：
#
#    1. 回合數
#    2. HP 百分比
#    3. MP 百分比
#    4. 自身 State
#    5. 隊伍最高等級
#    6. Switch
#
#  適合：
#    - 固定節奏技能
#    - 低血量變招
#    - 進入 Phase 2
#    - 劇情事件控制
#
#------------------------------------------------------------------------------
# 【B. 月紳士：エネミー行動パターン改良】
#------------------------------------------------------------------------------
#
#  核心能力：
#    - 新增 10 個條件 Switch。
#    - 一個行動可串接多個條件。
#    - 可改成純權重輪盤。
#    - 可依 State 變更敵人的整套行動模式。
#    - 可設定目標消失後的重新行動方式。
#
#  目前設定：
#
#    TOP_SWITCH = 121
#    ADDITION_CONDITION_SKILL = 83
#    CONDITION_ROULETTE = true
#
#------------------------------------------------------------------------------
# 【C. 月紳士：依目標 State 選技能】
#------------------------------------------------------------------------------
#
#  目前設定：
#
#    TOP_SWITCH = 150
#    SETTING = [2, -2, 3, -3]
#
#  對應：
#    Switch 150：只鎖定有 State 2 的目標
#    Switch 151：只鎖定沒有 State 2 的目標
#    Switch 152：只鎖定有 State 3 的目標
#    Switch 153：只鎖定沒有 State 3 的目標
#
#  正數 = 必須有該 State。
#  負數 = 必須沒有該 State。
#
#------------------------------------------------------------------------------
# 【D. 月紳士：依目標 Position 選技能】
#------------------------------------------------------------------------------
#
#  目前設定：
#
#    TOP_SWITCH = 134
#    SETTING = [-3, 3]
#
#  對應：
#    Switch 134：只鎖定「非後衛」
#    Switch 135：只鎖定「後衛」
#
#  Position：
#    1 = 前衛
#    2 = 中衛
#    3 = 後衛
#
#  負數代表排除。
#  例如 -3 = 不是後衛，也就是前衛＋中衛。
#
#------------------------------------------------------------------------------
# 【E. 月紳士：依技能有效度選目標】
#------------------------------------------------------------------------------
#
#  目前設定：
#
#    TOP_SWITCH = 136
#    SETTING = [2, 3]
#
#  對應：
#    Switch 136：只保留技能有效度 A～B 的目標
#    Switch 137：只保留技能有效度 A～C 的目標
#
#  適合：
#    - 火系敵人優先攻擊真正怕火的人。
#    - 控場敵人避免一直對高抗性目標浪費技能。
#    - 菁英法師看起來更像有腦，而不是用火球幫火精靈按摩。
#
#------------------------------------------------------------------------------
# 【F. Target Priority】
#------------------------------------------------------------------------------
#
#  Enemy Note / State Note：
#
#    <target priority: 1>
#    <target priority: 2>
#    <目標優先: 2>
#
#  特定技能忽略目標優先：
#
#    <ignore target priority>
#    <無視目標優先>
#
#  現有嘲諷 State 14：
#    會視為極高優先級 1000。
#
#------------------------------------------------------------------------------
# 【G. SummonGuard Dynamic Threat】
#------------------------------------------------------------------------------
#
#  技能 Note：
#
#    <summon_guard:2>
#      優先攻擊指定召喚群組。
#
#    <state_focus:31>
#      優先攻擊持有 State 31 的目標。
#
#    <dps_focus:800>
#      當某我方角色本場累積傷害達 800 以上，優先攻擊最高 DPS。
#
#    <threat_target>
#      使用柔性權重威脅選擇。
#
#    <state_threat:31,500>
#      持有 State 31，威脅權重 +500。
#
#    <dps_threat:100,10>
#      每累積 100 傷害，威脅權重 +10。
#
#  建議：
#    - 普通小怪少用硬鎖定。
#    - 菁英怪可偶爾使用。
#    - Boss 用來塑造「狩獵召喚物」「追殺高輸出者」個性。
