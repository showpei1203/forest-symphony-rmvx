# ■ 七、前中後期敵人 AI 複雜度曲線
#==============================================================================
#
#------------------------------------------------------------------------------
# 【前期 Lv1～15】
#------------------------------------------------------------------------------
#
#  玩家正在學：
#    - 單一 State
#    - 一條簡單 Combo
#    - 一隻召喚物
#
#  敵人：
#    - 2～3 行動。
#    - 一個明顯條件。
#    - 很少硬控。
#
#  範例：
#    普攻 60%
#    上毒 30%
#    HP < 50% 時自療 10%
#
#------------------------------------------------------------------------------
# 【中前期 Lv16～25】
#------------------------------------------------------------------------------
#
#  玩家有第二召喚槽。
#
#  敵人開始：
#    - 彼此配合。
#    - 看目標 State。
#    - 使用後排／前排條件。
#
#  範例：
#    A 疊毒。
#    B 只對已中毒者用腐蝕。
#
#------------------------------------------------------------------------------
# 【中後期 Lv26～35】
#------------------------------------------------------------------------------
#
#  玩家開始跑資源引擎。
#
#  敵人開始：
#    - 看 OD／ATB 相關時機。
#    - 打斷。
#    - 轉換 State。
#    - 使用菁英混編。
#
#------------------------------------------------------------------------------
# 【後期 Lv36～45】
#------------------------------------------------------------------------------
#
#  玩家有完整三召喚槽。
#
#  敵人開始：
#    - 狩獵召喚物。
#    - 壓制高 DPS。
#    - 隨 Phase 換行動模式。
#    - 使用 Break 恢復與抗性遞增。
#
#------------------------------------------------------------------------------
# 【終局 Lv46～60】
#------------------------------------------------------------------------------
#
#  敵人可以：
#    - 強迫換 Build。
#    - 對單一套路逐步抗性。
#    - 提供多種合理解答。
#
#  注意：
#    終局複雜度不是每個怪都像 Boss。
#    最好的敵群通常仍是一兩個簡單敵人，加一個真正改變規則的核心單位。
#
