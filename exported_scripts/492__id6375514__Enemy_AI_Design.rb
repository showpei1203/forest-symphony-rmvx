# ■ 三、月紳士輪盤評分的重要陷阱
#==============================================================================
#
#  這是非常重要的資料庫規則。
#
#  因為目前：
#
#    CONDITION_ROULETTE = true
#
#  腳本不是單純把所有合格行動丟進輪盤。
#  它會依「資料庫由上到下」掃描，並維持 high_rating。
#
#  如果後面的行動 rating 低於目前 high_rating：
#
#    直接跳過，不進輪盤。
#
#------------------------------------------------------------------------------
# 【錯誤例子】
#------------------------------------------------------------------------------
#
#    第1行：普通攻擊 rating 8
#    第2行：毒液     rating 6
#    第3行：咆哮     rating 7
#
#  結果：
#    第1行進輪盤，high_rating = 8。
#    第2行 6 < 8，被跳過。
#    第3行 7 < 8，也被跳過。
#
#  最後敵人只會普通攻擊。
#
#------------------------------------------------------------------------------
# 【正確例子】
#------------------------------------------------------------------------------
#
#    第1行：普通攻擊 rating 4
#    第2行：毒液     rating 6
#    第3行：咆哮     rating 8
#
#  若三條都符合條件：
#
#    普攻權重 4
#    毒液權重 6
#    咆哮權重 8
#
#  總權重 = 18。
#
#  約略機率：
#    普攻 22%
#    毒液 33%
#    咆哮 44%
#
#------------------------------------------------------------------------------
# 【推薦原則】
#------------------------------------------------------------------------------
#
#  1. 同一組可能同時成立的行動，評分由上到下保持不下降。
#  2. 不要把「最高優先的保底普攻」放第一行給高 rating。
#  3. 條件越特殊的招式，可以放較後面、較高 rating。
#  4. 如果一招只在特殊條件成立，較高 rating 沒問題。
#
#  人類很喜歡把「10分」理解成最高優先，
#  這支腳本則額外加入了「位置順序」這個小小的驚喜。資料庫管理因此獲得了戰術感。
#
