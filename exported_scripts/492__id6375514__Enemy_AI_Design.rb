#  三套抗性最好使用同一哲學：
#
#    玩家第一次成功，獲得完整回報。
#    連續重複，同類效果逐步遞減。
#    Boss 完成有效行動後，部分抗性恢復。
#
#------------------------------------------------------------------------------
# 【ATB】
#------------------------------------------------------------------------------
#
#  讓艾卓仍然能打斷。
#  但不能把 Boss 從滿血鎖到死。
#
#------------------------------------------------------------------------------
# 【State】
#------------------------------------------------------------------------------
#
#  讓維娜仍能上麻痺、毒、濕潤等。
#  但硬控連續成功率下降。
#
#------------------------------------------------------------------------------
# 【Break】
#------------------------------------------------------------------------------
#
#  Enemy Note 範例：
#
#    <break_threshold:8>
#    <break_resist:75>
#    <break_recover:1>
#
#  讓泰勒必須維持攻勢。
#
#------------------------------------------------------------------------------
# 【推薦 Boss 三抗性組合】
#------------------------------------------------------------------------------
#
#  普通 Boss：
#    ATB 動態抗性：中
#    State 動態抗性：只套硬控
#    Break threshold：5～7
#
#  菁英 Boss：
#    ATB 動態抗性：中高
#    State 動態抗性：硬控＋1～2 核心狀態
#    Break threshold：7～9
#    Break recover：1
#
#  終局 Boss：
#    ATB 動態抗性：高，但保留真實打斷窗口
#    State 動態抗性：依 Phase 變化
#    Break threshold：8～12
#    Break resist：50～80%
#    Break recover：1～2
#
#  請避免三者都接近免疫。
#  不然六角色特色會一起被請出戰鬥系統，Boss 剩下的唯一機制就是 HP 很多。
#
#==============================================================================
# ■ 十六、應避免的糟糕 AI
#==============================================================================
#
#------------------------------------------------------------------------------
# 【1. 完美讀心】
#------------------------------------------------------------------------------
#
#  每回合都精準選最低血、最高 DPS、後排補師、關鍵召喚物。
#  玩家會覺得 AI 在讀存檔，不是有戰術。
#
#------------------------------------------------------------------------------
# 【2. 無限控制】
#------------------------------------------------------------------------------
#
#  多名敵人輪流麻痺、睡眠、封技，直到玩家不能玩。
#  難度很高，遊戲性很低。人類通常稱這種設計為「挑戰」，受害者另有看法。
#
#------------------------------------------------------------------------------
# 【3. 所有招都無條件最高輸出】
#------------------------------------------------------------------------------
#
#  如果 AI 每回合只選預期傷害最高招式，敵人沒有個性、沒有節奏。
#
#------------------------------------------------------------------------------
# 【4. 假 Phase】
#------------------------------------------------------------------------------
#
#  HP 50% 後只是攻擊力 +50%，但行為完全不變。
#  這只能叫數值改變。
#
#------------------------------------------------------------------------------
# 【5. 全免疫】
#------------------------------------------------------------------------------
#
#  免疫毒、麻痺、濕潤、Break、ATB 削減、Cover 反制、召喚追擊。
#  玩家辛苦做 Build，Boss 的回答是「不准」。
#
#------------------------------------------------------------------------------
# 【6. 沒有 Tell 的秒殺】
#------------------------------------------------------------------------------
#
#  高傷害可以存在，但應該有：
#    - 蓄力 State
#    - 特殊動畫
#    - Pop Text
#    - 明顯節奏
#
#------------------------------------------------------------------------------
# 【7. 每隻小怪都像 Boss】
#------------------------------------------------------------------------------
#
#  一場 8 敵人，每隻都有 6 個條件、3 個 Phase、2 個 Counter。
#  這不是戰術深度，是行政流程。
#
#==============================================================================
# ■ 十七、資料庫設定檢查表
#==============================================================================
#
#------------------------------------------------------------------------------
# 【普通小怪】
#------------------------------------------------------------------------------
#
#  □ 2～4 種行動
#  □ 只有 1 個核心機制
#  □ 至少一個可讀取的危險訊號
#  □ 不會無限硬控
#  □ 評分由上到下符合輪盤規則
#
#------------------------------------------------------------------------------
# 【功能型小怪】
#------------------------------------------------------------------------------
#
#  □ 明確負責：起狀態／引爆／治療／護衛／控制／獵殺其中之一
#  □ 單獨不至於過強
#  □ 與其他怪混編才形成威脅
#  □ 玩家可以透過優先擊殺破解
#
#------------------------------------------------------------------------------
# 【菁英怪】
#------------------------------------------------------------------------------
#
#  □ 1 個招牌技能
#  □ 1 個條件反擊
#  □ 1 個保命或轉 Phase 手段
#  □ 4～6 種行動
#  □ 有清楚破解方式
#
#------------------------------------------------------------------------------
# 【Boss】
#------------------------------------------------------------------------------
#
#  □ 具有 Tell → Answer Window → Payoff
#  □ 至少兩種有效玩家答案
#  □ 不把六主角某一位完全封死
#  □ ATB 控制有遞減而非免疫
#  □ 硬控 State 有遞減而非全免疫
#  □ Break 有門檻／抗性／回復，而非濫用免疫
#  □ 每 Phase 的主要決策不超過 4 個
#  □ Phase 不是單純加攻擊力
#  □ 資料庫 rating 順序符合月紳士輪盤規則
#
#------------------------------------------------------------------------------
# 【最終設計問題】
#------------------------------------------------------------------------------
#
#  設計完任何敵人，最後問四件事：
#
#    1. 玩家第一次遇到，能看懂牠想做什麼嗎？
#    2. 看懂後，有至少一種可靠解法嗎？
#    3. 不同 Build 的解法會不一樣嗎？
#    4. 玩家成功破解後，會覺得是自己判斷正確，還是單純運氣好？
#
#  四題都有答案，這個敵人通常就不會太差。
#
#==============================================================================
