# ===============================================================================
# 第二十部　最終設計原則
# ===============================================================================
#
# 1. 10隻Boss不必人人都有複雜Phase。
#
# 2. 每隻Boss保留1個主要戰術主題。
#
# 3. 8隻Pokémon Boss最好展示不同狀態與Build語言。
#
# 4. 2隻Robot Boss應突出：
#    ・規律
#    ・防禦
#    ・Protocol
#    ・ATB
#    ・Break
#
# 5. 5隻超模召喚物確實可以強。
#
# 6. 但超模方式必須不同。
#
# 7. 不要讓所有超模召喚物都：
#    ATK最高
#    DEF最高
#    SPI最高
#    AGI最高
#    還會治療。
#
# 8. 真正的蒐集誘因是：
#
#    「我看過這隻非常強的存在，
#     我真的有可能讓牠加入隊伍嗎？」
#
# 9. 稀有召喚物的取得方式要多樣：
#
#    Boss
#    探索
#    謎題
#    耐久
#    劇情選擇
#
# 10. 最好的隱藏獎勵，
#     應該讓玩家記得自己是怎麼拿到它的。
#
#     而不是只記得：
#     又走進一個房間，
#     又打一隻HP比較多的東西，
#     然後領獎。
