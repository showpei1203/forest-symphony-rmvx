# ** Window_DebugLeft
#------------------------------------------------------------------------------
#  本視窗顯示於DEBUG畫面左側，用來顯示開關區段和系統變數區段。
#==============================================================================

class Window_DebugLeft < Window_Selectable
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     x : 視窗X座標
  #     y : 視窗Y座標
  #--------------------------------------------------------------------------
  def initialize(x, y)
    super(x, y, 176, 416)
    self.index = 0
    refresh
  end
  #--------------------------------------------------------------------------
  # * 更新顯示內容
  #--------------------------------------------------------------------------
  def refresh
    @switch_max = ($data_system.switches.size - 1 + 9) / 10
    @variable_max = ($data_system.variables.size - 1 + 9) / 10
    @item_max = @switch_max + @variable_max
    create_contents
    for i in 0...@item_max
      draw_item(i)
    end
  end
  #--------------------------------------------------------------------------
  # * 繪製條目
  #     index : 條目編號
  #--------------------------------------------------------------------------
  def draw_item(index)
    if index < @switch_max
      n = index * 10
      text = sprintf("開關[%04d-%04d]", n+1, n+10)
    else
      n = (index - @switch_max) * 10
      text = sprintf("變數[%04d-%04d]", n+1, n+10)
    end
    rect = item_rect(index)
    rect.x += 4
    rect.width -= 8
    self.contents.clear_rect(rect)
    self.contents.draw_text(rect, text)
  end
  #--------------------------------------------------------------------------
  # * 獲取模式資訊
  #--------------------------------------------------------------------------
  def mode
    if self.index < @switch_max
      return 0
    else
      return 1
    end
  end
  #--------------------------------------------------------------------------
  # * 獲取顯示於條目行頭處的編號資訊
  #--------------------------------------------------------------------------
  def top_id
    if self.index < @switch_max
      return self.index * 10 + 1
    else
      return (self.index - @switch_max) * 10 + 1
    end
  end
end
