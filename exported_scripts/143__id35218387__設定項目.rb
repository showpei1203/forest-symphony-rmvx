# ■ TPet_Dog
#------------------------------------------------------------------------------
# 　ペットのキャラクター（犬）クラス
#==============================================================================

class TPet_Dog < TPet_Character
  #--------------------------------------------------------------------------
  # ● オブジェクト初期化
  #--------------------------------------------------------------------------
  def initialize###$litb_S  $medb_S  $bigb_S
    super
    @character_name = "$LIF1S" if $game_variables[101] == 1 # 使用する画像ファイル名
    @character_name = "$LIF2S" if $game_variables[102] >= 15
    @character_name = "$LIF3S" if $game_variables[102] >= 30
    @character_index = 0        # 画像ファイルの中のどのキャラを使うか
  end
  #--------------------------------------------------------------------------
  # ● 鳴き声
  #--------------------------------------------------------------------------
  def cry(volume, pitch)
    Audio.se_play("Audio/SE/Dog.ogg", volume, pitch)  # 鳴き声として使うSE
  end
end

