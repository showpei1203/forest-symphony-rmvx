# ==============================================================================
# ■ 23. 任務常見問題
# ==============================================================================
#
# 問題：任務不顯示？
#
#   檢查：
#     ・MANUAL_REVEAL。
#     ・是否執行 reveal_quest。
#     ・任務 ID。
#     ・是否 conceal。
#     ・目前分類。
#
# 問題：目標操作錯一格？
#
#   目標 ID 從 0 開始。
#   第 1 個目標是 0。
#
# 問題：任務提早完成？
#
#   檢查 prime。
#   prime = [0, 1] 表示只需完成 0、1。
#
# 問題：任務永遠不完成？
#
#   檢查：
#     ・prime 是否含不存在的 ID。
#     ・prime 目標是否 failed。
#     ・是否只有 reveal，沒有 complete。
#     ・是否把第一目標誤寫成 1。
#
# 問題：獎勵只顯示沒拿到？
#
#   rewards 是資料。
#   呼叫：
#     give_quest_reward(任務ID)
#
#   或手動發放後：
#     change_reward_status(任務ID, true)
#
# 問題：字串獎勵沒有執行？
#
#   字串只顯示。
#   開關、配方、角色加入需另寫事件。
#
# 問題：common_event 不再觸發？
#
#   第一次完成後 common_event_id 會設為 0。
#   完整重設需：
#     reset_quest(任務ID)
#
# 問題：修改 QuestData 後舊存檔沒更新？
#
#   舊存檔中的 Game_Quest 已保存一份資料。
#   reset_quest 可重讀，但會清除該任務進度。
#   正式版本應另外寫存檔遷移。
#
# 問題：繁中說明擠成一行？
#
#   確認 SafetyPatch v1.0.14 在 Quest Journal 下方。
#   它修正：
#     ・UTF-8 繁中逐字換行。
#     ・中英文混排。
#     ・控制碼保護。
#     ・標點禁則。
#     ・Description／Objectives 行高。
#     ・Rewards 底部留白。
#     ・獎勵圖示位置。
#
#
