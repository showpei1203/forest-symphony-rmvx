# ■ 19. 任務完成與發獎
# ==============================================================================
#
# ------------------------------------------------------------------------------
# ● 標準流程
# ------------------------------------------------------------------------------
#
# 接受：
#
#   reveal_quest(10)
#   reveal_objective(10, 0)
#
# 完成第一階段：
#
#   complete_objective(10, 0)
#   reveal_objective(10, 1)
#
# 完成最後目標：
#
#   complete_objective(10, 1)
#
# 領獎：
#
#   if give_quest_reward(10)
#     $game_switches[50] = true
#   end
#
# give_quest_reward 回傳 true 的條件：
#   ・任務已完成。
#   ・尚未領取獎勵。
#
# 會處理：
#   0 物品
#   1 武器
#   2 防具
#   3 金錢
#   4 經驗值
#
# 不會處理：
#   字串、開關、配方、角色加入、自訂機制。
#
# ------------------------------------------------------------------------------
# ● 手動發獎
# ------------------------------------------------------------------------------
#
#   $game_party.gain_gold(500)
#   $game_party.gain_item($data_items[1], 3)
#   change_reward_status(10, true)
#
# 記得更新 reward status，
# 不然 NPC 會變成比城主財政更慷慨的無限提款機。
#
# ------------------------------------------------------------------------------
# ● common_event 與回報
# ------------------------------------------------------------------------------
#
# common_event：
#   任務第一次達成完成條件時觸發。
#
# 回報 NPC：
#   通常負責對話、發獎與開啟後續任務。
#
# 兩者不必是同一時點。
#
#
# ==============================================================================
# ■ 20. 任務商店
# ==============================================================================
#
# 格式：
#
#   call_quest_shop(任務陣列, "商店名稱")
#
# 商品陣列格式：
#
#   [任務ID, 價格]
#
#   [任務ID, 價格, [購買後顯示的目標ID]]
#
#   [任務ID, 價格, 開關ID]
#
#   [任務ID, 價格, [目標ID], 開關ID]
#
# 範例：
#
#   a = []
#   a.push([1, 50, [0]])
#   a.push([4, 80, 1])
#   a.push([3, 100])
#   a.push([5, 75, [0, 1], 1])
#   call_quest_shop(a, "冒險者公會")
#
# 解讀：
#
#   [1, 50, [0]]
#     任務 1，價格 50，只顯示目標 0。
#
#   [4, 80, 1]
#     任務 4，價格 80，開關 1 ON 時才出現，購買後顯示全部目標。
#
#   [5, 75, [0, 1], 1]
