# ■ 17. 任務進度指令
# ==============================================================================
#
# 所有指令寫在事件「腳本」。
#
# ------------------------------------------------------------------------------
# ● 開啟任務日誌
# ------------------------------------------------------------------------------
#
#   call_quest
#
#   call_quest(10)
#
# 第二種會嘗試定位到已顯示的任務 10。
#
# ------------------------------------------------------------------------------
# ● 取得任務物件
# ------------------------------------------------------------------------------
#
#   quest(10)
#
# 可讀取：
#
#   quest(10).name
#   quest(10).description
#   quest(10).location
#   quest(10).client
#   quest(10).objectives
#   quest(10).rewards
#
# ------------------------------------------------------------------------------
# ● 顯示／隱藏任務
# ------------------------------------------------------------------------------
#
#   reveal_quest(10)
#   conceal_quest(10)
#
# conceal 只隱藏，保留進度。
#
# ------------------------------------------------------------------------------
# ● 移除／重設任務
# ------------------------------------------------------------------------------
#
#   remove_quest(10)
#
# 從任務資料中移除。
# 再次存取時會依 QuestData 重建。
#
#   reset_quest(10)
#
# 重新讀取 QuestData 並清除：
#   ・目標顯示
#   ・完成狀態
#   ・失敗狀態
#   ・領獎旗標
#
# ------------------------------------------------------------------------------
# ● 顯示／隱藏目標
# ------------------------------------------------------------------------------
#
#   reveal_objective(10, 0)
#   reveal_objective(10, 1, 2)
#
#   conceal_objective(10, 0)
#   conceal_objective(10, 1, 2)
#
# ------------------------------------------------------------------------------
# ● 完成／取消完成
# ------------------------------------------------------------------------------
#
#   complete_objective(10, 0)
#   complete_objective(10, 1, 2)
#
#   uncomplete_objective(10, 0)
#
# 完成目標時：
#   ・尚未顯示的目標會自動顯示。
#   ・已失敗目標不會直接完成。
#   ・完成全部 prime 後，任務完成。
#   ・第一次完成可觸發 common_event。
#
# ------------------------------------------------------------------------------
# ● 失敗／取消失敗
# ------------------------------------------------------------------------------
#
#   fail_objective(10, 0)
#   unfail_objective(10, 0)
#
# ------------------------------------------------------------------------------
# ● 獎勵旗標
# ------------------------------------------------------------------------------
#
#   change_reward_status(10)
#   change_reward_status(10, true)
#   change_reward_status(10, false)
#
# 只修改 reward_given，不會發放物品或金錢。
#
