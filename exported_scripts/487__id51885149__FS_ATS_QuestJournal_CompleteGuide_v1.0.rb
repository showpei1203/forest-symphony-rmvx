# ==============================================================================
# ■ 12. 系統原理與安裝
# ==============================================================================
#
# Quest Journal 負責：
#
#   ・保存任務是否顯示。
#   ・保存各目標顯示、完成與失敗狀態。
#   ・判斷任務完成或失敗。
#   ・顯示任務名稱、說明、地點、委託人、目標與獎勵。
#   ・提供任務商店及事件腳本指令。
#
# 它不會自動：
#
#   ・計算擊殺數。
#   ・判斷抵達地點。
#   ・讀取 NPC 對話結果。
#   ・替你完成劇情流程。
#
# 標準流程：
#
#   事件判斷條件
#       ↓
#   呼叫 reveal／complete／fail
#       ↓
#   Quest Journal 保存並顯示狀態
#
# 建議腳本順序：
#
#   QJ2 - CONFIGURATION
#   QJ2 - BODY
#   FS_LegacyScripts_SafetyPatch v1.0.14
#   Main
#
#
# ==============================================================================
# ■ 13. QuestData 任務格式
# ==============================================================================
#
# 在 QuestData.quest_data(id) 的 case id 內新增：
#
#   when 10
#     banner = "Quest_Banner_010"
#     name = "失落的刻印"
#     client = "魯卡村村長"
#     location = "魯卡村北方原野"
#     description = "調查村外異常殘響的來源。"
#
#     objectives[0] = "向村長詢問刻印的來歷"
#     objectives[1] = "前往北方原野"
#     objectives[2] = "擊退失控的野生生物"
#     objectives[3] = "帶著調查結果返回村長家"
#
#     prime = [0, 1, 2, 3]
#
#     rewards = [
#       [0, 1, 3],
#       [3, 300],
#       "\\icon[137]解鎖魂刻合成功能"
#     ]
#
#     level = 1
#     common_event = 25
#     icon_index = 137
#     custom_categories = [:primary]
#
# 重要：
#   ・任務 ID 必須唯一。
#   ・目標 ID 從 0 開始。
#   ・Ruby 字串中的控制碼使用雙反斜線。
#   ・banner 圖片位於 Graphics/Pictures/。
#   ・未設定欄位使用預設值。
#
#
# ==============================================================================
# ■ 14. 任務欄位
# ==============================================================================
#
# ------------------------------------------------------------------------------
# ● banner
# ------------------------------------------------------------------------------
#
#   banner = "圖片檔名"
#
# 路徑：
#   Graphics/Pictures/
#
# 空字串表示不顯示：
#
#   banner = ""
#
# ------------------------------------------------------------------------------
# ● name
# ------------------------------------------------------------------------------
#
#   name = "失落的刻印"
#
# 任務名稱，建議必填。
#
# ------------------------------------------------------------------------------
# ● description
# ------------------------------------------------------------------------------
#
#   description = "調查村外異常殘響的來源。"
#
# 使用控制碼：
#
#   description = "找到\\c[2]破裂刻印\\c[0]的來源。"
#
# ------------------------------------------------------------------------------
# ● client
# ------------------------------------------------------------------------------
#
#   client = "魯卡村村長"
#
# 委託人。空字串可略過該區。
#
# ------------------------------------------------------------------------------
# ● location
# ------------------------------------------------------------------------------
#
#   location = "魯卡村北方原野"
#
# 任務地點。空字串可略過。
#
# ------------------------------------------------------------------------------
# ● objectives
# ------------------------------------------------------------------------------
#
#   objectives[0] = "與村長交談"
#   objectives[1] = "前往北方原野"
#   objectives[2] = "返回村莊"
#
# ID 從 0 開始，建議連續不跳號。
#
# ------------------------------------------------------------------------------
# ● prime
# ------------------------------------------------------------------------------
#
# 主要目標：
#
#   prime = [0, 1, 2]
#
# 只有 prime 中的目標影響整個任務完成／失敗。
#
# 若不設定 prime：
#   所有 objectives 都會自動成為主要目標。
#
# ------------------------------------------------------------------------------
# ● rewards
# ------------------------------------------------------------------------------
#
# 任務介面顯示的獎勵。
# 標準陣列可由 give_quest_reward 自動發放。
# 字串只顯示。
#
# ------------------------------------------------------------------------------
# ● level
# ------------------------------------------------------------------------------
#
#   level = 3
#
# 任務難度。0 通常表示不顯示。
#
# ------------------------------------------------------------------------------
# ● common_event
# ------------------------------------------------------------------------------
#
#   common_event = 25
#
# 任務第一次達成完成條件時呼叫公共事件 25。
#
# 完成後，執行中的 Game_Quest 會把 common_event_id 設為 0，
# 避免重複呼叫。
#
# ------------------------------------------------------------------------------
# ● icon_index
# ------------------------------------------------------------------------------
#
#   icon_index = 137
#
# 任務列表圖示。
#
# ------------------------------------------------------------------------------
# ● custom_categories
# ------------------------------------------------------------------------------
#
#   custom_categories = [:primary, :village]
#
# 必須在 CATEGORIES 與 ICONS 加入相同 symbol。
#
#
# ==============================================================================
# ■ 15. 目標與 prime
# ==============================================================================
#
# 目標 ID：
#
#   第 1 個目標 = 0
#   第 2 個目標 = 1
#   第 3 個目標 = 2
#
# 例：
#
#   complete_objective(10, 0)
#
# 完成任務 10 的第 1 個目標。
#
# ------------------------------------------------------------------------------
# ● 任務完成
# ------------------------------------------------------------------------------
#
# 當所有 prime 目標完成：
#
#   quest_complete?(10)
#
# 回傳 true。
#
# ------------------------------------------------------------------------------
# ● 任務失敗
# ------------------------------------------------------------------------------
#
# 任一 prime 目標失敗：
#
#   quest_failed?(10)
#
# 回傳 true。
#
# 非 prime 目標失敗：
#   只標記該目標，不一定讓整個任務失敗。
#
# ------------------------------------------------------------------------------
# ● 已失敗目標改為完成
# ------------------------------------------------------------------------------
#
# 先：
#
#   unfail_objective(10, 0)
#
# 再：
#
#   complete_objective(10, 0)
#
#
