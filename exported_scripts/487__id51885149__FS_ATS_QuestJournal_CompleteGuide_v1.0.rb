# ■ 25. 舊存檔與資料更新
# ==============================================================================
#
# ------------------------------------------------------------------------------
# ● ATS
# ------------------------------------------------------------------------------
#
# ats_all 會改變存檔中的 ATS 狀態。
#
# 常數更新後，舊存檔未必自動採用新值。
#
# 可在安全時點：
#
#   ats_dialogue_reset
#
# ------------------------------------------------------------------------------
# ● Quest Journal
# ------------------------------------------------------------------------------
#
# 任務保存於：
#
#   $game_party.quests
#
# 已建立的 Game_Quest 會保留：
#   ・任務文字資料
#   ・目標顯示
#   ・完成／失敗
#   ・領獎狀態
#
# 單任務重讀：
#
#   reset_quest(任務ID)
#
# 但會清除進度。
# 正式更新應寫資料遷移腳本，而不是假裝玩家沒有存檔。
#
