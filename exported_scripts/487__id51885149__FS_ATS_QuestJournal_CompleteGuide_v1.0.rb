# ■ 02. 專案三種背景樣式
# ==============================================================================
#
# 事件編輯器「顯示文字」的背景：
#
#   0：正常的視窗
#   1：暗化背景
#   2：透明
#
# ------------------------------------------------------------------------------
# ● 地圖：正常的視窗
# ------------------------------------------------------------------------------
#
# 背景：
#   Graphics/System/Default.png
#
# 行為：
#   ・使用 Default windowskin。
#   ・依文字自動調整寬度與高度。
#   ・過長繁中句子自動換行。
#   ・保留事件編輯器手動分行。
#   ・普通 NPC 預設自動跟隨目前事件。
#   ・可顯示 Speech Tag 小箭頭。
#
# 適合：
#   一般 NPC 對話、短句、頭頂氣泡。
#
# ------------------------------------------------------------------------------
# ● 地圖：暗化背景
# ------------------------------------------------------------------------------
#
# 背景：
#   Graphics/System/MessageBack.png
#
# 行為：
#   ・維持 MessageBack 原始固定尺寸。
#   ・不會因短句縮成小框。
#   ・使用 MessageBack 專屬安全文字區。
#   ・依立繪左右側保留文字空間。
#   ・尊重事件編輯器設定的上、中、下位置。
#   ・預設不自動綁定目前事件。
#
# 適合：
#   旁白、重要劇情、帶立繪對話。
#
# ------------------------------------------------------------------------------
# ● 地圖：透明
# ------------------------------------------------------------------------------
#
# 背景：
#   不顯示 Default，也不顯示 MessageBack。
#
# 行為：
#   ・文字仍使用原 Window_Message#contents。
#   ・適合搭配顯示圖片、自製 UI 或全畫面演出。
#
# ------------------------------------------------------------------------------
# ● 戰鬥：正常的視窗
# ------------------------------------------------------------------------------
#
# 背景：
#   Graphics/System/Default.png
#
# 行為：
#   ・顯示於指定 Actor／Enemy 的戰鬥 Sprite 上方。
#   ・持續追蹤 Tankentai SBS 的實際 Sprite 位置。
#   ・可顯示自動姓名框與 Speech Tag。
#   ・文字使用原 Window_BattleMessage#contents。
#
# ------------------------------------------------------------------------------
# ● 戰鬥：暗化背景
# ------------------------------------------------------------------------------
#
# 背景：
#   Graphics/System/MessageBack.png
#
# 行為：
#   ・固定大框。
#   ・依安全文字區自動換行。
#   ・仍使用原 Window_BattleMessage#contents。
#
# ------------------------------------------------------------------------------
# ● 戰鬥：透明
# ------------------------------------------------------------------------------
#
# 背景：
#   Graphics/Pictures/Battle_Message.png
#
# 行為：
#   ・直接沿用原戰鬥訊息腳本的 @b_sprite。
#   ・文字仍使用原 Window_BattleMessage#contents。
#   ・不建立第二套文字 Sprite 或複製 Bitmap。
#
#
# ==============================================================================
# ■ 03. ats_all、ats_next 與重設
# ==============================================================================
#
# ------------------------------------------------------------------------------
# ● ats_all
# ------------------------------------------------------------------------------
#
# 格式：
#
#   ats_all(:屬性名稱, 值)
#
# 作用：
#   同時修改 $game_ats 與 $game_message。
#   會持續影響後續對話，並可能保存到存檔。
#
# 範例：
#
#   ats_all(:message_speed, 0)
#   ats_all(:message_fontsize, 22)
#   ats_all(:speech_tag_index, -1)
#
# 適合：
#   章節級、全遊戲級或系統選項設定。
#
# ------------------------------------------------------------------------------
# ● ats_next
# ------------------------------------------------------------------------------
#
# 格式：
#
#   ats_next(:屬性名稱, 值)
#
# 作用：
#   只套用到下一段顯示文字。
#   對話結束後恢復目前全域設定。
#
# 範例：
#
#   ats_next(:message_speed, -1)
#   ats_next(:message_fontcolour, 2)
#   ats_next(:speech_tag_index, -1)
#
# 適合：
#   單句特殊語速、單次字色、單次關閉箭頭。
#
# ------------------------------------------------------------------------------
# ● 重設
# ------------------------------------------------------------------------------
#
# FS 指令：
#
#   ats_dialogue_reset
#
# 原生方式：
#
#   $game_ats.reset
#   $game_message.clear
#
# 注意：
#
#   ・只能在兩段「顯示文字」之間呼叫。
#   ・不要在訊息正在顯示時執行。
#   ・$game_message.clear 會清除目前文字、選項及相關暫存。
#   ・ATS 沒有記錄上一個 ats_all 值，不能自動「復原上一層」。
#
#
# ==============================================================================
# ■ 04. FS 擴充指令
# ==============================================================================
#
# 所有指令寫在事件指令「腳本」。
#
# ------------------------------------------------------------------------------
# ● 尺寸與排版
# ------------------------------------------------------------------------------
#
#   ats_dialogue_auto
#
#     使用自動寬高與自動換行。
#     正常背景 NPC 對話的標準模式。
#
#   ats_dialogue_fixed(544, 128)
#
#     使用固定寬 544、高 128，但仍可自動換行。
#
#   ats_dialogue_wrap(true)
#
#     開啟 FS 自動換行。
#
#   ats_dialogue_wrap(false)
#
#     關閉 FS 自動換行。
#
#   ats_dialogue_reset
#
#     恢復 FS 擴充預設。
#     必須在沒有訊息顯示時執行。
#
#   ats_dialogue_speed(1)
#
#     設定持續使用的文字速度。
#
#     常用：
#       -1：立即顯示
#        0：最快逐字
#        1：專案預設
#        2 以上：逐漸變慢
#
#   ats_dialogue_tag(0)
#
#     使用 Speech Tag 索引 0。
#
#   ats_dialogue_tag(-1)
#
#     關閉 Speech Tag。
#
# ------------------------------------------------------------------------------
# ● 地圖說話者
# ------------------------------------------------------------------------------
#
#   ats_speaker_auto
#
#     恢復自動模式。
#     普通 NPC 事件使用目前事件作為說話者。
#
#   ats_speaker_event
#
#     指定目前事件。
#
#   ats_speaker_event(12)
#
#     指定 Event ID 12。
#
#   ats_speaker_event(12, 4)
#
#     指定 Event ID 12，char_ref 為 4。
#
#   ats_speaker_player
#
#     指定玩家。
#
#   ats_speaker_player(4)
#
#     指定玩家，char_ref 為 4。
#
#   ats_speaker_none
#
#     關閉角色跟隨，改用事件編輯器的上、中、下位置。
#
# ------------------------------------------------------------------------------
# ● 戰鬥說話者
# ------------------------------------------------------------------------------
#
#   ats_battle_actor(1)
#
#     指定資料庫 Actor ID 1。
#
#   ats_battle_actor(1, -12)
#
#     指定 Actor ID 1，對話框額外往上 12 px。
#
#   ats_battle_actor(1, 0, false)
#
#     第三參數 false：不自動建立姓名框。
#
#   ats_battle_enemy(1)
#
#     指定敵群中的第 1 隻敵人。
#     此方法從 1 開始。
#
#   ats_battle_enemy(2, -8, true)
#
#     第 2 隻敵人，往上 8 px，自動姓名框。
#
#   ats_battle_enemy_index(0)
#
#     使用 0-based index。
#     index 0 代表第 1 隻敵人。
#
#   ats_battle_active
#
#     指定 Scene_Battle 的目前 @active_battler。
#
#   ats_battle_active(-10, true)
#
#     目前行動者，往上 10 px，自動姓名框。
#
#   ats_battle_clear
#
#     清除戰鬥說話者。
#
# 參數：
#   y_offset：
#     負數往上，正數往下。
#
#   auto_name：
#     true：文字內沒有 \nb[] 時，自動使用 battler.name。
#     false：不自動建立姓名框。
#
#
# ==============================================================================
# ■ 05. 地圖說話者
# ==============================================================================
#
# char_ref：
#
#   0：角色上方
#   1：角色左側
#   2：角色下方
#   3：角色右側
#   4：上方放得下就放上方，否則放下方
#
# 推薦：
#   ats_speaker_event(事件ID, 4)
#   ats_speaker_player(4)
#
# ------------------------------------------------------------------------------
# ● 一般 NPC
# ------------------------------------------------------------------------------
#
# 事件腳本：
#
#   ats_speaker_auto
#
# 接著顯示文字，背景選「正常的視窗」。
#
# 效果：
#   ・自動跟隨目前 NPC。
#   ・顯示 Speech Tag。
#   ・不必每段使用 ats_next(:character, ...)。
#
# ------------------------------------------------------------------------------
# ● 指定另一個 NPC
# ------------------------------------------------------------------------------
#
#   ats_speaker_event(15, 4)
#
# 適合：
#   同一事件控制多人對話、遠處 NPC 插話。
#
# ------------------------------------------------------------------------------
# ● 旁白
# ------------------------------------------------------------------------------
#
#   ats_speaker_none
#
# 接著使用暗化或透明背景。
#
# ------------------------------------------------------------------------------
# ● 原生 ATS 定位控制碼
# ------------------------------------------------------------------------------
#
#   \oc[0]   玩家上方
#   \oc[5]   Event ID 5 上方
#   \uc[5]   Event ID 5 下方
#   \lc[5]   Event ID 5 左側
#   \rc[5]   Event ID 5 右側
#   \e[5]    上方放得下就上方，否則下方
#
#
# ==============================================================================
# ■ 06. 戰鬥說話者與 Tankentai SBS
# ==============================================================================
#
# FS 擴充會：
#
#   1. 從 Spriteset_Battle 取得 @actor_sprites／@enemy_sprites。
#   2. 依 battler 物件比對實際 Sprite。
#   3. 使用 sprite.x、sprite.y、sprite.oy、zoom_y 計算頭頂位置。
#   4. 每幀更新，所以 SBS 移動、跳躍、衝刺時仍會跟隨。
#
# ------------------------------------------------------------------------------
# ● Actor 頭頂對話
# ------------------------------------------------------------------------------
#
#   ats_battle_actor(1)
#
# 顯示文字：
#   背景選「正常的視窗」。
#
# 結束：
#   ats_battle_clear
#
# ------------------------------------------------------------------------------
# ● Enemy 頭頂對話
# ------------------------------------------------------------------------------
#
#   ats_battle_enemy(1)
#
# 注意：
#   1 是敵群位置，不是 Enemy 資料庫 ID。
#
# ------------------------------------------------------------------------------
# ● 全畫面戰鬥劇情
# ------------------------------------------------------------------------------
#
# 先指定說話者：
#
#   ats_battle_enemy(1)
#
# 再依需求選：
#
#   暗化背景：
#     MessageBack 固定大框。
#
#   透明背景：
#     Battle_Message 圖片。
#
# 指定 battler 仍可用來自動建立姓名框。
#
