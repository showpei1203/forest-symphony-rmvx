# ==============================================================================
# ■ 26. 製作規範
# ==============================================================================
#
# ATS：
#
#   1. 一般 NPC 使用正常背景。
#   2. 旁白與重要劇情使用暗化 MessageBack。
#   3. 戰鬥系統訊息或自製 UI 使用透明 Battle_Message。
#   4. 單次變化使用 ats_next。
#   5. 長期變化才使用 ats_all。
#   6. 戰鬥劇情後呼叫 ats_battle_clear。
#   7. 不用空格人工排版 MessageBack。
#   8. 不同 DialogueExtension 版本不可同時啟用。
#
# Quest：
#
#   1. 任務 ID 唯一。
#   2. 目標 ID 從 0 連續排列。
#   3. prime 明確列出主要目標。
#   4. 至少設定 name、description、objectives。
#   5. 字串特殊獎勵另做事件。
#   6. 發獎後更新 reward_given。
#   7. 階段切換時完成舊目標並顯示新目標。
#   8. 不用「任務已顯示」代替「目標已完成」。
#   9. 修改資料前考慮舊存檔。
#  10. 每個任務建立獨立測試事件。
