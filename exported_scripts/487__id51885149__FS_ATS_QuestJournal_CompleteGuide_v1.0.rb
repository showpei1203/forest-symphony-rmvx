# ------------------------------------------------------------------------------
# ● 說明、價格、持有數
# ------------------------------------------------------------------------------
#
#   \di[x]       物品說明
#   \dw[x]       武器說明
#   \da[x]       防具說明
#   \ds[x]       技能說明
#
#   \pi[x]       物品價格
#   \pw[x]       武器價格
#   \pa[x]       防具價格
#
#   \i#[x]       物品持有數
#   \w#[x]       武器持有數
#   \a#[x]       防具持有數
#
# ------------------------------------------------------------------------------
# ● 圖示
# ------------------------------------------------------------------------------
#
#   \i[x]        Icon Index x
#   \ii[x]       物品圖示
#   \wi[x]       武器圖示
#   \ai[x]       防具圖示
#   \si[x]       技能圖示
#   \ti[x]       狀態圖示
#
# Quest Journal 常見：
#   \icon[x]
#
# QuestData 是 Ruby 字串，需寫：
#   "\\icon[137]特殊獎勵"
#
# ------------------------------------------------------------------------------
# ● 顏色與字型
# ------------------------------------------------------------------------------
#
#   \c[x]          windowskin 色盤第 x 色
#   \c[#RRGGBB]    十六進位 RGB 色彩
#   \fn[字型]      更換字型
#   \fs[x]         字體大小
#   \fa[x]         字體透明度
#
#   \b  /b         粗體開／關
#   \i  /i         斜體開／關
#   \s  /s         陰影開／關
#   \u  /u         底線開／關
#   \hl[x]         反白
#   /hl            關閉反白
#   \hl[-1]        關閉反白
#
# ------------------------------------------------------------------------------
# ● 對齊
# ------------------------------------------------------------------------------
#
#   \l             靠左
#   \r             靠右
#   \c             置中
#   \t             Tab 到下一個 32 px 倍數
#   \x[n]          直接指定文字繪製 x 座標
#
# 注意：
#   \c 是置中。
#   \c[x] 才是顏色。
#
# ------------------------------------------------------------------------------
# ● 等待與速度
# ------------------------------------------------------------------------------
#
#   \.             等待 15 frame
#   \|             等待 60 frame
#   \w[x]          等待 x frame
#   \!             暫停並等待輸入
#   \^             略過下一次輸入暫停
#   \>             加快一級
#   \<             減慢一級
#   \s[x]          目前每字等待加上 x
#   \s[=x]         直接指定每字等待
#
# 範例：
#   \s[2]          變慢 2 frame
#   \s[-3]         加快 3 frame
#   \s[=0]         每字 1 frame
#   \s[=-1]        立即顯示
#
# ------------------------------------------------------------------------------
# ● 快速顯示
# ------------------------------------------------------------------------------
#
#   \@  /@         本行立即顯示開／關
#   \@@ /@@        整段立即顯示開／關
#   \%             禁止玩家按鍵快轉
#
# ------------------------------------------------------------------------------
# ● 姓名框與其他視窗
# ------------------------------------------------------------------------------
#
#   \g             金錢視窗開／關
#   \nb[姓名]      開啟姓名框
#   /nb            關閉姓名框
#   \wb[文字]      開啟單行字詞框
#   /wb            關閉字詞框
#
# ------------------------------------------------------------------------------
# ● 臉圖、音效、動畫與氣泡
# ------------------------------------------------------------------------------
#
#   \af[x]             顯示 Actor ID x 的臉圖
#   \se[SE名稱]        播放 SE
#   \me[ME名稱]        播放 ME
#   \ani[目標,動畫]    播放動畫
#   \bln[目標,氣泡]    播放氣泡
#
# 地圖目標：
#   0 為玩家，其餘為 Event ID。
#
# ------------------------------------------------------------------------------
# ● 視窗位置
# ------------------------------------------------------------------------------
#
#   \oc[x]         角色上方
#   \uc[x]         角色下方
#   \lc[x]         角色左側
#   \rc[x]         角色右側
#   \e[x]          自動上／下
#   \mxy[x,y]      訊息視窗位置
#   \fxy[x,y]      臉圖視窗位置
#   \nxy[x,y]      姓名框位置
