#==============================================================================
# ** Window_NameEdit
#------------------------------------------------------------------------------
#  本視窗顯示於名稱輸入畫面中，用來編輯某個主角的名稱。
#==============================================================================

class Window_NameEdit < Window_Base
  #--------------------------------------------------------------------------
  # * 宣告執行個體變數
  #--------------------------------------------------------------------------
  attr_reader   :name                     # 主角名稱
  attr_reader   :index                    # 游標位置
  attr_reader   :max_char                 # 字元數上限
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     actor    : 主角
  #     max_char : 字元數上限
  #--------------------------------------------------------------------------
  def initialize(actor, max_char)
    super(176, 144, 368, 128)
    @actor = actor
    @name = actor.name
    @max_char = max_char
    name_array = @name.split(//)[0...@max_char]   # 自動適應字元數上限
    @name = ""
    for i in 0...name_array.size
      @name += name_array[i]
    end
    @default_name = @name
    @index = name_array.size
    self.active = false
    refresh
    update_cursor
  end
  #--------------------------------------------------------------------------
  # * 換回默認的主角名稱
  #--------------------------------------------------------------------------
  def restore_default
    @name = @default_name
    @index = @name.split(//).size
    refresh
    update_cursor
  end
  #--------------------------------------------------------------------------
  # * 插入字元
  #     character : 要插入的字元
  #--------------------------------------------------------------------------
  def add(character)
    if @index < @max_char and character != ""
      @name += character
      @index += 1
      refresh
      update_cursor
    end
  end
  #--------------------------------------------------------------------------
  # * 刪除字元
  #--------------------------------------------------------------------------
  def back
    if @index > 0
      name_array = @name.split(//)          # 刪掉一個字元
      @name = ""
      for i in 0...name_array.size-1
        @name += name_array[i]
      end
      @index -= 1
      refresh
      update_cursor
    end
  end
  #--------------------------------------------------------------------------
  # * 獲取條目顯示所需的矩形區域資訊
  #     index : 條目編號
  #--------------------------------------------------------------------------
  def item_rect(index)
    rect = Rect.new(0, 0, 0, 0)
    rect.x = 220 - (@max_char + 1) * 12 + index * 24
    rect.y = 36
    rect.width = 24
    rect.height = WLH
    return rect
  end
  #--------------------------------------------------------------------------
  # * 更新內容顯示
  #--------------------------------------------------------------------------
  def refresh
    self.contents.clear
    draw_actor_face(@actor, 0, 0)
    name_array = @name.split(//)
    for i in 0...@max_char
      c = name_array[i]
      c = '_' if c == nil
      self.contents.draw_text(item_rect(i), c, 1)
    end
  end
  #--------------------------------------------------------------------------
  # * 更新游標繪製
  #--------------------------------------------------------------------------
  def update_cursor
    self.cursor_rect = item_rect(@index)
  end
  #--------------------------------------------------------------------------
  # * 更新幀
  #--------------------------------------------------------------------------
  def update
    super
    update_cursor
  end
end
