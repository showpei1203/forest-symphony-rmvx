# 第十二部　狀態設計平衡規則
# ===============================================================================
#
# 1. 一個State最好只有1個主功能。
#
# 2. 可疊層State：
#    一般 3～5層。
#    系統進度State可10～15層。
#
# 3. Hard CC：
#    通常1回合。
#    Boss動態抗性。
#
# 4. 一般Buff：
#    +15～25%。
#
# 5. 一般Debuff：
#    -15～25%。
#
# 6. 多層Debuff：
#    每層 4～10%。
#
# 7. Broken：
#    是大爆發窗口，不能隨手常駐。
#
# 8. Poison：
#    需要有：
#      疊層
#      擴散
#      飄移
#      引爆
#    才能成為完整Build。
#
# 9. 狀態免疫應少用。
#    用抗性、動態抗性、縮短時間通常更有趣。
#
# 10. 玩家看不懂的State數量越多，
#     戰略性通常不是增加，而是UI開始加班。
