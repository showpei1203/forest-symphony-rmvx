#   不成為一般目標。
#
# 【State 14｜挑釁】
# 多個目標優先系統硬鎖：
#   PROVOKE_STATE_ID = 14
#
# 【State 17｜Wild AI】
# AutoBattleAI。
#
# 【State 18｜Healy AI】
# AutoBattleAI。
#
# 【State 22｜Protect AI】
# AutoBattleAI。
#
# 【State 23｜Support AI】
# AutoBattleAI。
#
# 【State 25｜Balanced AI】
# AutoBattleAI。
# 注意：
#   舊Untargetable腳本也曾使用25，先前已確認有衝突風險。
#   目前正式規劃不要再拿25做其他用途。
