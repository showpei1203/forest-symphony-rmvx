# 【基準】
#  依據 All_Scripts_Export(7).txt Main 以上有效腳本。
#
# 【最高原則】
#  可以設計很多 State，但玩家真正需要記住的「核心戰鬥語言」
#  應控制在約 12～18 種。
#
#  其餘 State 應屬於：
#    ・角色專屬
#    ・Boss專屬
#    ・系統隱藏
#    ・少數特殊敵人
#
#  40個圖示一起亮著不叫深度，通常叫交通事故。
