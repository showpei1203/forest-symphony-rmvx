class Sprite_Picture < Sprite
  #--------------------------------------------------------------------------
  # ● フレーム更新(エイリアス)
  #--------------------------------------------------------------------------
  def update
    if @picture.name.is_a?(Array) and @picture.name[0].is_a?(String) and
       @picture_name != @picture.name
      # 文字ピクチャ
      @picture_name = @picture.name
      str27_update_2 if @picture_name != ""
    elsif @picture.name.is_a?(Array) and @picture.name[0].is_a?(Numeric) and
          @picture_name != @picture.name
      @picture_name = @picture.name[0]
      if @picture_name != ""
        self.bitmap.dispose if self.bitmap != nil and not @picture_name.is_a?(String)
      end
      self.bitmap = @picture.name[1].clone
      @picture.name[1].dispose
      @picture.name = @picture_name 
    elsif @picture_name != @picture.name
      # 通常ピクチャ
      @picture_name = @picture.name
      if @picture_name != ""
        self.bitmap.dispose unless @picture_name.is_a?(String)
        self.bitmap = Cache.picture(@picture_name)
      end
    end
    # 呼び戻し
    update_str27
  end
  #--------------------------------------------------------------------------
  # ● 解放
  #--------------------------------------------------------------------------
  alias str38_dispose dispose
  def dispose
    @picture_name = @picture.name = ""
    str38_dispose
  end
end
