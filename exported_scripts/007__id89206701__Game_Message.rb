class Game_Message
  #--------------------------------------------------------------------------
  # * 常數
  #--------------------------------------------------------------------------
  MAX_LINE = 4                            # 文本行數上限
  #--------------------------------------------------------------------------
  # * 宣告執行個體變數
  #--------------------------------------------------------------------------
  attr_accessor :texts                    # 整理文本（按行）
  attr_accessor :face_name                # 臉圖所在圖檔名
  attr_accessor :face_index               # 臉圖編號
  attr_accessor :background               # 視窗皮膚類型
  attr_accessor :position                 # 視窗顯示位置
  attr_accessor :main_proc                # 主回檔（進程）
  attr_accessor :choice_proc              # 顯示選項：回檔（進程）
  attr_accessor :choice_start             # 顯示選項：起始行
  attr_accessor :choice_max               # 顯示選項：選項條目數
  attr_accessor :choice_cancel_type       # 顯示選項：取消
  attr_accessor :num_input_variable_id    # 數字輸入：系統變數編號
  attr_accessor :num_input_digits_max     # 數字輸入：位數
  attr_accessor :visible                  # 顯示一個訊息
  #--------------------------------------------------------------------------
  # * 物件初始化
  #--------------------------------------------------------------------------
  def initialize
    clear
    @visible = false
  end
  #--------------------------------------------------------------------------
  # * 清零
  #--------------------------------------------------------------------------
  def clear
    @texts = []
    @face_name = ""
    @face_index = 0
    @background = 0
    @position = 2
    @main_proc = nil
    @choice_start = 99
    @choice_max = 0
    @choice_cancel_type = 0
    @choice_proc = nil
    @num_input_variable_id = 0
    @num_input_digits_max = 0
  end
  #--------------------------------------------------------------------------
  # * 判斷忙碌狀態
  #--------------------------------------------------------------------------
  def busy
    return @texts.size > 0
  end
  #--------------------------------------------------------------------------
  # * 新建文本頁
  #--------------------------------------------------------------------------
  def new_page
    while @texts.size % MAX_LINE > 0
      @texts.push("")
    end
  end
end
