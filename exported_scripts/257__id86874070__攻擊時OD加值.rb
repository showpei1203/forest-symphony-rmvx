#///        攻撃時に取得するオーバードライブゲージ増加量を変動させる
#///        装備やスキルを作る事が出来ます。
#///
#///     ◇ 装備品やスキルのメモ覧に <OdBonus +n> と記述します。
#///        攻撃時のオーバードライブゲージが、n の値分増えます。
#///        敵のメモ覧に <EnemyOdBonus +n>と記述すると、
#///        敵のオーバードライブ増加量も変動するはずです。(曖昧)
#    攻擊時的od獲取增加
#/// 技能、裝備<OdBonus +n>   敵人<EnemyOdBonus +n>
#//////////////////////////////////////////////////////////////////////////////

module Paramata
  
  module BaseItem     
    BONUS_OD_AT = /<OdBonus\s*([\+\-]?\d+)>/i
  end
  
  module ENEMY_PARAMETER
    ENEMY_OD_BONUS = 0  
  end

end

class RPG::BaseItem
  #--------------------------------------------------------------------------
  # ○ メモ判定
  #--------------------------------------------------------------------------
  def new_paramata_plus 
    @bonus_od_at = 0
    self.note.each_line { |line|
    case line      
    when Paramata::BaseItem::BONUS_OD_AT
      @bonus_od_at = $1.to_i       
    end
    }
  end
  #--------------------------------------------------------------------------
  # ○ BONUS_OD_AT
  #--------------------------------------------------------------------------
  def bonus_od_at
    new_paramata_plus
    return @bonus_od_at
  end      
end  
#==============================================================================
# ■ Game_Actor
#------------------------------------------------------------------------------
# 　アクターを扱うクラスです。このクラスは Game_Actors クラス ($game_actors)
# の内部で使用され、Game_Party クラス ($game_party) からも参照されます。
#==============================================================================

class Game_Actor < Game_Battler  
  #--------------------------------------------------------------------------
  # ○ オーバードライブボーナスの取得
  #--------------------------------------------------------------------------
  def bonus_od_at
    n = 0
    for item in equips.compact + skills.compact
      n += item.bonus_od_at
    end
    return n
  end      
end

#==============================================================================
# ■ RPG module
#==============================================================================

module RPG
    #----------------------------------------------------------------------
    # ● 敵オーバードライブ
    #----------------------------------------------------------------------
  
  class Enemy
    alias initialize_ENEMY_PARAMETER initialize
    def initialize
      initialize_ENEMY_PARAMETER
      @bonus_od_at = 0
    end
    attr_accessor :bonus_od_at
    #----------------------------------------------------------------------
    # ● 追加パラメータ
    #----------------------------------------------------------------------
    def bonus_od_at
      text = @note[/EnemyOdBonus\[\d+?]/]
      return Paramata::ENEMY_PARAMETER::ENEMY_OD_BONUS if text == nil
      return text[/\d+/].to_i
    end
  end
end

