# 　配列全般を扱う組み込みクラスです。
#==============================================================================

class Array
  #--------------------------------------------------------------------------
  # ● 要素の交換
  #    a : 要素1
  #    b : 要素2
  #--------------------------------------------------------------------------
  def change(a, b)
    # データを複製
    data = self.dup
    # 要素を交換する（self自体には変化がない）
    data[a] = self[b]
    data[b] = self[a]
    return data
  end
  #--------------------------------------------------------------------------
  # ● 要素の交換（破壊的）
  #    a : 要素1
  #    b : 要素2
  #--------------------------------------------------------------------------
  def change!(a, b)
    # データを複製
    data = self.dup
    # 要素を交換する（selfを直接書き換える）
    self[a] = data[b]
    self[b] = data[a]
  end
end
