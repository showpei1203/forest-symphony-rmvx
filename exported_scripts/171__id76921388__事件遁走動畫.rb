# ■ Numeric
#------------------------------------------------------------------------------
# 　数値全般を扱う組み込みクラスです。
#==============================================================================

class Numeric
  #--------------------------------------------------------------------------
  # ● 範囲内から乱数を得る
  #    min : 求められた最小の数値
  #--------------------------------------------------------------------------
  def mm_rand(min)
    return rand(self - min + 1) + min
  end
  #--------------------------------------------------------------------------
  # ● 求めた数値に対するパーセンテージを返す
  #    order : 求められた数値
  #--------------------------------------------------------------------------
  def rate(order)
    return 100 if order == 0 
    return (self * 100) / order
  end
end

