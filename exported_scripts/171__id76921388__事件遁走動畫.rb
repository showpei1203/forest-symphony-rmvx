# ☆ MINTO_Sprite_Character_01
#------------------------------------------------------------------------------
#   Sprite_Characterクラスの強化システムモジュールです。
#==============================================================================

module MINTO_Sprite_Character_01
  #--------------------------------------------------------------------------
  # ● オブジェクト初期化
  #    viewport : ビューポート
  #--------------------------------------------------------------------------
  def initialize(viewport)
    # 崩壊エフェクト用のデータを初期化
    self.collapse_type = 0
    self.collapse_duration = 0
    self.last_data = []
    # スーパークラスを実行 （継承先の処理に移行する）
    super(viewport)
  end
  #--------------------------------------------------------------------------
  # ● 崩壊エフェクトの開始
  #    type : 崩壊エフェクトの演出タイプ（0～4）
  #--------------------------------------------------------------------------
  def collapse_start(type)
    # 元の表示形式を保存
    self.last_data[0] = self.blend_type
    # 元の色を保存
    self.last_data[1] = self.color.dup
    # 崩壊エフェクト演出タイプを設定
    self.collapse_type = type
    # 崩壊エフェクト更新カウントを設定
    self.collapse_duration = 48
    # 表示形式を 加算 にする
    self.blend_type = 1
    # 崩壊エフェクトの色を設定
    self.color.set(255, 128, 128, 224)
    # 不透明度を 255（完全表示）にする
    self.opacity = 255
    # キャラクター側の崩壊エフェクト開始フラグを オフ にする
    self.character.collapse = false
  end
  #--------------------------------------------------------------------------
  # ● フレーム更新（崩壊エフェクト）
  #--------------------------------------------------------------------------
  def update_collapse
    # 崩壊エフェクトの更新カウントが 1 以上の場合
    if self.collapse_duration >= 1 then
      # 崩壊エフェクトの更新カウントを減らす
      self.collapse_duration -= 1
      # キャラクターの不透明度を更新カウントに応じて下げる
      self.opacity = 256 - (48 - self.collapse_duration) * 6
      # 崩壊エフェクトの更新カウントが 0 になった場合
      if self.collapse_duration == 0 then
        # 縦横のズーム倍率を初期化
        self.zoom_x = 0
        self.zoom_y = 0
        # 元の表示形式に戻す
        self.blend_type = self.last_data[0]
        # 元の色に戻す
        self.color = self.last_data[1].dup
        # 最終データをクリア
        self.last_data = []
      end
      # 崩壊エフェクトの演出を更新
      update_collapse_effect
    end
  end
  #--------------------------------------------------------------------------
  # ● フレーム更新（崩壊エフェクト演出）
  #--------------------------------------------------------------------------
  def update_collapse_effect
    # 崩壊エフェクト演出タイプに応じて分岐
    case self.collapse_type
    # 処理なし
    when 0 then
    # 演出 1
    when 1 then
      # ズーム補正（縦に伸ばす）
      self.zoom_x -= 0.05
      self.zoom_y += 0.03
    # 演出 2
    when 2 then
      # ズーム補正（横に伸ばす）
      self.zoom_x += 0.05
    # 演出 3
    when 3 then
      # 崩壊エフェクト更新カウントが 24 以上の場合
      if self.collapse_duration >= 24 then
        # ズーム補正（縮める）
        self.zoom_y -= 0.02
        self.zoom_x += 0.01
        # 横のズーム補正値が 0 以下にならないようにする
        self.zoom_y = [self.zoom_y, 0].max
        # 横のズーム補正値が 1.24 以上にならないようにする
        self.zoom_x = [self.zoom_x, 1.24].min
      # 崩壊エフェクト更新カウントが 24 未満の場合
      else
        # ズーム補正（縦に伸ばす）
        self.zoom_x -= 0.115
        self.zoom_y += 0.6
      end
    # 演出 4（処理に負荷がかかります）
    when 4 then
      # ズーム補正（回転させる）
      self.zoom_x -= 0.03
      self.zoom_y += 0.05
      # 回転度を修正
      self.angle += 7.5
    end
  end
  #--------------------------------------------------------------------------
  # ● フレーム更新
  #--------------------------------------------------------------------------
  def update
    # キャラクターが有効な場合
    if self.character.is_a?(Game_Character) == true then
      # キャラクター側の崩壊エフェクト開始フラグが オン の場合
      if self.character.collapse == true then
        # 崩壊エフェクトを開始
        self.collapse_start(self.character.collapse_type)
      end
      # 崩壊エフェクトを更新
      update_collapse
    end
    # スーパークラスを実行 （継承先の処理に移行する）
    super
  end
end
