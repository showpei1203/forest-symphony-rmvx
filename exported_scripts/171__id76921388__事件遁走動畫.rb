説明

イベントなどのマップ上のキャラクターに対して、
コラプスの演出を実行できるようになります。

コラプスを実行するには、
イベントのスクリプトで

$scene.call_collapse_effect(id, type)

と入力してください。

id はイベントキャラクターのID、
type は演出タイプをそれぞれ表しています。

なお、id 0 で「このイベント」、
id -1 で「プレイヤー」となります。

演出タイプには以下の5種類あります。

タイプ0
特に演出を行いません。

タイプ 1
敵が縦に細く伸びて消えます。

タイプ 2
敵が横に伸びて消えます。

タイプ 3
敵が一旦縦に縮んだ後、縦に細く伸びて消えます。

タイプ 4
敵が縦に細く伸びながら回転して消えます（処理に負荷がかかります）

記述例

$scene.call_collapse_effect(1, 1)

ID 1 のイベントに対し、キャラを縦に細く伸ばして消します。

$scene.call_collapse_effect(1, 2)
$scene.call_collapse_effect(2, 3)
$scene.call_collapse_effect(3, 4)

このように連続で記入することも可能です。

ただし、SEとすり抜けの処理はないので、
適当なタイミングでSEを鳴らし、
コラプス前にすり抜けをオンにしてください。

