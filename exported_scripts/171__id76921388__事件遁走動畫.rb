class Scene_Map < Scene_Base
  #--------------------------------------------------------------------------
  # ● 崩壊エフェクトの呼び出し
  #    id   : キャラクター（Sprite_Character）のID
  #    type : 崩壊エフェクトの演出タイプ（0～4）
