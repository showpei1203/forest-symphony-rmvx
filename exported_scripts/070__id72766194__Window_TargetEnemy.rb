class Window_TargetEnemy < Window_Command
  #--------------------------------------------------------------------------
  # * 物件初始化
  #--------------------------------------------------------------------------
  def initialize
    commands = []
    @enemies = []
    for enemy in $game_troop.members
      next unless enemy.exist?
      commands.push(enemy.name)
      @enemies.push(enemy)
    end
    super(416, commands, 2, 4)
  end
  #--------------------------------------------------------------------------
  # * 獲取敵人資訊
  #--------------------------------------------------------------------------
  def enemy
    return @enemies[@index]
  end
end
