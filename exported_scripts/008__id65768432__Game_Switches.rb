# ** Game_Switches
#------------------------------------------------------------------------------
#  這個類用來操控開關，是內建類“Array”的外殼。
#  這個類的實例被全域變數 $game_switches 所引用。
#==============================================================================

class Game_Switches
  #--------------------------------------------------------------------------
  # * 物件初始化
  #--------------------------------------------------------------------------
  def initialize
    @data = []
  end
  #--------------------------------------------------------------------------
  # * 獲取開關資訊
  #     switch_id : 開關編號
  #--------------------------------------------------------------------------
  def [](switch_id)
    if @data[switch_id] == nil
      return false
    else
      return @data[switch_id]
    end
  end
  #--------------------------------------------------------------------------
  # * 設置開關
  #     switch_id : 開關編號
  #     value     : ON[被開啟]（true）/ OFF[被關閉]（false）
  #--------------------------------------------------------------------------
  def []=(switch_id, value)
    if switch_id <= 5000
      @data[switch_id] = value
    end
  end
end
