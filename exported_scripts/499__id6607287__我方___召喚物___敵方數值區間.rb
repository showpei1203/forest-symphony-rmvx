# ===============================================================================
# 第八部　傷害公式對能力值的影響
# ===============================================================================
#
# 目前核心：
#
#   Power =
#     (使用者 ATK × atk_f + 使用者 SPI × spi_f) / 100
#
#   EffectiveDefense =
#     (目標 DEF × atk_f + 目標 SPI/MND × spi_f)
#     / (atk_f + spi_f)
#
#   Damage =
#     (BaseDamage + Power)
#     × 120 / (120 + EffectiveDefense)
#
# 再套：
#   ・穿透
#   ・暴擊 1.7 倍
#   ・多屬性乘算
#   ・Variance
#   ・Guard
#
# 因此：
#
# 1. DEF 不是線性減傷。
# 2. 高 DEF 不會讓傷害突然歸零。
# 3. BaseDamage 太低時，高等級技能會疲弱。
# 4. atk_f / spi_f 過高時，裝備與能力差異會被放大。
# 5. 一般單體核心技建議 atk_f / spi_f 120～220。
# 6. 重擊 220～320。
# 7. 大招 300～450，但必須有成本 / 條件 / 冷卻。
#
# ===============================================================================
# 第九部　EXP 系統：依目前實際生效的 FC EXP Controller 設計
# ===============================================================================
#
# 【目前真正生效的設定】
#
#   SPLIT_EXP         = true
#   EXP_METHOD        = 1
#   SET_NEED          = 100
#   SET_LEVEL_TYPE    = 1
#
# 意義：
#
# 1. 每個等級固定需要 100 EXP。
#
# 2. 敵人 EXP 會依：
#
#      敵人資料庫 EXP
#      ×
#      <exp at level x> 的 x
#      ÷
#      目前戰鬥隊伍平均等級
#
#   計算。
#
# 3. 戰鬥結束後，再把全體死亡敵人的 EXP 總和：
#
#      ÷ 戰鬥成員數
#
#   分給每名戰鬥成員。
#
# 4. KGC LargeParty 在戰鬥中：
#
#      $game_party.members
#
#   實際回傳 battle_members。
#
#   因此 FC EXP Controller 的分母是：
#
#      目前實際參戰人數
#
#   而不是所有待機角色。
#
# 5. 你的待機角色 EXP 比率：
#
#      STAND_BY_EXP_RATE = 1000
#
#   也就是待機角色會再取得相當於戰鬥成員的 100% EXP。
#
# 所以目前實際結果是：
#
#   ・參戰角色取得分攤後 EXP。
#   ・待機角色也取得同樣的分攤後 EXP。
#
# 這代表你目前的系統很適合維持大量主要角色與召喚物的等級同步，
# 不會因為沒出戰三小時就變成博物館藏品。
#
# ------------------------------------------------------------------------------
# 【FC EXP Controller 的真實公式】
# ------------------------------------------------------------------------------
#
# Enemy EXP：
#
#   AdjustedEnemyEXP =
#     floor(
#       DatabaseEXP
#       ×
#       ExpAtLevel
#       /
#       PartyAverageLevel
#     )
#
# 其中：
#
#   DatabaseEXP
#     = 敵人資料庫中的 EXP 欄位。
#
#   ExpAtLevel
#     = Enemy Note：
#
#         <exp at level 20>
#
#       若沒有寫，預設是 1。
#
#   PartyAverageLevel
#     = 目前戰鬥成員平均等級，因 SET_LEVEL_TYPE = 1。
#
# Troop EXP：
#
#   PerMemberEXP =
#     floor(
#       所有死亡且非隱藏敵人的 AdjustedEnemyEXP 總和
#       /
#       BattleMemberCount
#     )
#
# ------------------------------------------------------------------------------
# 【極重要：沒有 <exp at level x> 會發生什麼？】
# ------------------------------------------------------------------------------
#
# FC EXP Controller 預設：
#
#   @exp_at_level = 1
#
# 所以假設：
#
#   敵人資料庫 EXP = 60
#   隊伍平均 Lv50
#   沒寫 <exp at level x>
#
# 則：
#
#   60 × 1 / 50
#   = 1.2
#   → Game_Enemy#exp 最後 to_i
#   = 1 EXP
#
# 若有 6 名戰鬥成員：
#
#   1 / 6
#   = 0 EXP
#
# 也就是辛苦打一場，系統發給玩家一張精神獎狀。
#
# 所以使用 EXP_METHOD = 1 時：
#
#   幾乎所有會給 EXP 的正式敵人，
#   都應該寫：
#
#     <exp at level x>
#
# ------------------------------------------------------------------------------
# 【同等級敵人的簡化公式】
# ------------------------------------------------------------------------------
#
# 若：
#
#   <exp at level 30>
#   隊伍平均 Lv30
#
# 則：
#
#   AdjustedEnemyEXP = DatabaseEXP
#
# 因此每名角色實拿：
#
#   PerMemberEXP =
#     TroopDatabaseEXPTotal
#     /
#     BattleMemberCount
#
# 這讓數值設計非常直觀。
#
# 例如：
#
#   4人隊
#   3隻敵人
#   每隻資料庫 EXP = 24
#
# 總 EXP：
#
#   24 × 3 = 72
#
# 每名角色：
#
#   72 / 4 = 18 EXP
#
# 每級需要 100 EXP：
#
#   約 5.6 場這種戰鬥升 1 級。
#
# ------------------------------------------------------------------------------
# 【超過敵人推薦等級後，自然降低 EXP】
# ------------------------------------------------------------------------------
#
# 敵人：
#
#   Database EXP = 30
#   <exp at level 20>
#
# 隊伍平均 Lv20：
#
#   30 × 20 / 20
#   = 30
#
# 隊伍平均 Lv25：
#
#   30 × 20 / 25
#   = 24
#
# 隊伍平均 Lv40：
#
#   30 × 20 / 40
#   = 15
#
# 所以 FC Set Method 已經天然具有：
#
#   ・低等隊伍打高區域怪，EXP提高。
#   ・高等隊伍回頭刷低區域怪，EXP降低。
#
# 這非常適合 Forest Symphony。
#
# 不需要再額外用一堆腳本懲罰刷低等怪。
# FC 已經很有禮貌地替玩家說：
#
#   「你都 Lv40 了，真的還要欺負 Lv20 的草叢生物嗎？」
