# ===============================================================================
# 第十一部-E　整數截斷與0 EXP陷阱
# ===============================================================================
#
# Game_Enemy#exp 最後：
#
#   return result.to_i
#
# Game_Troop#exp_total 又會：
#
#   exp / $game_party.members.size
#
# Ruby 1.8 的整數除法會直接捨去小數。
#
# 所以：
#
#   5 EXP / 6人
#   = 0
#
# 因此設計時：
#
