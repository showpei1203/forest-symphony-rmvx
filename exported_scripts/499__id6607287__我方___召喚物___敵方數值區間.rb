# ===============================================================================
# 第十一部-C　FC EXP 與 YERD Enemy Level Control 的關係
# ===============================================================================
#
# 目前腳本順序：
#
#   FC EXP Controller
#   ↓
#   YERD Enemy Level Control
#
# YERD 後面 alias 了 Game_Enemy#exp。
#
# 所以實際順序是：
#
#   1. FC先算：
#
#        DatabaseEXP
#        × ExpAtLevel
#        / PartyLevel
#
#   2. YERD再套：
#
#        <growth exp +x%>
#        <growth exp +x>
#
# 目前：
#
#   GROWTH_EXP = 0
#
# 所以沒有寫 growth exp Note 時，
# 不會額外成長。
#
# 建議：
#
# 固定區域怪：
#   不寫 growth exp。
#
# 小幅跨區域成長怪：
#   <growth exp +1%>
#   或
#   <growth exp +1>
#
# 不建議：
#
#   <growth exp +10%>
#
# 因為Lv50：
#
#   100 + 49×10
#   = 590%
#
# FC本來已經在做等級縮放，
# 再加高百分比growth exp，會把平衡送去太空。
#
