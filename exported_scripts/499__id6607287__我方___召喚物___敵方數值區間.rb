# ===============================================================================
# 第十四部　最終設計原則
# ===============================================================================
#
# 1. Main 角色靠資料庫曲線，不需要硬套 Pokémon Base。
# 2. Pokémon 召喚物可直接參考 Attack / Defense / Speed。
# 3. SPI 必須融合 Sp.Atk / Sp.Def。
# 4. HP / MP 用專案專屬 Base。
# 5. 普通敵人不要靠 HP 當特色。
# 6. 菁英要有機制，Boss 要有節奏。
# 7. EXP 先看「每級需求」，再反推每場戰鬥。
# 8. 所有 Lv100 表格目前實際仍受 Lv99 clamp 限制。
#
# 真正的平衡不是讓所有數字差不多。
# 真正的平衡是：每個角色有清楚的長處，而沒有一個角色因為數字或機制，
# 讓其他五個人的存在變成一種禮貌。
