# ===============================================================================
# 第一部　先回答：召喚物 / 敵人直接套 Pokémon 種族值，適不適合？
# ===============================================================================
#
# 結論：
#
#   HP / MP：不建議直接照搬 Pokémon 原始數值。
#   ATK：適合直接參考 Pokémon Attack。
#   DEF：適合直接參考 Pokémon Defense。
#   AGI：適合直接參考 Pokémon Speed。
#   SPI：不能直接照搬單一 Pokémon 能力，因為本專案 SPI 同時牽涉
#        魔法輸出與魔法防禦，而 Pokémon 分成 Sp.Atk / Sp.Def。
#
# 【推薦 SPI 轉換】
#
# 1. 魔法攻擊型：
#    SPI種族值 = round(Sp.Atk × 0.65 + Sp.Def × 0.35)
#
# 2. 支援 / 魔防型：
#    SPI種族值 = round(Sp.Atk × 0.35 + Sp.Def × 0.65)
#
# 3. 均衡型：
#    SPI種族值 = round((Sp.Atk + Sp.Def) / 2)
#
# 不要直接取 max(Sp.Atk, Sp.Def)。
# 因為在本專案中，一個高 SPI 同時會提高魔攻與魔防，直接取高值會讓召喚物
# 免費得到兩份優勢。
#
# 【為什麼 HP / MP 不直接照搬？】
#
# 目前 HP / MP 公式：
#
#   Raw = ((2 × 種族值 + 31) / 100 × Lv) + Lv + 10
#
# 接著：
#
#   HP × 14.0
#   MP × 2.2
#
# 因此 Pokémon 原本的 HP Base Stat 在本專案不是「HP」，而比較像
# 「HP 成長種族係數」。
#
# MP 更不能照 Pokémon PP 直接轉，因為本專案 MP 是共用資源池，
# 而 Pokémon 每招 PP 是技能個別使用次數，概念完全不同。
#
# ===============================================================================
# 第二部　目前程式的真實成長公式
# ===============================================================================
#
# 【召喚物與敵人：ATK / DEF / SPI / AGI】
#
#   Final = floor(
#     ((2 × Base + 31) / 100 × Lv)
#     + Lv
#     + 5
#   )
#
# 【召喚物與敵人：HP / MP】
#
#   Raw = ((2 × Base + 31) / 100 × Lv) + Lv + 10
#
#   HP = floor(Raw × 14.0)
#   MP = floor(Raw × 2.2)
#
# 【重要：目前實際上限是 Lv99】
#
# 以下位置都把等級夾在 1～99：
#   ・YE::BATTLE::ENEMY::MAX_LEVEL = 99
#   ・ActorEnemyGrowth#albert_growth_level
#   ・HPMP_Scale_Growth#hpmp_raw
#
# 所以本文件雖以 Lv1～100 規劃，但「Lv100」在目前腳本等同 Lv99 終點。
#
# 若未來真的要開 Lv100，至少要同步改：
#   1. YE::BATTLE::ENEMY::MAX_LEVEL
#   2. albert_growth_level 的 99
#   3. hpmp_raw 的 99
#   4. Actor change_level / EXP 表相關上限
