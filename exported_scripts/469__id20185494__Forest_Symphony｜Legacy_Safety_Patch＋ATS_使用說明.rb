# ■ 三、事件編輯器三種背景樣式
#==============================================================================
#
# 地圖：
#
#   正常的視窗
#     ・使用 Default windowskin。
#     ・依文字長度自動調整寬度與高度。
#     ・普通 NPC 事件預設跟隨目前事件。
#     ・可顯示 ATS Speech Tag 小箭頭。
#
#   暗化背景
#     ・使用 MessageBack。
#     ・維持圖片原始尺寸，不依短句縮小。
#     ・依安全文字區自動換行。
#     ・預設尊重事件編輯器的上／中／下位置。
#     ・不會自動跟隨目前事件，除非明確呼叫 ats_speaker_event。
#
#   透明
#     ・不顯示 Default 或 MessageBack。
#     ・仍使用 ATS 原本的 Window contents 顯示文字。
#
# 戰鬥：
#
#   正常的視窗
#     ・使用 Default。
#     ・顯示在指定 battler 頭上。
#     ・顯示 Speech Tag。
#
#   暗化背景
#     ・使用 MessageBack。
#     ・固定大框與安全文字區。
#     ・不顯示 battler 頭頂小窗。
#
#   透明
#     ・使用原戰鬥訊息腳本建立的 @b_sprite。
#     ・背景圖片為 Battle_Message。
#     ・文字仍由原 Window_BattleMessage#contents 繪製。
#     ・不建立第二個文字 Sprite。
#
#==============================================================================
# ■ 四、ATS 對話設定指令
#==============================================================================
#
# 以下指令寫在事件「腳本」指令中。
#
#------------------------------------------------------------------------------
# 1. 自動尺寸＋自動換行
#------------------------------------------------------------------------------
#
#   ats_dialogue_auto
#
# 說明：
#   ・開啟 fit_window_to_text。
#   ・保留事件編輯器手動分行。
#   ・過長的繁中單行仍會自動換行。
#   ・此設定使用 ats_all，會持續生效。
#
#------------------------------------------------------------------------------
# 2. 固定尺寸＋自動換行
#------------------------------------------------------------------------------
#
#   ats_dialogue_fixed(544, 128)
#
# 參數：
#   第一個數字：Window 寬度。
#   第二個數字：Window 高度。
#
# 說明：
#   ・關閉自動尺寸。
#   ・仍保留自動換行。
#   ・此設定會持續生效。
#
#------------------------------------------------------------------------------
# 3. 開關自動換行
#------------------------------------------------------------------------------
#
#   ats_dialogue_wrap(true)   # 開啟
#   ats_dialogue_wrap(false)  # 關閉
#
#------------------------------------------------------------------------------
# 4. 恢復擴充版預設值
#------------------------------------------------------------------------------
#
#   ats_dialogue_reset
#
# 恢復：
#   ・正常背景使用 Default。
#   ・自動尺寸開啟。
#   ・繁中自動換行開啟。
#   ・paragraph_format 關閉，以保留事件編輯器手動分行。
#
# 重要：
#   只能在沒有正在顯示文字時使用。
#   本指令會執行 $game_message.clear，若在對話顯示途中使用會清掉當前文字。
#
#------------------------------------------------------------------------------
# 5. 文字速度
#------------------------------------------------------------------------------
#
#   ats_dialogue_speed(1)
#
# 常用：
#   -1 ＝立即顯示。
#    0 ＝最快逐字。
#    1 ＝目前預設。
#    數字越大越慢。
#
#------------------------------------------------------------------------------
# 6. Speech Tag 箭頭
#------------------------------------------------------------------------------
#
#   ats_dialogue_tag(0)   # 使用第 0 組箭頭
#   ats_dialogue_tag(-1)  # 關閉箭頭
#
#==============================================================================
# ■ 五、地圖說話者指令
#==============================================================================
#
#------------------------------------------------------------------------------
# 1. 恢復自動模式
#------------------------------------------------------------------------------
#
#   ats_speaker_auto
#
# 普通 NPC 事件會自動使用目前事件作為說話者。
#
#------------------------------------------------------------------------------
# 2. 指定事件
#------------------------------------------------------------------------------
#
#   ats_speaker_event
#
# 不填 ID：
#   使用目前事件。
#
#   ats_speaker_event(12)
#
# 指定 Event ID 12。
#
#   ats_speaker_event(12, 4)
#
# 第二個參數 char_ref：
#   0 ＝上方
#   1 ＝左側
#   2 ＝下方
#   3 ＝右側
#   4 ＝能放上方就放上方，否則放下方
#
#------------------------------------------------------------------------------
# 3. 指定玩家
#------------------------------------------------------------------------------
#
#   ats_speaker_player
#   ats_speaker_player(4)
#
#------------------------------------------------------------------------------
# 4. 關閉角色跟隨
#------------------------------------------------------------------------------
#
#   ats_speaker_none
#
# 對話改用事件編輯器設定的上／中／下位置。
#
#==============================================================================
# ■ 六、戰鬥說話者指令
#==============================================================================
#
# 指令必須在「顯示文字」之前執行。
#
#------------------------------------------------------------------------------
# 1. 指定 Actor
#------------------------------------------------------------------------------
#
#   ats_battle_actor(1)
#
# 使用資料庫 Actor ID 1。
#
#   ats_battle_actor(1, -12)
#
# 第二個參數為 Y 修正：
#   負數往上，正數往下。
#
#   ats_battle_actor(1, 0, false)
#
# 第三個參數 auto_name：
#   true  ＝若文字中沒有 \nb[]，自動使用 battler 名稱建立姓名框。
#   false ＝不自動建立姓名框。
#
#------------------------------------------------------------------------------
# 2. 指定 Enemy
#------------------------------------------------------------------------------
#
#   ats_battle_enemy(1)
#
# 使用敵群畫面中的第 1 隻敵人，從 1 開始。
#
#   ats_battle_enemy(2, -8, true)
#
#------------------------------------------------------------------------------
# 3. 使用 0-based Enemy index
#------------------------------------------------------------------------------
#
#   ats_battle_enemy_index(0)
#
# index 0 代表第 1 隻敵人。
# 一般事件建議使用較直覺的 ats_battle_enemy。
#
#------------------------------------------------------------------------------
# 4. 指定目前行動者
#------------------------------------------------------------------------------
#
#   ats_battle_active
#   ats_battle_active(-10, true)
#
# 讀取 Scene_Battle 的 @active_battler。
#
#------------------------------------------------------------------------------
# 5. 清除戰鬥說話者
#------------------------------------------------------------------------------
#
#   ats_battle_clear
#
# 建議一段戰鬥劇情結束後執行。
#
#------------------------------------------------------------------------------
# 6. 戰鬥背景選擇範例
#------------------------------------------------------------------------------
#
#   ats_battle_enemy(1)
#   顯示文字：背景樣式「正常的視窗」
#     → Enemy 頭頂 Default 小窗。
#
#   ats_battle_enemy(1)
#   顯示文字：背景樣式「暗化背景」
#     → 固定 MessageBack。
#
#   ats_battle_enemy(1)
#   顯示文字：背景樣式「透明」
#     → 原 Battle_Message 圖片＋原 contents。
#
#==============================================================================
# ■ 七、MessageBack 安全文字區
#==============================================================================
#
# 在 FS_ATS_DIALOGUE 中調整：
#
#   MESSAGEBACK_TEXT_LEFT = 36
#   MESSAGEBACK_TEXT_RIGHT = 24
#   MESSAGEBACK_FACE_RESERVE = 152
#   MESSAGEBACK_MIN_TEXT_WIDTH = 120
#
# 用途：
#   ・避開 MessageBack 左側裝飾。
#   ・有右側立繪時自動保留右側空間。
#   ・有左側立繪時自動保留左側空間。
#   ・換行以安全文字區實際像素寬度計算。
#
# 右側立繪：
#   ATS 的 FACE_SIDE = false。
#
# 左側立繪：
#   ATS 的 FACE_SIDE = true。
#
# 事件文字前不需要手動輸入大量空格。
#
#==============================================================================
# ■ 八、其他常用 ATS 原生指令
#==============================================================================
#
#   ats_all(:屬性, 值)
#     永久修改 $game_ats 與目前 $game_message。
#
#   ats_next(:屬性, 值)
#     只套用下一次顯示文字。
#
# 範例：
#
#   ats_next(:message_speed, -1)
#   ats_next(:speech_tag_index, -1)
#
# 注意：
#   :character 與 :char_ref 是 ATS 的 next-only 設定。
#   本擴充已提供 ats_speaker_event／player，通常不需要手寫 ats_next。
#
