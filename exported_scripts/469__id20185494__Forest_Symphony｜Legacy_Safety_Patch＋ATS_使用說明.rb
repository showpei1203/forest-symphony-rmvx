# ■ 十三、常見問題
#==============================================================================
#
# 1. 對話框仍使用舊行為
#    ・確認舊版 FS_ATS_DialogueExtension 已停用。
#    ・完整關閉 Game.exe 後重開。
#
# 2. 正常背景不是 Default
#    ・確認 Graphics/System/Default.png 存在。
#    ・確認 NORMAL_WINDOWSKIN = "Default"。
#
# 3. 暗化背景被縮小
#    ・確認 KEEP_DIM_IMAGE_NATIVE_SIZE = true。
#    ・確認 Graphics/System/MessageBack.png 存在。
#
# 4. 戰鬥透明背景沒有 Battle_Message
#    ・確認 Graphics/Pictures/Battle_Message.png 存在。
#    ・確認原戰鬥訊息腳本 GRAPHIC_NAME = "Battle_Message"。
#    ・確認原戰鬥訊息腳本位於本擴充上方。
#
# 5. 戰鬥透明背景有圖但沒有字
#    ・v1.7 直接沿用原 @b_sprite，不再重建 Battle_Message。
#    ・文字使用原 Window_BattleMessage#contents。
#    ・確認沒有其他放在 v1.7 下方的腳本再次修改
#      Window_BattleMessage#refresh／clear／contents_opacity。
#
# 6. ats_dialogue_reset 清掉文字
#    ・只能在兩段顯示文字之間使用。
#
# 7. 暗化背景不跟隨 NPC
#    ・這是預設設計。
#    ・需要跟隨時先執行 ats_speaker_event。
#
