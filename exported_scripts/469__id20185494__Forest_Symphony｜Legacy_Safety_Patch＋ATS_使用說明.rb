# ■ 十、大型飛行船視覺設定
#==============================================================================
#
# 在 FS_FLIGHT_VISUAL 中調整：
#
#   VEHICLE_TYPES = [4]
#
# 目前只處理乗り物擴張中的大型飛行船 type 4。
#
# Overlay 開關：
#
#   SHADOW_SWITCH  = 202
#   PAR_SWITCH     = 203
#   GROUND_SWITCH  = 204
#   SHADOW2_SWITCH = 205
#
# 起飛時自動：
#   ・記錄上述開關狀態。
#   ・關閉 Shadow／Par／Ground／Shadow2。
#   ・套用低透明度 Fog。
#
# 降落時自動：
#   ・等待真正開始降落。
#   ・恢復起飛前各開關狀態。
#   ・恢復地圖原本 Fog。
#
# Fog 設定：
#
#   FOG_TRANSITION = 60
#   FIRST_FOG_FADE_IN = 15
#   FOG_NAME = "fog"
#   FOG_SPEED_X = 1
#   FOG_SPEED_Y = 0
#   FOG_OPACITY = 35
#   FOG_BLEND = 0
#   RESTORE_TRANSITION = 60
#
# 原乗り物擴張腳本中的：
#
#   Shuu_Fog.change(60, "")
#
# 建議維持註解，避免原腳本與 SafetyPatch 同時控制 Fog。
#
# 原公共事件可移除：
#   ・Shuu_Fog.change(60,"fog",1,0,35,0)
#   ・Switch 202／203／204／205 的 OFF 操作
#
# 騎乘物選擇、召喚動畫、角色圖變更、等待、乘降指令仍可保留。
#
