# 腳本：Pokemon Action Sequences
# 系統：Tankentai Sideview Battle System（SBS）｜module N01
#
# 【用途】
# 本頁是寶可夢專用的 ANIME Key／ACTION Sequence 資料庫。它只描述「身體演出」：
# 姿勢、移動、浮空、回位、強制動作、目標修改、技能連結、條件、角度、縮放、動畫、
# 飛行圖、音效、狀態、Cut-In、Switch／Variable 等。技能傷害、命中、狀態成功率等真正
# 戰鬥結果仍由 SBS／Battle Runtime／FS Authority 處理。
#
# 【最重要規則】
# 1. Hash 左側字串就是 Action Key API。資料庫技能、其他 SBS 腳本或 FS Bridge 可能直接
#    引用這些字串；除非同步反查全部引用，否則不要改名。
# 2. POKEMON_ANIME_KEYS 定義單一步驟；POKEMON_ACTION_SEQUENCES 定義步驟組合。
# 3. Reset 類 Key 代表該 battler 的回合／動作結束；Reset 後不要再安排造成傷害的步驟。
# 4. 本頁是演出資料，不要在這裡加入會繞過正式 Authority 的傷害／ATB／狀態邏輯。
#
# 【Battler Pose 格式】
# [FileNo, Row, Speed, Loop, Wait, Fixed, Z, Shadow, WeaponKey]
# FileNo：0 使用預設 Walking Graphic；n 使用「角色圖名_n」。
# Row   ：角色圖第幾列，0 為最上列。
# Speed ：換 frame 速度，數字越小越快。
# Loop  ：0 往返；1 單向循環；2 播放一次。
# Wait  ：再次循環前等待 frame；Loop=2 不使用。
# Fixed ：-2 反向循環（武器動畫亦反向）；-1 正常循環；0～2 固定顯示指定 frame。
# Z     ：追加至 battler 的 Z 優先度。
# Shadow：是否顯示影子。
# WeaponKey：搭配的武器 Sprite Animation Key；無則 ""。
#
# [Xa, Ya, Za, A1, A2, Origin, Invert, XScale, YScale, XPitch, YPitch, Weapon2]
# Xa/Ya：武器 Sprite 位移；Y 軸負值向上、正值向下。
# Za    ：true 在 battler 前方，false 在後方。
# A1/A2：起始／結束角度；負值逆時針。
# Origin：0 中心、1 左上、2 右上、3 左下、4 右下。
# Invert：水平翻轉。Scale 可用小數。Pitch 是初始座標修正。
# Weapon2：true 時使用雙持第二武器 Sprite。
#
# [Origin, X, Y, Time, Accel, Jump, AnimationKey]
# Origin：0目前位置、1目標中心、2螢幕、3起始位置、4目標頭部、5目標腳部。
# X/Y：相對 Origin 的像素位移；Y 負值向上。
# Time：移動時間，越大越慢。Accel 正值加速、負值減速。
# Jump：負值一般拋物線跳躍，正值反向弧線，0 不跳。
# AnimationKey：移動中使用的姿勢 Key。
#
# ["float", StartHeight, EndHeight, Time, AnimationKey]
# 高度負值向上；EndHeight 會維持到其他 Action 再改變。
#
# ["reset", Time, Accel, Jump, AnimationKey]
# 把 battler 返回起始座標；距離會影響視覺速度。此步驟通常代表該動作完成。
#
# 可指定 Actor／Enemy／State／學會特定 Skill 的 battler 強制執行某 ANIME/ACTION Key，
# 並設定結束後是否回原位。原格式內的 Object、Reset Type 與 Key 請依下方資料欄位使用。
# Skill 篩選可用「負號 + Skill ID」；這是原 SBS 的識別規則，不可翻譯改字串。
#
# 修改後續 Action 的目標：0=Self、1=Self 原目標、2=修改後目標、3=還原先前目標。
# 可依 Actor／Enemy／State 等條件指定對象。
#
# ["der", Chance, Learned?, SkillID]
# Chance：連結成功率；Learned? 為 false 時 Actor 必須真的學會 SkillID。
# 連結技能會沿用目前動作流程，因此不要繞過正式技能效果判定。
#
# 條件可檢查 State、Parameter、Switch、Variable、Skill；Object 可指定 Self／Target。
# State／Skill 條件可要求符合的 battler 數量；Switch 使用 true/false；Variable 正值表示
# 至少達到門檻，負號形式表示小於門檻。條件成功後再執行指定 Key。
#
# Sprite Angle：指定起始角、終止角與時間；武器不會自動跟著角色旋轉。
# Sprite Zoom ：暫時縮放 battler，可設定是否恢復原比例。
#
# 此類 Key 可以播放資料庫 Animation，並決定是否實際套用 Weapon／Skill／Item 的效果。
# ID 的特殊負值可要求使用裝備武器動畫、Weapon2 或只套用傷害。這一區是少數會觸發
# 正式效果套用的 SBS Action，修改前必須查原 Tankentai 定義與 FS Battle Authority。
#
# Moving Animation 會把 Animation／飛行圖從起點移向指定目標，可設定通過目標、時間、
# 弧線、偏移、起點與 Z。Flying Graphic Angle 只控制飛行 Weapon／Skill 圖形的旋轉。
#
# 【其他 Action 類型】
# Balloon       ：使用 Graphics/System/Balloon.png 指定列與循環。
# Sound Effects ：播放指定 SE。
# State Grant   ：對 Self／Target／全敵／全友附加 State ID。
# State Remove  ：解除 State ID。
# Change Graphic：暫時／持續替換 battler 圖形。
# Cut-In        ：顯示 Graphics/Pictures 內圖片。
# Switch Control：直接 ON/OFF 資料庫 Switch。
# Variable Ctrl ：直接操作資料庫 Variable。
#
# 【範例】
# 「寶可夢普攻前進動作」先依目標腳部 Origin=5 位移，再配合「寶可夢普攻前進姿勢」。
# 新增動作時建議：先建立 Pose Key → Movement／Animation Key → 最後在
# POKEMON_ACTION_SEQUENCES 內按順序組合，並保留既有回位／收勢 Key。
#
# 【素材】
# 角色圖、武器圖、Balloon、Cut-In、動畫圖等由 SBS Key、資料庫與 N01 設定間接讀取；
# 不要只因本頁沒有固定完整檔名就刪素材。
