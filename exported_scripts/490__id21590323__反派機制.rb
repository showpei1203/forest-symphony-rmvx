#  Forest Symphony 森之交響曲
#  AntagonistMechanicCore_v1_0 導入後的設計影響分析
#-------------------------------------------------------------------------------
# 【用途】
#  純註釋文件，可直接放進 RPG Maker VX 腳本庫。
#  用來回答：
#    1. 新反派核心到底改變了哪些既有設計？
#    2. 哪些文件必須更新？
#    3. 哪些系統其實不必重算？
#    4. 玩家 Build 與 Boss 設計要如何重新定位？
#
# 【新核心的四大共用反派機制】
#    ・觀律：懲罰重複技能／重複屬性。
#    ・雙弦：兩名 Actor 連結，按實際 HP 損失造成連帶傷害。
#    ・改譜：依 Actor ID 套用不同 State。
#    ・大諧律：每若干有效行動輪替法則 State。
#===============================================================================
# ===============================================================================
# 第一部　先下結論：哪些設計受影響？
# ===============================================================================
#
# 【重大影響，必須更新】
#
# 1. 敵方 AI／Boss 設計
# 2. 敵方技能設計
# 3. State 設計與 State ID 規劃
# 4. 玩家 Build／Combo 的後期適應層
# 5. Note Tag 參考庫
# 6. 保護 ID 清單
#
# 【中度影響，可補充但不用重算底層】
#
# 7. 裝備／物品
#    原本的 Mana Shield、解除異常、單體救援價值提高。
#    但不需要重算全部裝備能力。
#
# 8. Battle State HUD
#    新 State 120、121、130～135、139～143、150～152
#    都應有正確 HUD priority/detail。
#    但 HUD 核心顯示方式不需要因此重寫。
#
# 【基本不受影響】
#
# 9. 六主角基礎成長數值
# 10. Pokémon 種族值公式
# 11. FC EXP Controller
# 12. JP 升級公式
# 13. 一般武器／防具 Tier 數值
# 14. HP／MP Scale Growth
#
# 原因：
#   AntagonistMechanicCore 改的是「戰鬥規則與決策」，
#   沒有直接改寫角色成長公式、EXP公式或傷害基礎公式。
#
# 人類很喜歡看到新系統就重算所有數字。
# 有時這叫嚴謹，有時只是把整間房子拆掉，因為換了一盞燈。
#
# ===============================================================================
# 第二部　觀律對既有設計的影響
# ===============================================================================
#
# 腳本固定 Note：
#
# <observe_repeat_state:120>
#   重複行為時，對行動者增加 State 120。
#
# <observe_same_skill:1>
#   重複同一技能時增加 1 層。
#
# <observe_same_element:1>
#   重複同一屬性時增加 1 層。
#
# <observe_stack_both>
#   同技能與同屬性可同時累積。
#
# <observe_if_state:150>
#   只有 Boss 擁有 State 150 時才啟動觀律。
#
# <observe_main_actors_only>
#   只觀察主要 Actor 1～6。
#
# 【對玩家 Build 的改變】
#
# 以前：
#   找到最高效率技能
#   → 重複使用
#   → Build穩定。
#
# 現在：
#   同一技能重複
#   → 被觀律記錄。
#   同一屬性重複
#   → 被觀律記錄。
#   技能與屬性都重複
#   → 若有 observe_stack_both，可能一次加兩層。
#
# 所以後期 Build 不能只問：
#
#   「哪招最痛？」
#
# 還要問：
#
#   「我能不能用另一招、另一屬性、另一名角色，
#    在不破壞引擎的情況下繼續推進？」
#
# 【對召喚物的影響】
#
# 因為：
#   <observe_main_actors_only>
#
# 代表 Actor 1～6 受觀察，
# 召喚物 Actor 7+ 可以成為「節奏緩衝」。
#
# 因此喬伊的價值反而提高：
#
#   主角A重複技能快累積觀律
#   → 讓召喚物接棒
#   → 另一名主角改用不同屬性
#   → 再回原本技能
#
# 這讓「3人類＋3召喚物」真正變成節奏工具，
# 而不是六個單位輪流按傷害最大的招。
#
# 【最受影響的既有 Build】
#
# 高度受影響：
#   ・毒爆處刑
#   ・時間監獄
#   ・破防追擊
#   ・共鳴風暴
#
# 原因：
#   這些 Build 原本容易依賴少數核心技能反覆循環。
#
# 中度受影響：
#   ・腐敗森林
#   ・雷雨鎖鏈
#   ・魔力永動
#
# 較低影響：
#   ・怒海堡壘
#   ・混成標準隊
#
# ===============================================================================
# 第三部　雙弦對既有設計的影響
# ===============================================================================
#
# Skill Note：
#
# <double_thread:121,40>
#
# 腳本固定意義：
#   ・技能命中的前兩名 Actor 被綁定。
#   ・121 = 雙弦標記 State。
#   ・40 = 連帶傷害比例 40%。
#
# 真正計算：
#   某一名被連結 Actor 實際失去 HP
#   → 另一名連結 Actor 額外承受該實際 HP 損失的 40%。
#
# 不是：
#   原始傷害 × 40%。
#
# 所以：
#   Guard
#   Cover
#   Mana Shield
#   減傷
# 先降低真正 HP 損失，
# 再計算雙弦連帶傷害。
#
# 這一點非常重要。
#
# 【為什麼米亞的 Mana Shield 變強？】
#
# 例如原始傷害 1000。
#
# 沒有盾：
#   Actor A實損1000
#   Actor B連帶400
#
# 有盾後：
#   A實際只失500
#   B連帶200
#
# 所以 Mana Shield 對雙弦是天然反制。
#
# 【艾薇 Cover 的影響】
#
# Cover可能改變誰真正吃到原始傷害。
# 雙弦又看「實際 HP 損失」。
#
# 因此：
#   艾薇是否Cover
#   → 誰真正受傷
#   → 雙弦連帶量
# 都會改變。
#
# 這讓艾薇的決策更高價值，
# 但也必須小心艾薇自身若就是雙弦對象，
# 高額承傷可能反過來拖死另一個隊友。
#
# 【致死規則】
#
# <double_thread_lethal>
#   允許雙弦連帶傷害致死。
#
# 沒有此Note：
#   預設連帶傷害最多保留 1 HP。
#
# 因此Boss技能設計時，
# lethal 不應隨便常駐。
#
# 建議：
#   普通／菁英：不致死。
#   中後期Boss終結技：可致死。
#   最終Boss特定法則：可致死。
#
# ===============================================================================
# 第四部　改譜對既有設計的影響
# ===============================================================================
#
# Skill Note：
#
# <rewrite_actor 1:130>
# <rewrite_actor 2:131>
# <rewrite_actor 3:132>
# <rewrite_actor 4:133>
# <rewrite_actor 5:134>
# <rewrite_actor 6:135>
#
# <rewrite_default_state:139>
#
# 意義：
#   技能命中 Actor 1～6 時，
#   按 Actor ID 套用不同 State。
#
# 例如：
#   喬伊 Actor 1 → State 130
#   米亞 Actor 2 → State 131
#   艾卓 Actor 3 → State 132
#   維娜 Actor 4 → State 133
#   艾薇 Actor 5 → State 134
#   泰勒 Actor 6 → State 135
#
# 其他 Actor：
#   → State 139
#
# 【這改變了什麼？】
#
# 以前 Boss 的 Debuff 大多是：
#
#   攻擊降低
#   防禦降低
#   麻痺
#   中毒
#
# 改譜允許：
#
#   同一招
#   → 對六名主角產生六種不同結果。
#
# 因此 Boss 能真正「針對角色人格與機制」。
#
# 但有一條底線：
#
#   改譜 State 不應直接封印整個角色核心。
#
# 例如：
#   不要讓喬伊完全不能追擊。
#   不要讓艾卓所有 ATB 技能無效。
#   不要讓維娜所有 State 必定失敗。
#   不要讓泰勒完全不能Break。
#
# 那不是反制，是拔掉角色的控制器。
#
# 正確方向：
#   降低效率
#   改變節奏
#   迫使換招
#   要求解除或轉換
#
# ===============================================================================
# 第五部　大諧律對既有設計的影響
# ===============================================================================
#
# Enemy Note：
#
# <law_cycle_states:140,141,142,143>
# <law_cycle_actions:2>
# <law_cycle_if_state:151>
#
# 意義：
#
#   Boss只有擁有 State 151 時，
#   每完成 2 次有效行動，
#   依序切換：
#
#     140
#     ↓
#     141
#     ↓
#     142
#     ↓
#     143
#     ↓
#     140
#
# 【這不是一般 Buff 輪替】
#
# 最好的用途不是：
#
#   140 ATK+10%
#   141 DEF+10%
#   142 SPI+10%
#   143 AGI+10%
#
# 那太像一個非常勤奮的 Excel。
#
# 更好的做法：
#
#   State 140～143 作為「法則旗標」。
#
# Boss AI依目前 State，
# 選擇不同技能／反制規則。
#
# 建議：
#
# 140 觀測律
#   ・反重複
#   ・觀律爆發
#   ・針對高觀律層目標
#
# 141 鎮壓律
#   ・ATB
#   ・雙弦
#   ・召喚物威脅
#   ・防守
#
# 142 改譜律
#   ・Rewrite
#   ・State轉換
#   ・角色差異化Debuff
#
# 143 歸一律
#   ・高壓AOE
#   ・連鎖
#   ・終結
#   ・強迫全隊處理生存
#
# 玩家要看懂：
#   「現在是哪一律？」
#
# 然後改變操作。
#
# 這才叫法則循環。
#
# ===============================================================================
# 第六部　賽勒斯三階段與既有 Boss 設計的整合
# ===============================================================================
#
# 【第一階段｜全知儀】
#
# State 150：
#   全知儀啟動。
#   觀律功能生效。
#
# Enemy Note：
#   <observe_repeat_state:120>
#   <observe_same_skill:1>
#   <observe_same_element:1>
#   <observe_stack_both>
#   <observe_if_state:150>
#   <observe_main_actors_only>
#
# 玩家問題：
#   如何保持Build效率，又避免重複模式？
#
# 【第二階段｜大諧律】
#
# State 151：
#   啟動法則循環。
#
# Enemy Note：
#   <law_cycle_states:140,141,142,143>
#   <law_cycle_actions:2>
#   <law_cycle_if_state:151>
#
# 玩家問題：
#   現在應該進攻、控制、解狀態，還是保命？
#
# 【第三階段｜失奏】
#
# State 152：
#   進入失奏。
#
# 規則：
#   ・移除 State 151。
#   ・清除 140～143。
#   ・大諧律循環停止。
#
# 設計方向：
#   第三階段不應只是數字+50%。
#
# 真正應該是：
#   賽勒斯失去完美秩序，
#   戰鬥變得更直接、更不穩定、更危險。
#
# ===============================================================================
# 第七部　哪些既有文件需要更新？
# ===============================================================================
#
# 【已更新】
#
# 1. All NoteTags
#    加入 AntagonistMechanicCore 所有 Note。
#
# 2. Protected IDs
#    新增 120、121、130～135、139～143、150～152。
#
# 3. Enemy AI Design
#    新增三律席／賽勒斯的 AI 結構與玩家反制。
#
# 4. Full Skill Design
#    新增完整反派技能庫。
#
# 5. All States Design
#    新增所有 Antagonist State。
#
# 6. Builds / Combos
#    新增「抗觀律適應層」與反派戰對應。
#
# 【暫時不需要重寫】
#
# 7. StatGrowth / FC EXP
#    不受核心直接改寫。
#
# 8. Equipment / Items
#    核心數值不用重算。
#    但原本的：
#      Mana Shield
#      單體治療
#      解除State
#    在雙弦／改譜戰中價值提高。
#
# 9. Variables / Switches
#    目前已知這支核心以 Note / State 為主。
#    沒有證據需要新增 Variable / Switch 保留區。
#
# ===============================================================================
# 第八部　最重要的總結
# ===============================================================================
#
# AntagonistMechanicCore 對設計最大的改變是：
#
#   以前 Boss 主要反制角色能力。
#
# 現在 Boss 可以反制：
#
#   ・玩家的重複習慣
#   ・隊伍的HP關係
#   ・不同角色的身份
#   ・玩家的時間節奏
#
# 所以往後設計 Boss 時，
# 不應再只問：
#
#   「Boss要有多少HP？」
#   「大招BaseDamage多少？」
#
# 而要問：
#
#   「這場戰鬥要求玩家改變哪一種習慣？」
#
# 這才是反派機制真正值得存在的原因。
