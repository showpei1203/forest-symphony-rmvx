=begin

  ※このスクリプトは月紳士の「エネミー行動パターン改良」に
  　新たな行動条件を追加する拡張スクリプトです。
 　 「エネミー行動パターン改良」(Ver8.00以降)が必要となります。
  　このスクリプトは「エネミー行動パターン改良」より下に挿入してください。
  
  ○ 新たな行動条件の追加。
　　エネミーの行動パターンに、さらなる行動条件を追加します。
　　追加できるのは
    ・特定のステートになっている者のみを対象とする行動条件
    ・特定のステートになっていない者のみを対象とする行動条件
    の二種類です。
    
    追加する行動条件の数は任意で、カスタマイズ項目にて
    行動条件にするステートを登録した後、
    登録した行動条件に合わせたスイッチを用意することで
    設定します。
    
    詳しくはカスタマイズ項目をご覧ください。
    
=end
#==============================================================================
# ■ エネミー行動パターン行動条件追加：対象のステート・モジュール
#==============================================================================
module EacAdd_State_Condition

 # カスタマイズ項目------------------------------------------------------------
  
  TOP_SWITCH = 150
       #↑# 「行動条件追加：対象のステート」に使用するスイッチ郡の、
          # 最初の番号をここで指定します。
          # 「エネミー行動パターン改良」の元もとのスイッチ郡と
          # つなげる必要はありません。
          # ゲーム中の判定に差し支えない番号にしてください。
          
  SETTING = [2, -2, 3, -3]
       #↑# 行動条件追加にしたいステートをここで設定してください。
          # 行動条件の設定数は任意です。 , (半角カンマ)で区切ってください。
          #          
          # ここで指定する数字は、行動条件にあげたいステートのIDです。
          # そのステートになっている者を対象とする行動条件として設定します。
          # 数字に“-”(半角マイナス)をつけますと、
          # そのステートになっていない者を対象とする行動条件となります。
          #
          # 条件を満たす対象がいれば行動条件を満たし、それを狙います。
          # 対象がいなければ行動条件を満たさず、その行動も選ばれません。
          
=begin

　SETTINGで設定した順番に対応させ、
  TOP_SWITCHから順番に設定数と同じ数のスイッチを用意してください。
  例をあげて説明しますと…

　毒ステート(ID:2)を行動条件にしたい場合で
　TOP_SWITCH = 21
　SETTING = [2, -2]
　と設定したのであれば、
　スイッチ21が「毒に犯された者を対象とする」行動条件、
　スイッチ22が「毒に犯されていない者を対象とする」行動条件となります。

　スイッチの名前は任意でかまいません。製作中にわかりやすい名前にしてください。
    
=end
 # ------------------------------------------------(カスタマイズ項目ここまで)--
 
  SWITCHES_RANGE = TOP_SWITCH...(TOP_SWITCH + SETTING.size)
  
 # ----------------------------------------------------------------------------
end

