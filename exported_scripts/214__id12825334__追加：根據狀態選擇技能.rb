# ■ Game_Temp
#------------------------------------------------------------------------------
# 　セーブデータに含まれない、一時的なデータを扱うクラスです。このクラスのイン
# スタンスは $game_temp で参照されます。
#==============================================================================

class Game_Temp
  #--------------------------------------------------------------------------
  # ◎ 拡張行動条件に使用するスイッチデータの作成
  #--------------------------------------------------------------------------
  alias tig_eac_sc_make_ex_conditions_switches make_ex_conditions_switches
  def make_ex_conditions_switches
    switches = Array.new(EacAdd_State_Condition::SETTING.size){|i|i+EacAdd_State_Condition::TOP_SWITCH}
    return tig_eac_sc_make_ex_conditions_switches + switches
  end
end

#==============================================================================
# ■ Game_BattleAction
#------------------------------------------------------------------------------
# 　戦闘行動を扱うクラスです。このクラスは Game_Battler クラスの内部で使用され
# ます。
#==============================================================================

class Game_BattleAction
  #--------------------------------------------------------------------------
  # ◎ 条件にあうターゲットグループの取得
  #--------------------------------------------------------------------------
  alias tig_eac_sc_conditions_targets conditions_targets
  def conditions_targets(arrays, skill)
    targets = tig_eac_sc_conditions_targets(arrays, skill)
    for array in arrays ; next if array[0] != 6
      if EacAdd_State_Condition::SWITCHES_RANGE.include?(array[1])
        new_targets = []
        index = array[1] - EacAdd_State_Condition::TOP_SWITCH
        state_id = EacAdd_State_Condition::SETTING[index]
        if state_id > 0
          for target in targets
            next unless target.state?(state_id)
            new_targets.push(target)
          end
        elsif state_id < 0
          state_id = state_id.abs 
          for target in targets
            next if target.state?(state_id)
            new_targets.push(target)
          end
        end
        targets = new_targets
      end
    end
    return targets
  end
end