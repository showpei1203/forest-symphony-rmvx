class Sprite_Battler < Sprite_Base
  #--------------------------------------------------------------------------
  # ● 新しいエフェクトの設定
  #--------------------------------------------------------------------------
  alias setup_new_effect_KGC_AdjustBattleWait setup_new_effect
  def setup_new_effect
    self.visible = true

    setup_new_effect_KGC_AdjustBattleWait
  end
end

