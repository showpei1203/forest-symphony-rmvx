#==============================================================================
# □ KGC::Commands
#==============================================================================

module KGC
module Commands
  module_function
  #--------------------------------------------------------------------------
  # ○ バトルウェイト設定
  #     battle_wait : バトルウェイト
  #--------------------------------------------------------------------------
  def set_battle_wait(battle_wait)
    $game_system.battle_wait = [battle_wait, 0].max
  end
end
end

class Game_Interpreter
  include KGC::Commands
end

