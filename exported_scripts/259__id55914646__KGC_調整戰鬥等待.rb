#==============================================================================
# ■ Scene_Battle
#==============================================================================

class Scene_Battle < Scene_Base
  #--------------------------------------------------------------------------
  # ● 一定時間ウェイト
  #--------------------------------------------------------------------------
  alias wait_KGC_AdjustBattleWait wait
  def wait(duration, no_fast = false)
    duration = [duration * $game_system.battle_wait / 100, 1].max

    wait_KGC_AdjustBattleWait(duration, no_fast)
  end
end
