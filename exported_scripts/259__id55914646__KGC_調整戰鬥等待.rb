#==============================================================================
# ■ Game_System
#==============================================================================

class Game_System
  #--------------------------------------------------------------------------
  # ● 公開インスタンス変数
  #--------------------------------------------------------------------------
  attr_writer   :battle_wait              # 戦闘時のウェイト倍率
  #--------------------------------------------------------------------------
  # ○ 戦闘時のウェイト倍率取得
  #--------------------------------------------------------------------------
  def battle_wait
    if @battle_wait != nil
      return @battle_wait
    else
      return KGC::AdjustBattleWait::INITIAL_WAIT
    end
  end
end

