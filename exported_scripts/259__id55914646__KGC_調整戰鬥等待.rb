module KGC
module AdjustBattleWait
  # ◆ デフォルトのウェイト倍率
  #  100 が標準値。
  #  小さいほど短く（速く）、大きいほど長く（遅く）なる。
  INITIAL_WAIT = 70
end
end

#★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★☆★

