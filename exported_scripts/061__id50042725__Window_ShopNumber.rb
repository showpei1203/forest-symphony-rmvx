# ** Window_ShopNumber
#------------------------------------------------------------------------------
#  本視窗顯示于交易畫面中，用於輸入單向交易的某件物品的數量。
#==============================================================================

class Window_ShopNumber < Window_Base
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     x      : 視窗X座標
  #     y      : 視窗Y座標
  #--------------------------------------------------------------------------
  def initialize(x, y)
    super(x, y, 544, 224)#304 304
    @item = nil
    @max = 1
    @price = 0
    @number = 1
  end
  #--------------------------------------------------------------------------
  # * 設置交易品、交易數量上限和售價
  #--------------------------------------------------------------------------
  def set(item, max, price)
    @item = item
    @max = max
    @price = price
    @number = 1
    refresh
  end
  #--------------------------------------------------------------------------
  # * 設置輸入的交易品數量資訊
  #--------------------------------------------------------------------------
  def number
    return @number
  end
  #--------------------------------------------------------------------------
  # * 更新顯示內容
  #--------------------------------------------------------------------------
  def refresh
    y = 96 - 20
    self.contents.clear
    draw_item_name(@item, 0+125, y)
    self.contents.font.color = normal_color
    self.contents.draw_text(212+125, y, 20, WLH, "×")
    self.contents.draw_text(248+125, y, 20, WLH, @number, 2)
    self.cursor_rect.set(244+125, y, 28, WLH)
    draw_currency_value(@price * @number, 4+125, y + WLH * 2, 264)
  end
  #--------------------------------------------------------------------------
  # * 更新幀
  #--------------------------------------------------------------------------
  def update
    super
    if self.active
      last_number = @number
      if Input.repeat?(Input::RIGHT) and @number < @max
        @number += 1
      end
      if Input.repeat?(Input::LEFT) and @number > 1
        @number -= 1
      end
      if Input.repeat?(Input::UP) and @number < @max
        @number = [@number + 10, @max].min
      end
      if Input.repeat?(Input::DOWN) and @number > 1
        @number = [@number - 10, 1].max
      end
      if @number != last_number
        Sound.play_cursor
        refresh
      end
    end
  end
end
