class TPet_Item < Sprite
  #--------------------------------------------------------------------------
  # ● 公開インスタンス変数
  #--------------------------------------------------------------------------
  attr_reader :real_x
  #--------------------------------------------------------------------------
  # ● オブジェクト初期化
  #--------------------------------------------------------------------------
  def initialize(item)
    super(nil)
    @item = item
    @real_x = (rand(TPET::HOUSE_W - 24) + TPET::HOUSE_X) << 3
    @real_y = TPET::HOUSE_Y << 3
    self.x = @real_x >> 3
    self.y = @real_y >> 3
    self.bitmap = Cache.system("Iconset")
    self.src_rect = Rect.new(@item.icon_index % 16 * 24, @item.icon_index / 16 * 24, 24, 24)
  end
  #--------------------------------------------------------------------------
  # ● フレーム更新
  #--------------------------------------------------------------------------
  def update
    @real_y += 64
    dy = (TPET::HOUSE_Y + TPET::HOUSE_H - 32 - 8) << 3
    @real_y = dy if @real_y > dy
    self.y = @real_y >> 3
  end
  #--------------------------------------------------------------------------
  # ● アイテムのメモを返す
  #--------------------------------------------------------------------------
  def get_note
    if @item.is_a?(RPG::Item)
      note = $data_items[@item.id].note
    elsif @item.is_a?(RPG::Weapon)
      note = $data_weapons[@item.id].note
    else
      note = $data_armors[@item.id].note
    end
    return note
  end
  #--------------------------------------------------------------------------
  # ● アイテムの経験値を返す
  #--------------------------------------------------------------------------
  def get_exp
    if get_note =~ /<EXP=(\d+)\s*>/i
      return $1.to_i
    else
      return TPET::ITEM_EXP
    end
  end
  #--------------------------------------------------------------------------
  # ● アイテムのカロリー（満腹度）を返す
  #--------------------------------------------------------------------------
  def get_cal
    if get_note =~ /<CAL=(\d+)\s*>/i
      return $1.to_i
    else
      return TPET::ITEM_EXP
    end
  end
end

