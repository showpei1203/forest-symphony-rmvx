class Window_ShopSell < Window_Item
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     x      : 視窗X座標
  #     y      : 視窗Y座標
  #     width  : 視窗寬度
  #     height : 視窗高度
  #--------------------------------------------------------------------------
  def initialize(x, y, width, height)
    super(x, y, width, height)
    #self.contents.font.size = 14
  end
  #----------------------------------------------------------------------
  # * 是否包含於物品清單中
  #     item : 物品
  #--------------------------------------------------------------------------
  def include?(item)
    return item != nil
  end
  #--------------------------------------------------------------------------
  # * 顯示物品是否可用
  #     item : 物品
  #--------------------------------------------------------------------------
  def enable?(item)
    return (item.price > 0)
  end
end
