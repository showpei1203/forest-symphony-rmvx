　② 行動条件を複数設定可能にする機能・設定の仕方

　　まずはダミースキルを作ります。
　　スクリプト内のカスタマイズ項目 ADDITION_CONDITION_SKILL = で、
　　ダミースキルとするスキルのidを指定します。
　　ゲーム内では使用しないスキルの番号にしてください。

　　ダミースキルは名前を "＋追加条件" 等としておくと
　　データベースで編集する際、わかりやすいです。

　　次に、データベース・敵キャラにて、行動パターンの編集時に
　　条件を追加したい行動のすぐ次の行に、上記で設定したスキルを選び、
　　そのスキルの行動条件として、追加したい行動条件を選びます。
　　そうすることで、先に設定した行動に、後に選んだ行動条件が追加されます。

　　追加条件はダミースキルを連ねていくことでいくつでも追加可能です。

　　※追加条件の組み合わせによっては、
　　　行動パターンにまったく反映されない場合もあります。
　　
