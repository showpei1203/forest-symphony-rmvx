  ① 新たな行動条件の追加機能・追加行動条件の説明
  
  対象の状態を条件とする項目(0 ～ 7)は、
  行動が通常攻撃や単体を対象とするスキル(連続を含む)の場合、
  条件を満たす対象の中から、狙うべき対象を選びます。
  
  対象がランダムのスキルの場合や、
  グループを対象とするスキルの場合は、
  条件を満たす対象がひとりでも含まれていれば、
  条件を満たしていると判断します。
  (スキルの性質上、個人を狙うような動作はしません。
   よって実際の対象には条件を満たさない者も含まれる場合があります)
  
  条件を満たす対象が一人も存在しない場合、
　その行動自体が行動パターンにはあがりません。

  ・付加・解除が有効の対象  可針對隊友跟敵人
  
  　　スキルに付加・解除するステートが設定されている場合専用です。
  　　ステート付加・解除が対象にとって有効な場合、条件を満たします。
  　　もし、そのステートがすでに付加されていたり、すでに解除されていたりすると
  　　この条件は満たしません。
 
　　　効果がないスキルの無駄撃ちをさせずに別の行動を行わせたり、
　　　まだそのスキルによるバッドステートに掛かっていない敵を狙わせたり、
　　　バッドステートに犯された仲間がいる場合のみ回復呪文を使わせたり出来ます。


　・HPが全快でない、HPが○○以下、MPが残っている対象 敵人的話可以優先打虛弱

　　　条件名の通り、対象のHP・MPを行動条件に出来ます。
　　　
　　　敵ならば瀕死の敵を狙う、味方なら瀕死の仲間を救うスキルを作れます。
　　　マナドレインを、MPの回収が見込める対象のみに使わせることができます。


　・動くことが出来る対象

　　　麻痺や混乱などで行動出来ない対象を除き、行動できる対象のみ狙います。
　　　不意打ちによって、対象パーティー全体が動けない場合も条件に含みます。

　　　「逃げる」「防御」など、消極的な行動の条件に使用すると良いでしょう。
　　　相手が行動出来ない無防備な状況では、この行動条件は満たされないからです。


　・指定indexの対象

　　　グループ内のindexで対象を指定することができます。
　　　指定は、データベース・敵グループ、バトルイベントのスクリプトで

　　　$game_troop.appoint_target = [1]

　　　と記述することで設定します。( 1 は任意のindexに変更してください)
　　　※indexは 0 から数えます。一人目は 0 、二人目は 1 です。注意してください。
　　　通常は０ターン目(戦闘開始前)のイベントとして組み込んで置くと良いですが、
　　　バトルイベントとの組み合わせで、戦況により指定を変更することも出来ます。

　　　$game_troop.appoint_target = [1, 2, 3]　等と連記することも可能です。
　　　その際は連記したindexの中からランダムに対象が選ばれます。

      $game_troop.appoint_target が未設定(= [])の場合、
      この条件は満たさない、という扱いになります。

　　　ボスを援助する子分エネミー等が作れます。

　・自分以外の対象

　　　常に自分以外を対象としてスキルを使います。
　　　味方グループを対象とするスキル用の条件です。

　　　回復魔法等を自分以外の仲間の為だけに使わせることが出来ます。

   
　・味方に戦闘不能無し

　　　敵グループにまだ戦闘不能のエネミーがいない場合を条件とします。
　　　味方に死者が出たことをきっかけに戦術を変えるエネミーを作れます。

   
　・自分ひとりの時 可以逃跑的敵人

　　　自分が最後のひとりの場合、行動します。
　　　ひとり取り残された場合に逃げ出す臆病なエネミー等を作ることが出来ます。
 
