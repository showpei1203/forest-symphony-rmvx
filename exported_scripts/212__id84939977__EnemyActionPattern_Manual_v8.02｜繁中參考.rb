　④ 行動パターンを変化させるステートを作成・説明

 　 エネミーの行動パターンを、設定したステートを付加することで
　　一時的に別のエネミーの行動パターンに変化させることができます。

　　<エネミー行動変化：1>

　　とメモ欄に書いたステートをエネミーに付加してください。
　　1 の部分は任意のエネミーのIDを入れます。(半角数字)

　　これらステートにかかったエネミーは、ステートにかかっている間
　　ID指定したエネミーの行動パターンで行動します。

　　※ このタイプのステートが付加した時点、もしくは解除された時点で
　　　 未行動だった場合は、そのターンの行動はキャンセルされる仕様です。
　　
#------------------------------------------------------------------------------ 

　オプション①：条件に合うターゲットがいない場合の動作設定

　　行動パターンはターン開始前に決定される為、
    そのエネミーの行動順番が回って来た時点で、行動条件を満たすターゲットが
    存在しない場合があります。
    
    通常攻撃の場合は、ターゲットの条件に合う敵を再検索し、
    条件に合うターゲットへ通常攻撃をしかけます。
    (条件に合うターゲットがいない場合は行動をしません)
    
    スキルの場合は、ただターゲットを変更することが最善とは言えない場合も、
    そのスキルの性質によってありえることです。
    また、どんな行動を再選択するのか、ということは
    エネミーの性格付けに関わるポイントとなるでしょう。
    
    この、スキルによる「ターゲット消失」の際の、
    エネミーの動作を以下の３種類から選べます。
    
    無鉄砲タイプ … スキルはそのまま実行し、
    　　　　　　　　スキルのターゲットが単独の場合はランダムに対象を選びます。
    好戦的タイプ … スキルを中止し、ランダム通常攻撃に切り替えます。
    慎重派タイプ … スキルを中止し、そのターンは様子を見ます。
    
　　設定の仕方は、デフォルトの動作設定と、エネミー個別設定の二種類あり、
　　個別設定がされていないエネミーの動作は、自動的にデフォルトの動作になります。

　　デフォルトの動作設定は、スクリプト内のカスタマイズ項目にて設定してください。

　　エネミー個別に設定する場合は、データベース・エネミーのメモ欄に、
　　　<無鉄砲> <好戦的> <慎重派>
　　のいずれかのワードを記入してください。< > ←の囲みは必ず付けてください。


　オプション②：ステートによる索敵確率操作

　　ステートのメモ欄に
　　　<索敵:頻回> <索敵：極稀>
　　のいずれかのワードを書き入れることで、ターゲット索敵率を
　　操作することができる特別なアクター専用ステートを作成することが出来ます。
　　< > ←の囲みは必ず付けてください。

　　<索敵:頻回>
　　　…エネミーが条件を満たすターゲットグループからターゲットを選ぶ際、
　　　　このステートになっている者は選ばれやすくなります。
　　　　※つまり敵に狙われる可能性が高くなります！

　　<索敵:極稀>
　　　…エネミーが条件を満たすターゲットグループからターゲットを選ぶ際、
　　　　このステートになっている者は選ばれにくくなります。
　　　　※つまり敵に狙われる可能性が低くなります！

　　どちらもターゲットを任意に選ぶ攻撃(スキル)の場合のみに有効です。
　　全体攻撃や、ランダム攻撃の場合にはこのオプションは機能しません。


  オプション③：カスタマイズ項目、USE_RANDOM_TARGET の説明

   カスタマイズ項目、USE_RANDOM_TARGET の設定にて、
   条件にあった対象をランダムに選出する処理に、
   Game_Unitクラスのrandom_targetメソッドを流用するか、否かを選べます。

   流用すると、random_targetメソッドが他のスクリプトで書き換えられている際、
   その書き換えが、当スクリプトの「条件にあった対象をランダムに選出」する
   処理にも反映されることになります。
　 書き換えしているスクリプトの内容にもよりますが、機能拡張となります。
   
   流用すれば、他スクリプトの機能を取り入れられるメリットがありますが、
   他スクリプトの書き換え内容によっては、競合してしまい
   満足な結果が得られない(場合によっては不具合の原因となる)ことになります。
   
   この為、流用機能の導入は任意設定できるようにしてあります。
   
   流用しない場合は、当スクリプトで別に準備した独自の選出処理を使用します。
　 他スクリプトの処理が反映されませんが、競合の可能性も低くなります。
   
   random_targetメソッドを書き換えるスクリプトを他に導入していなければ、
   このカスタマイズは特に意味を持ちません。オン／オフ同じ処理をします。

