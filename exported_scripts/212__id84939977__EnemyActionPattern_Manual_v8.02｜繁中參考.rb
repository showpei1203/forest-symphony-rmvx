　① 新たな行動条件の追加機能・設定の仕方
  　
  １：確保するスイッチ番号を決める
  
  　この機能はエネミーのデータベースにて、
  　行動条件のスイッチを利用して設定をおこないます。
  
  　追加機能用に確保されたスイッチを、条件「スイッチがONの時」に選ぶことで
  　「その項目が満たされた場合を条件とする」という意味になります。
  　
  　スクリプト内で、確保するスイッチの最初の番号を、
  　「カスタマイズ項目」の TOP_SWITCH = にて設定してください。
  　そのスイッチより数えて９つのスイッチが、このスクリプト用に使われます。
  　(この９つのスイッチは通常のスイッチとしての機能はなくなります)
  　
　　追加される行動条件と、対応するスイッチの番号は下記の通りです。

    index (Switche No.)       : 条件（推奨するスイッチにつける名前）
    
        0 (= TOP_SWITCH)     : 付加・解除が有効の対象
        1 (= TOP_SWITCH + 1) : HPが全快でない対象
        2 (= TOP_SWITCH + 2) : HPが1/2以下の対象
        3 (= TOP_SWITCH + 3) : HPが1/5以下の対象
        4 (= TOP_SWITCH + 4) : MPが残っている対象
        5 (= TOP_SWITCH + 5) : 動くことが出来る対象
        6 (= TOP_SWITCH + 6) : 指定indexの対象
        7 (= TOP_SWITCH + 7) : 自分以外の対象
        8 (= TOP_SWITCH + 8) : 味方に戦闘不能無し
        9 (= TOP_SWITCH + 9) : 自分ひとりの時
        
        
  ２：スイッチに名前をつけておく
  
  　（これは任意ですが）確保したスイッチにわかりやすく名前をつけてください。
  　実際に行動パターンを設定する際に便利です。
  
  
  ３：データベース・エネミーにて、スイッチを行動条件に設定する
  
  　ここまでの準備が出来たら、あとの設定はすべてデータベース内で行えます。
  　確保したスイッチを行動条件に選ぶことで、項目名どおりの条件で、
  　その行動がパターンとして登録されるようになります。
  
