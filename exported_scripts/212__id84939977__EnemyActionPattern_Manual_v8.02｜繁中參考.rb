本腳本的四大功能
新增行動條件

可為敵人的行動模式 新增額外的條件。
允許設定多個行動條件

可同時設定 「回合數指定 + HP 指定」 等條件，
只有當所有條件都滿足時，才會執行對應行動。
變更行動模式為「輪盤決定方式」

改變敵人行動模式的決策機制，
採用「純粹優先度輪盤機制」。
透過狀態變化來改變行動模式

讓敵人因 特定狀態 的影響，暫時切換至不同的行動模式。
① 新增行動條件的功能與設定方式
1. 確保特定的開關號碼
這個功能會在 敵人資料庫（Enemy DB） 中使用 「開關條件」 來設定。
需保留 9 個開關 供本腳本使用，這些開關將無法用於其他用途。
請在 腳本的自訂部分 設定 TOP_SWITCH，此數值為保留的第一個開關號碼。
這些開關對應的條件如下：
索引 (Switch No.)	條件名稱（建議的開關名稱）
0 (= TOP_SWITCH)	可施加 / 解除效果的目標
1 (= TOP_SWITCH + 1)	HP 未全滿的對象
2 (= TOP_SWITCH + 2)	HP 低於 1/2 的對象
3 (= TOP_SWITCH + 3)	HP 低於 1/5 的對象
4 (= TOP_SWITCH + 4)	MP 仍然有剩餘的對象
5 (= TOP_SWITCH + 5)	可以行動的對象（未被麻痺等影響）
6 (= TOP_SWITCH + 6)	指定 索引編號 的對象
7 (= TOP_SWITCH + 7)	除自己以外的對象
8 (= TOP_SWITCH + 8)	隊伍內沒有戰鬥不能的成員
9 (= TOP_SWITCH + 9)	當場上只剩自己一人時

2. 為開關命名
（選擇性） 可以為開關設定明確的名稱，以方便管理。

3. 設定敵人的行動條件
完成上述準備後，可在 敵人資料庫（Enemy DB） 的 行動條件 欄位內，
選擇這些開關來設定敵人的行動模式。


② 允許設定多個行動條件
設定方式
建立一個「虛擬技能」（Dummy Skill）

在腳本的自訂設定 ADDITION_CONDITION_SKILL 中，設定 虛擬技能的 ID。
此技能不會在遊戲內實際使用，可命名為 「+額外條件」 以便識別。
在敵人行動模式中設定條件

在 敵人資料庫（Enemy DB） 的 行動模式 中：
先設定 主要行動（例如攻擊）。
在下一行選擇「+額外條件」的技能，並設定其他條件（例如 回合數）。
這樣可以為單一行動設置多個條件。
可串聯多個條件

透過 連續使用「虛擬技能」，可無限增加條件。
注意：某些條件組合可能導致行動無法觸發，請注意測試！

③ 行動模式變更為「輪盤決定方式」
機制說明
行動的決策方式

採用 優先度輪盤決定行動：
符合條件的行動，會依照「優先度」的數值被加入輪盤。
優先度數值 = 抽選機率（數值越高，該行動越容易被選擇）。
獨特的「升序註冊」規則

行動的優先度必須為遞增，否則該行動會被跳過：
範例： 如果輪盤優先度為 1, 2, 5, 3, 6
實際加入輪盤的順序為 1, 2, 5, 6（因為 3 被 5 擋住）。
如果 5 的條件不符合，則 3 會被重新納入。
應用範例

在敵人行動模式中，將 「當場上只剩自己」 設為 優先度 10 的「逃跑」，
則敵人在有隊友時不會逃跑，只會在最後剩自己時逃跑。
此功能可開關

若不使用此功能，則會回到 RPG Maker 預設的 固定優先度行動。

④ 透過狀態變化改變行動模式
機制說明
設置特殊狀態

在 狀態資料庫（State DB） 的 備註欄 內加入：
<エネミー行動変化：1>
1 為 指定的敵人 ID，當敵人獲得這個狀態時，
行動模式將變為 ID 為 1 的敵人行動模式。
適用於「狂暴化」「畏縮」等行為

例如：
敵人受到「狂暴」狀態影響，其行動會改為 另一個敵人的攻擊模式。
敵人受到「懼怕」狀態影響，其行動會改為 較保守的模式。
其他選項

① 當沒有符合條件的目標時的行動
若行動順序到來時，目標條件已不符合，可選擇以下處理方式：

無腦型 (無鉄砲) → 隨機選擇其他目標。
好戰型 (好戦的) → 改用普通攻擊。
謹慎型 (慎重派) → 取消行動，該回合不動作。
可在 腳本設定 或 敵人資料庫（Enemy DB）備註 內設定：

<無鉄砲>
<好戦的>
<慎重派>

② 狀態影響敵人目標選擇
在 狀態資料庫（State DB） 備註內設定：

<索敵:頻回>  # 讓敵人更容易選擇此角色為攻擊目標
<索敵:極稀>  # 讓敵人較難選擇此角色為攻擊目標
適用於單體技能，對於群體技能無效。


