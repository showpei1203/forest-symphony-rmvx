　オプション

　①起動アイテム・スキルの種類により　イベント内で条件分岐をする方法

　　カスタマイズ項目　LAST_USE_ITEM = で指定した番号の変数に、
　　起動に使われたアイテムもしくはスキルのID番号が出力されます。
　　アイテムならアイテムIDを、スキルの場合は、+1000 の値を出力します。
    (アイテムIDが15なら15を出力、スキルIDが15なら1015を出力)                        
    
    イベント起動するアイテム・スキルが複数ある際、この変数を参照することで
    アイテム毎、スキル毎にイベント内で条件分岐できます。

  ②起動アイテム・スキルのタイプで　イベント内で条件分岐をする方法
  
  　イベント内の条件分岐で、スクリプトを条件とし、下記のいずれかを
  　記入してください。(「カギ」の部分は任意のタイプを示す単語にしてください)
　　　　
　　type?("カギ")　　　　　　　　　　起動したスキル・アイテムが カギ の場合
　　item_type?("カギ")　　　　　　 　起動させたのが カギ タイプのアイテムの場合
　　skill_type?("カギ")　　　　　　　起動させたのが カギ タイプのスキルの場合

　　該当する場合、分岐条件を満たします。

　③イベント内で起動したスキルのコストを消費させる方法

　　イベント内のスクリプトに

　　consume_skill_cost

　　と記入すると、イベント起動に使ったスキルのコストを使用者が消費します。
　　（スキルで起動させたイベントでないイベントで使うと、
　　　動作不良の原因になりますので、注意してください）

　④イベント起動に設定されたアイテムやスキルの効果について

　　アイテムやスキルの効果の前に、割り込んでイベントが起きる仕様です。
　　ポーションなどの「本来の効果」があるアイテムの場合、
　　その効果(消費も含む)を起こさずに、設定されたイベントが開始され、
　　「本来の効果」は現れません。

　　それを利用して、イベントの内容によっては「NPCに使った」などの
　　表現をすることが出来るわけです。

　　割り込むアイテムの「本来の効果」には、
　　アイテムに設定されるコモンイベントも含みます。
　　サンプルプロジェクト内で出てくる「スコップ」というアイテムの失敗表示には、
　　このコモンイベントへの割り込みの仕組みを利用しています。


　　イベント内で、使用したアイテム数の減少や③のスキルコスト減少を行うと
　　「使用したイベント」らしい表現になるでしょう。
　　逆に、数やコストを減らさないと、
　　「使用する前になにかが起きた」という表現のイベントになりますね。


　※　この他にも、サンプルプロジェクト内には便利なスクリプト記述や、
　　　扉イベントのテンプレートを用意しています。

　　　活用してみてください！

