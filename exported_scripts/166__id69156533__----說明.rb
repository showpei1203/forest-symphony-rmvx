　※このマニュアルは素材としてプロジェクト内に貼り付ける事も可能です。

　このスクリプトでは…

　　メニュー画面でアイテムやスキルを「使う」ことで、
　　目の前の扉を開けることが出来る「カギ」のようなオブジェクトを作ったり、
　　持ち物の中から正しいアイテムを選ぶと進むイベント等が作れます！

　　つまり、ゲームに謎解き要素を加えることができます！

　　　このスクリプトではイベントを起こす「きっかけ」になるアイテムを
　　　作る事が出来ます。アイテム側に設定するコモンイベントとは異なる物で、
　　　イベント側に「どのアイテムがそのイベント起動のきっかけになるか」を
　　　設定して作ります。

　　具体的には…
　　　イベントページに、そのイベントページを起動するオブジェクトを設定します。
　　　そのイベントの目の前(もしくは重なった場所)で
　　　該当オブジェクトを使用した時のみ、このページのイベントが起きます。
　　　(他に優先するページがある場合はこのページのイベントは起こせません)


#------------------------------------------------------------------------------

　設定の仕方

　①ＩＤでの指定

　・アイテムのidで指定する場合
　　起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　(数字部分は任意のアイテムのid番号にしてください)

　　　　　起動条件<item-id:25>

　・スキルのidで指定する場合
　　起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　(数字部分は任意のスキルのid番号にしてください)

　　　　　起動条件<skill-id:15>

　　※起動させたいアイテム・スキルが複数ある場合、連記が可能です。
　　　(間に / を入れてください)

　　　　　起動条件<item-id:25/item-id:26/item-id:30>
　　　　　起動条件<item-id:25/skill-id:15>



　③アイテム・スキルのタイプでの指定

　　まずアイテムもしくはスキルのメモ欄に次のように記入し、タイプを作ります。
　　(「カギ」の部分はタイプを示す任意の単語にしてください)
　
　　　　　起動条件<type:カギ>

　　次に起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　(アイテム・スキルへの記述と、同様の記述になります)

　　　　　起動条件<type:カギ>

　　※起動させたいアイテムタイプが複数ある場合、連記が可能です。

　　　　　起動条件<type:カギ/type:回復アイテム>

　　※①、②、③を混ぜて連記することも可能です。

　　　　　起動条件<type:カギ/type:回復アイテム/skill-id:15>

　④すべてのアイテム・スキルを起動条件とする場合

　・アイテムの場合
　　起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　
　　　　　起動条件<items>

　・スキルの場合
　　起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　
　　　　　起動条件<skills>

　　※idの記述と混合して連記することも可能です。

　　　　　起動条件<items/skill-id:15>
　　　　　起動条件<skills/item-id:25>

　・アイテム・スキルすべての場合
　　起動させたいイベントページの一行目に注釈で以下のように記入してください。
　　
　　　　　起動条件<all>

