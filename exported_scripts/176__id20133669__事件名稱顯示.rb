#==============================================================================
# ■ Game_Event
#==============================================================================
class Game_Event < Game_Character
  #--------------------------------------------------------------------------
  # ● イベントページのセットアップ
  #--------------------------------------------------------------------------
  alias tnpop_game_event_setup setup
  def setup(new_page)
    tnpop_game_event_setup(new_page)
    if @list != nil
      @namepop = $1 if /<namepop\s*(\S+?)>/i =~ @event.name
      for list in @list
        if list.code == 108
          @namepop = $1 if /<namepop\s*(\S+?)>/i =~ list.parameters[0]
          break
        end
      end
    end
  end
end

