# ■ Game_Temp
#------------------------------------------------------------------------------
# 　セーブデータに含まれない、一時的なデータを扱うクラスです。このクラスのイン
# スタンスは $game_temp で参照されます。
#==============================================================================

class Game_Temp
  #--------------------------------------------------------------------------
  # ◎ 拡張行動条件に使用するスイッチデータの作成
  #--------------------------------------------------------------------------
  alias tig_eac_pt_make_ex_conditions_switches make_ex_conditions_switches
  def make_ex_conditions_switches
    switches = Array.new(EacAdd_Position_Target::SETTING.size){|i|i+EacAdd_Position_Target::TOP_SWITCH}
    return tig_eac_pt_make_ex_conditions_switches + switches
  end
end

#==============================================================================
# ■ Game_BattleAction
#------------------------------------------------------------------------------
# 　戦闘行動を扱うクラスです。このクラスは Game_Battler クラスの内部で使用され
# ます。
#==============================================================================

class Game_BattleAction
  #--------------------------------------------------------------------------
  # ◎ 条件にあうターゲットグループの取得
  #--------------------------------------------------------------------------
  alias tig_eac_pt_conditions_targets conditions_targets
  def conditions_targets(arrays, skill)
    targets = tig_eac_pt_conditions_targets(arrays, skill)
    for array in arrays ; next if array[0] != 6
      if EacAdd_Position_Target::SWITCHES_RANGE.include?(array[1])
        new_targets = []
        index = array[1] - EacAdd_Position_Target::TOP_SWITCH
        case EacAdd_Position_Target::SETTING[index]
        when 1  ; target_position = [0]
        when 2  ; target_position = [1]
        when 3  ; target_position = [2]
        when -1 ; target_position = [1, 2]
        when -2 ; target_position = [0, 2]
        when -3 ; target_position = [0, 1]
        end
        if target_position
          for target in targets
            next unless target.actor?
            next unless target_position.include?(target.class.position)
            new_targets.push(target)
          end
        end
        targets = new_targets
      end
    end
    return targets
  end
end