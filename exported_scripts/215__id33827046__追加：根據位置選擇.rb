=begin

  ※このスクリプトは月紳士の「エネミー行動パターン改良」に
  　新たな行動条件を追加する拡張スクリプトです。
 　 「エネミー行動パターン改良」(Ver8.00以降)が必要となります。
  　このスクリプトは「エネミー行動パターン改良」より下に挿入してください。
  
  ○ 新たな行動条件の追加。
　　エネミーの行動パターンに、さらなる行動条件を追加します。
　　追加できるのは
    ・特定のポジションのアクターを対象とする行動条件
    ・特定のポジションでないアクターを対象とする行動条件
    の二種類です。
    ポジションとは、クラスに設定できる
    「前衛」「中衛」「後衛」
    のことです。
    
    追加する行動条件の数は任意で、カスタマイズ項目にて
    行動条件にするポジションを登録した後、
    登録した行動条件に合わせたスイッチを用意することで
    設定します。
    
    詳しくはカスタマイズ項目をご覧ください。
    
=end
#==============================================================================
# ■ エネミー行動パターン行動条件追加：対象のポジション・モジュール
#==============================================================================
module EacAdd_Position_Target

 # カスタマイズ項目------------------------------------------------------------
  
  TOP_SWITCH = 134
       #↑# 「行動条件追加：対象のポジション」に使用するスイッチ郡の、
          # 最初の番号をここで指定します。
          # 「エネミー行動パターン改良」の元もとのスイッチ郡と
          # つなげる必要はありません。
          # ゲーム中の判定に差し支えない番号にしてください。
          
  SETTING = [-3, 3]
       #↑# 行動条件追加にしたいポジションをここで設定します。
          # ターゲットとして用意したい対象ポジションをここで設定してください。
          # 行動条件の設定数は任意です。 , (半角カンマ)で区切ってください。
          #
          # 数字により、行動条件にあげるポジションを指定します。
          # 使える数字は以下です。
          # 1 = 前衛 / 2 = 中衛 / 3 = 後衛
          # 数値をマイナスにすると、それ以外、となります。
          # (例) -2 なら 後衛以外、つまり前衛と中衛です。
          #
          # 条件を満たす対象がいれば行動条件を満たし、それを狙います。
          # 対象がいなければ行動条件を満たさず、その行動も選ばれません。
          
=begin

　SETTINGで設定した順番に対応させ、
  TOP_SWITCHから順番に設定数と同じ数のスイッチを用意してください。
  例をあげて説明しますと…

　TOP_SWITCH = 14
　SETTING = [1, 2, 3]
　と設定したのであれば、
　スイッチ14が「前衛を対象とする」行動条件、
　スイッチ15が「中衛を対象とする」行動条件、
　スイッチ16が「後衛を対象とする」行動条件となります。

　スイッチの名前は任意でかまいません。製作中にわかりやすい名前にしてください。
    
=end         
 # ------------------------------------------------(カスタマイズ項目ここまで)--
 
  SWITCHES_RANGE = TOP_SWITCH...(TOP_SWITCH + SETTING.size)
  
 # ----------------------------------------------------------------------------
end

