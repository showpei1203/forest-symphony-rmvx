#
# 【用途】
# Tankentai ATB 的集中設定頁。控制戰鬥開始量表、ATB Wait／Active 規則、整體速度、
# 回合計算、持續傷害時機、復活／行動後量表重設、量表位置／圖形／音效、遊戲內
# ATB Options，以及 Skill／Item／State／Weapon／Armor／Actor／Enemy 的蓄力與量表資料。
#
# 【依賴／載入順序】
# 1. 本頁建立 $imported["TankentaiATB"] 與 N02 設定，必須位於 ATB 主程式之前。
# 2. SBS Action Sequence 名稱由 SBS Configuration 定義；<charge action: key> 的 key
#    必須存在於 SBS ACTION。
# 3. Forest Symphony 後方還有 DynamicResistance、BattleFormula 等補丁，本頁不要搬
#    到那些 Runtime Authority 後面。
#
# 【戰鬥開始量表】
# ATB_BASE_ACTOR／ATB_BASE_ENEMY：我方／敵方初始 ATB 百分比。
# ATB_BASE_ADD：再追加的隨機百分比，雙方都套用。
# ATB_BACKATTACK：先制／偷襲時的 ATB 懲罰百分比。
# ATB_RUN_NG：逃跑失敗時的 ATB 懲罰百分比。
# ATB_DEAD_COUNT：從戰鬥不能狀態復活後的量表百分比，可為負值。
#
# 【Wait／Active 規則；僅 ATB_CUSTOMIZE=false 時直接使用】
# ATB_PARTY_COMMAND_WAIT：選 Fight／Escape 時量表是否繼續。
# ATB_COMMAND_WAIT：選角色指令時是否繼續。
# ATB_TARGET_WAIT：選目標時是否繼續。
# ATB_SELECT_WAIT：選 Skill／Item 時是否繼續。
# ATB_ACTION_WAIT：技能／攻擊演出與處理中是否繼續。
# true＝量表會跑；false＝等待。
#
# 【測試／控制按鍵】
# ATB_SHIFT_BOOST：true 時按 Shift 令量表速度 x4。
# ATB_CTRL_ACTIVE：true 時 Ctrl 可強制停住的量表繼續上升。
# ATB_ALT_WAIT：true 時 Alt 可強制停止目前活動量表。
#
# 【速度】
# ATB_SPEED：整體速度。原作參考：1 很慢、5 舒適、10 一般、20 快、500 非常快。
# ATB_BASE_SPEED：速度比較基準：
#   0 固定值（搭配 ATB_ABSOLUTE_SPEED）
#   1 場上最高 AGI
#   2 場上最低 AGI
#   3 全戰鬥者平均 AGI
# 個別戰鬥者的 AGI 仍會影響其量表速度。
#
# 【回合與持續傷害】
#   0＝累積行動次數等於場上戰鬥者數量後算 1 Turn
#   1＝累積行動次數達場上人數的一半後算 1 Turn
#   2＝任一戰鬥者完成一次行動就算 1 Turn
# ATB_SLIP_DAMAGE：0＝中毒／再生在該戰鬥者每次行動時結算；1＝每 Turn 全體結算。
#
# 【行動後量表重設】
# ATB_ATTACK_RESET：普通攻擊後；ATB_GUARD_RESET：防禦後；ATB_SKILL_RESET：技能後；
# ATB_ITEM_RESET：物品後；ATB_NONACT_RESET：無行動後。單位都是百分比。
# 各 Skill／Item／Weapon／Actor／Enemy 的 recharge 方法可覆蓋對應預設值。
#
# 【量表顯示與位置】
# ATB_ENEMY_ON：敵方量表預設顯示。
# ATB_ACTION_ACTOR_OFF／ATB_ACTION_ENEMY_OFF：行動執行中是否隱藏我方／敵方量表。
# ATB_POSITION_ACTOR／ATB_POSITION_ENEMY：[X,Y]，以各自起始位置為基準；背襲會反轉 X。
# ATB_POSITION_HPWINDOW=true：我方改用 ATB_PARTY_POSITION 的固定座標。
# ATB_PARTY_POSITION：每個 Actor 的 [X,Y]；MAX_MEMBER 增減時記得同步座標數量。
#
# 【量表圖形／素材】
#   atb_bar        等待中的藍量表
#   act_bar        蓄力中的紅量表
#   atb_bar_active 量表滿時圖形
#   atb_bar_skin   量表外框／Skin
# 四張圖建議同尺寸。
# ATB_WIDTH：真正使用的 bar 寬度；原作建議使用可整除 1000 的值。
# ATB_SPACE：bar 左右透明／未使用像素的排除量。
# 音效：ATB_MAX_SOUND01、ACT_MAX_SOUND01、NEXT_SOUND01 皆為 [Pitch,Volume,SE檔名]。
# 現行預設會讀 Audio/SE：Accept、Accept2、Miss。
#
# 【遊戲內 ATB Options】
# ATB_CUSTOMIZE=true 才啟用玩家 Menu 自訂。
# ATB_CUSTOMIZE_NAME／HELP：選項名稱與 Help Window 文字。
# ATB_MODE1～3：格式 [名稱, PartyCmd, ActorCmd, Target, SkillItem, Action]；
# ATB_NEWGAME_MODE：新遊戲預設模式 index。
# ATB_SPEED_MODE：Menu 的 1～9 檔對應實際速度；啟用後會取代固定 ATB_SPEED。
# ATB_NEWGAME_SPEED：新遊戲預設速度檔。
#
# FORCE_ACTION_CONSUME_GAUGE：強制行動是否消耗量表。
# FORCE_ACTION_INCREASE_TURN：強制行動是否增加 Turn Count。
#
# 【Skill／Item／Weapon／Actor／Enemy 的 charge 格式】
# charge 回傳：[Standard, RequiredGauge%, FixedValue, "ChargingAction"]
# Standard：0 固定；1 最高 AGI；2 最低 AGI；3 平均 AGI；4 自身 AGI。
# RequiredGauge%：蓄力量；200＝一般滿量表的兩倍，10＝十分之一，0＝立即。
# FixedValue：Standard=0 時當成計算用 AGI。
# ChargingAction：SBS ACTION key；"" 代表蓄力時不播放 Action Sequence。
# 範例：
#   return [4, 50, 0, "CHARGING"]
#
# 【ATB Notetag；字串不得翻譯】
#   <charge action: key>          # 必須同時有 <charge: ...>
#
# State#atb_damage：負值會削減 ATB；正值會補量表。蓄力中被削減可取消蓄力。
# State#atb_minus_damage：true 允許量表被打到 0 以下，例如 -25 代表之後需累積 125%。
# State#charge_bonus：對所有蓄力 Action 的加成，狀態之間可累加；負值縮短、正值延長。
#
# Weapon#charge：普通攻擊的蓄力；二刀流使用兩把武器的平均蓄力，Weapon 1 的
#                 Charging Action 優先。
# Weapon#charge_bonus：武器對所有蓄力 Action 的修正；二刀流取平均。
# Weapon#recharge：該武器普通攻擊後量表重設值；不影響 Skill／Item。
# Weapon#atb_base：裝備時修正戰鬥開始量表；多件效果可累積，二刀流取平均。
# Armor#charge_bonus／Armor#atb_base：與上面相同概念，防具效果可累積。
#
# Game_Actor#charge／Game_Enemy#charge：空手普通攻擊蓄力。
# recharge：空手普通攻擊後量表重設。
# atb_base：個別戰鬥開始量表，可覆蓋 ATB_BASE_ACTOR／ENEMY。
# atb_on：true 顯示、false 隱藏；Enemy 個別設定優先於 ATB_ENEMY_ON。
#
# union_action 內每個 Array 是一組技能 ID，例如 [260,261]。
# 任一成員技能被使用時，只有全部必要角色 ATB 滿格才可發動；中途有人戰鬥不能
# 會取消。Array 第一個 Skill ID 所屬角色視為 active battler，傷害以他為基準。
# 參戰角色會進入 Prepare，直到組合完成或取消。
#
# 【範例】
#   def charge
#     case @id
#     when 1
#       return [4, 50, 0, "CHARGING"]
#     end
#     return [4, 10, 0, ""]
#   end
# Weapon／State／Armor 等也依 ID case 設定；沒有指定的 ID 必須回傳 Default。
#
# 【維護規則】
# 1. 本頁是設定資料，不要直接搬到 ATB Runtime 後方。
# 2. SBS ACTION key、Notetag、SE／圖檔名、常數名都是程式識別字，不翻譯。
# 3. 原作者、版本、網址與 Credits 保留；下方英文解說已整併到本中文手冊。
