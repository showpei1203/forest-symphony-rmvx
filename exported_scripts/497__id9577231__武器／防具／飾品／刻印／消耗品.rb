# 第七部　刻印／召喚裝備
# ===============================================================================
#
# 目前專案已有防具→召喚Actor Mapping，例如：
#   Armor 101 → Actor 8
#   Armor 103 → Actor 7
#   Armor 105 → Actor 9
#
# 所以「刻印」最好視為特殊Armor。
#
# 設計原則：
#   1. 刻印本身不應給過高裸能力。
#   2. 主要價值是召喚物選擇、喬伊技能變化、隊伍Build。
#   3. 稀有召喚物不代表必然數值碾壓，而是更特殊的引擎。
#
# 【普通刻印】
# 取得：
#   常見魔物、劇情。
# 功能：
#   召喚一隻初階Pokémon。
# 額外：
#   可給喬伊一個小技能。
# Note：
#   <equipskill: 對應SkillID>
#
# 【進階刻印】
# 取得：
#   菁英、支線、進化。
# 功能：
#   召喚中階Pokémon。
# 額外：
#   +5～10%單一能力。
#
# 【機器人核心】
# 取得：
#   遺跡、Boss、製作。
# 功能：
#   召喚Robot。
# 額外：
#   通常不給大量角色能力。
#
# 【人類複製檔案】
# 取得：
#   劇情、特殊實驗室、Boss。
# 功能：
#   召喚Clone。
# 限制：
#   稀有，不應像路邊藥水一樣買99個。
#
