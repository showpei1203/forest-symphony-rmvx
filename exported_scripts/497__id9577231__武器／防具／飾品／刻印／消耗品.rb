# ===============================================================================
# 第十一部　平衡禁區
# ===============================================================================
#
# 1. 不要在一件普通裝備同時給：
#    ATK +30%
#    DEF +30%
#    SPI +30%
#    AGI +30%
#    half MP
#    auto heal
#    three skills
#    還附贈咖啡。
#
# 2. 同一件裝備最多一個「改玩法」核心。
#
# 3. 商店裝備偏穩定。
#    Boss裝備偏特殊。
#
# 4. 最強數字不等於最好設計。
#
# 5. 裝備應讓玩家問：
#    「我要毒爆、擴散、還是腐蝕？」
#    而不是只問：
#    「哪個綠字比較大？」
#
# ===============================================================================
# 第十二部　正式落地前的檢查清單
# ===============================================================================
#
# 每件裝備上線前：
#
# [ ] 是否符合該Tier能力預算？
# [ ] 是否強化角色定位而非抹除定位？
# [ ] 是否有明確Build用途？
# [ ] 是否與技能／State互動？
# [ ] 是否和其他裝備形成真正二選一？
# [ ] Note是否經實機測試？
# [ ] 是否避開保護ID？
# [ ] 是否讓一個角色因裝備變成萬能答案？
#
# 裝備系統做得好，玩家會記住：
#   「我為了這個Build，特別去打那隻Boss。」
#
# 做得差，玩家只會記住：
#   「我每十分鐘又要清一次背包。」
