# ===============================================================================
# 第一部　裝備設計的總原則
# ===============================================================================
#
# 本專案的角色裸裝數值已經有明確人格：
#
#   喬伊：均衡、召喚連結
#   米亞：SPI / MP / 治療
#   艾卓：ATK / AGI / ATB控制
#   維娜：SPI / AGI / State
#   艾薇：HP / DEF / Cover / 怒氣
#   泰勒：ATK / DEF / Break
#
# 因此裝備的任務不是把角色洗成另一個職業。
# 裝備應該做三件事：
#
# 1. 強化角色既有核心。
# 2. 打開一個新的Build分支。
# 3. 提供對特定敵人／Boss的戰術調整。
#
# 推薦整套裝備對裸裝能力的影響：
#
#   前期：主要能力約 +10～18%
#   中期：主要能力約 +15～25%
#   後期：主要能力約 +20～35%
#
# 不要讓一把武器就把ATK翻倍。
# 否則角色升級、召喚物、Break、State、JP全部會淪為背景工作人員。
#
# ===============================================================================
# 第二部　裝備階段與能力預算
# ===============================================================================
#
# 【Tier 1｜Lv1～10｜起源裝備】
# 武器主能力：+6～12
# 身體防具：DEF/SPI +6～12
# 頭部：+3～7
# 飾品：+2～5% 或單一小功能
# 取得：
#   初始、商店、劇情必得。
#
# 【Tier 2｜Lv11～20｜旅途裝備】
# 武器主能力：+12～22
# 身體防具：+12～22
# 頭部：+6～12
# 飾品：+4～8%
# 取得：
#   商店、普通怪稀有掉落、支線。
#
# 【Tier 3｜Lv21～30｜專精裝備】
# 武器主能力：+22～35
# 身體防具：+20～34
# 頭部：+10～18
# 飾品：+6～10%
# 開始出現：
#   ・<equipskill>
#   ・Auto State
#   ・元素抗性
#   ・Build專屬功能
#
# 【Tier 4｜Lv31～40｜Build成形】
# 武器主能力：+35～50
# 身體防具：+30～48
# 頭部：+15～25
# 飾品：+8～12%
# 開始允許一件裝備同時有：
#   1個主能力 + 1個Build功能。
#
# 【Tier 5｜Lv41～50｜高階專武】
# 武器主能力：+50～68
# 身體防具：+45～65
# 頭部：+22～34
# 飾品：+10～15%
# 菁英、Mini Boss、深層探索掉落。
#
# 【Tier 6｜Lv51～60｜終局前裝備】
# 武器主能力：+68～88
# 身體防具：+60～85
# 頭部：+30～45
# 飾品：+12～18%
# 開始出現角色專屬終局Build裝備。
#
# 【Tier 7｜Lv61～75｜傳說裝備】
# 武器主能力：+88～110
# 身體防具：+80～110
# 頭部：+40～60
# 飾品：+15～22%
# 只給高難Boss、長支線、隱藏區域。
#
# 【Tier 8｜Lv76～90｜神話裝備】
# 武器主能力：+110～135
# 身體防具：+100～135
# 頭部：+50～75
# 飾品：+18～25%
#
# 【Tier 9｜Lv91～100｜終極裝備】
# 武器主能力：+135～165
# 身體防具：+125～165
# 頭部：+65～90
# 飾品：+20～30%
#
# 注意：
#   以上是單一「主要能力」的預算。
#   若一件裝備同時加 ATK + SPI + AGI，就不能三項都拿滿額。
#
# 建議多能力換算：
#   100%預算 = 一項主能力
#   兩項主能力 = 各60～70%
#   三項主能力 = 各40～50%
#
