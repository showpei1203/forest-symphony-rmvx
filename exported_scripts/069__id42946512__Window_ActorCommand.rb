#------------------------------------------------------------------------------
#  本視窗顯示於作戰畫面中，用來選擇主角的行動指令。
#==============================================================================

class Window_ActorCommand < Window_Command
  #--------------------------------------------------------------------------
  # * 物件初始化
  #--------------------------------------------------------------------------
  def initialize
    super(128, [], 1, 5)
    self.active = false
    self.opacity = 0
  end
  #--------------------------------------------------------------------------
  # * 設置參數
  #     actor : 主角
  #--------------------------------------------------------------------------
  def setup(actor)
    s1 = ""#Vocab::attack
    s2 = ""#Vocab::attackVocab::skill
    s3 = ""#Vocab::attackVocab::guard
    s4 = ""#Vocab::attackVocab::item
    s5 = ""#Vocab::attackVocab::escape
    if actor.class.skill_name_valid     # 自訂技能指令項顯示名合法？
      s2 = actor.class.skill_name       # 替換技能指令項顯示名
    end
    @commands = [s1, s2, s3, s4, s5]
    @item_max = 5
    refresh
    self.index = 0
  end
  def update_cursor
    self.cursor_rect.empty
  end
end
