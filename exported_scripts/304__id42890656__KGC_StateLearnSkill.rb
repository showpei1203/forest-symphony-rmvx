$imported = {} if $imported == nil
$imported["StateLearnSkill"] = true

module KGC
module StateLearnSkill
  module Regexp
    module State
      # 習得スキル
      LEARN_SKILL = /<(?:LEARN_SKILL|スキル習得)\s*(\d+(?:\s*,\s*\d+)*)>/i
    end
  end
end
end

