# ■ Spriteset_Battle
#==============================================================================
class Spriteset_Battle
  #--------------------------------------------------------------------------
  # ● エフェクトの作成
  #--------------------------------------------------------------------------
  def create_streffect
    $game_temp.streffect_b = []
  end
  #--------------------------------------------------------------------------
  # ● エフェクトの解放
  #--------------------------------------------------------------------------
  def dispose_streffect
    for i in 0...$game_temp.streffect_b.size
      $game_temp.streffect_b[i].dispose if $game_temp.streffect_b[i] != nil
    end
    $game_temp.streffect_b = []
  end
  #--------------------------------------------------------------------------
  # ● エフェクトの更新
  #--------------------------------------------------------------------------
  def update_streffect
    for i in 0...$game_temp.streffect_b.size
      if $game_temp.streffect_b[i] != nil
        $game_temp.streffect_b[i].viewport = @viewport1
        $game_temp.streffect_b[i].update
        $game_temp.streffect_b.delete_at(i) if $game_temp.streffect_b[i].disposed?
      end
    end
  end
  #--------------------------------------------------------------------------
  # ★ エイリアス
  #--------------------------------------------------------------------------
  alias create_actors_stref create_actors
  def create_actors
    create_actors_stref
    create_streffect
  end
  alias dispose_stref dispose
  def dispose
    dispose_stref
    dispose_streffect
  end
  alias update_stref update
  def update
    update_stref
    update_streffect
  end
end