#
# 【用途】
# 這是 Tankentai SBS 的核心「資料／動作語言」頁。它定義 ANIME Hash、ACTION
# Sequence、角色／敵人的預設 Action、State／Weapon／Skill／Item 的動作與擴充。
# Forest Symphony 大量 Hero Action、武器演出、追擊、召喚、技能動畫都依賴這裡的
# Key 名稱，因此 Key 是 Runtime API，**不要為了中文化任意改字串 Key**。
#
# 【最重要的規則】
# 1. ANIME Key／ACTION Key 大小寫敏感；未定義的 ANIME Key 在 Sequence 中通常會被
#    跳過，錯字可能不一定直接報錯，反而變成「少一段動畫」這種很難抓的問題。
# 2. ANIME Hash 每筆結尾逗號不可漏；漏逗號會 Syntax Error。
# 3. ACTION Sequence 是 ANIME Key 的陣列；ANIME 本身通常不直接當 Skill Action。
# 4. Battler Position Reset 類 Hash 代表該戰鬥者回合結束；Reset 後不能再由該
#    battler 追加傷害，因此每個完整攻擊 Sequence 都必須注意 Reset 的位置。
# 5. 本頁位於 SBS 核心資料層；修改 Key 前要同步查 SBS Core、ATB Charge Action、
#    FS Hero Action Add-on、Pokemon Action Sequences 與技能資料庫 Note。
#
# 【ANIME Hash 基本語法】
#   ANIME = {
#     "KEY" => [參數...],
#   }
# Key 可自行命名，但不能只用純數字；不要與既有 Key 重名。
# Hash Array 的欄位依動作類型不同；下列各節是主要格式。
#
# 【戰鬥者姿勢／Battler Pose】
# 格式概念：
#   [FileNo, Row, Speed, Loop, Wait, Fixed, Z, Shadow, WeaponAnimeKey]
# FileNo：0=資料庫指定的 Walking Graphic；n=CharacterName_n。
# Row：Sprite Sheet 列，0 為最上方（通常 0～3）。
# Speed：換幀速度，數字越小越快。
# Loop：0 往返 1-2-3-2；1 單向 1-2-3-1；2 只播一次。
# Wait：再次 Loop 前等待幀；Loop=2 時不使用。
# Fixed：-2 反向 Loop；-1 正常 Loop；0～2 固定顯示指定 frame。
# Z：加到 Battler Z priority。
# Shadow：true 顯示影子，false 隱藏。
# WeaponAnimeKey：同時播放的武器 Sprite Animation Key；"" 代表不用。
#
# 【武器 Sprite 動畫】
# Weapon Sprite Key 不直接放入 ACTION，而是填在 Battler Pose 的 Weapon 欄。
# 主要參數：Xa／Ya 位移；Za 決定武器畫在人物前或後；A1／A2 起迄角度；
# Or 旋轉原點（0 中央、1 左上、2 右上、3 左下、4 右下）；Inv 水平鏡像；
# Xs／Ys 縮放；Xp／Yp 初始位置微調；Weapon2=true 改用二刀流第二把武器。
# Y 軸方向與一般座標相反：負值往上、正值往下。
#
# 【戰鬥者移動】
# 格式概念：[Origin, X, Y, Time, Accel, Jump, PoseKey]
# Origin：0 目前位置；1 目標中心；2 畫面（0,0 左上）；3 自己起始位置；
#         4 目標頭部；5 目標腳部。
# X／Y：相對 Origin 的 pixel；Y 負值上、正值下。
# Time：總移動時間，越大越慢。
# Accel：正值加速、負值減速。
# Jump：負值為一般跳弧，正值反向弧，0 不跳。
# PoseKey：移動中使用的 Battler Pose。
#
# 【浮空移動】
# Type 固定 "float"；A=起始高度、B=結束／維持高度、Time=移動時間、Animation=Pose。
# 浮空是相對自己的 Shadow；原作提醒不適合一邊用 Battler Movement 水平移動、一邊
# 同時做浮空位移。
#
# 【位置重設】
# Type 固定 "reset"；參數包含回起始位置的 Time、Accel、Jump、PoseKey。
# Sequence 使用 Reset 後視為該 battler 回合結束；Reset 後不要再放傷害段。
#
# 【強制其他 Battler 行動】
# Type 可為 "SINGLE"（執行一個 ANIME Key）或 "SEQUENCE"（執行 ACTION Key）。
# Object：0=目前選中目標；1～999=擁有該 State ID 的 battler；負號＋Skill ID 可指
#         定「學會該技能的其他 Actor」；1000+Actor Index 可指特定 Actor。
# Reset Type：被強制行動者回原位置的方式。
# 找不到指定對象時可能取消該 Action，因此不要把不存在的 Actor Index 寫死。
#
# Type 固定 "target"。Object 指定要改 Target 的 Battler；Target：
#   0 自己；1 自己原 Target；2 修改後的新 Target；3 還原先前 Target。
# 原本 Target 仍保存；真正能造成傷害的仍是目前 active battler。
#
# 【Skill Link／衍生技能】
# Type 固定 "der"；參數包含成功率、是否必須已學會、Skill ID。
# 成功 Link 會立刻結束目前 ACTION Sequence，並改執行被連結技能；被連結技能的
# MP／HP cost 仍會消耗。若機率判定失敗則跳過 Link，原 Sequence 繼續。
#
# 本節用條件決定是否執行某 ANIME／ACTION Key。條件類型與參數請以本頁 Hash 實際
# 定義為準；改條件 Key 前先反查目前 Skill／Hero Action 是否引用。
#
# Angle 類 Hash 控制 Battler Sprite 旋轉；Zoom 控制 X/Y 比例。角度負值通常代表
# 反時針；縮放可用小數。這些只影響演出，不應拿來改邏輯座標。
#
# 本節負責播放資料庫 Animation、Skill Effect／傷害段以及對象／Mirror 等設定。
# 多段技能若需要多次真正傷害，應依 SBS Sequence 正確安排多個 Effect 段；不要只
# 靠動畫看起來像多段。
#
# 【Moving Animation／飛行圖形】
# 用於箭、投擲武器、Projectile 等從起點飛到目標的圖形／動畫。Weapon／Skill／Item
# 的 fly graphic 可由後方各自設定，檔案一般來自 Graphics/Characters。
# Flying Graphic Angle 可控制飛行途中角度；Skill 亦有獨立版本。
#
# 【其他 ANIME Hash 類型】
# Emotion Balloon：顯示 Balloon／情緒圖示。
# Sound Effects：播放 SE。
# Game Speed Modifier：暫時改變演出速度。
# State Granting／Removal：附加／解除 State。
# Change Actor Graphic：暫時／永久切換 Actor Character Graphic。
# Cut-In Image：顯示 Cut-In 圖片。
# Game Switch／Variable Control：操作遊戲 Switch／Variable。
# Script Operation：執行 Script expression；風險最高，修改前先查依賴。
# Special Modifier Keys：原作明確要求名稱不可更改。
# Delay Sequence Processing：延遲 Sequence 處理。
#
# 【ACTION Sequence 基本語法】
# ACTION Hash 是「依序執行哪些 ANIME/ACTION Key」的清單；可以列任意數量的 Key。
# Key 名稱必須已在 ANIME 或其他 ACTION 中定義。Action Sequence 會被後方 Actor／
# Enemy／Weapon／Skill／Item 方法依 ID 指派。
#
# 【Actor 基本 Action】
# 本頁可依 Actor ID 設定：空手攻擊、待機、HP 1/4 瀕危、防禦、受傷、閃避、
# Command Input、Command Selected、逃跑成功／失敗、勝利、戰鬥開始、中斷重設、
# 戰鬥不能、Shadow 與 Shadow 微調。
# Actor 沒有 Database Notebox，所以這類基本 Action 多半必須在本頁 case @actor_id
# 直接設定。
#
# 【Enemy 基本 Action】
# 可依 Enemy ID 設定：空手攻擊、待機、瀕危、防禦、受傷、閃避、逃跑、戰鬥開始、
# 中斷重設、戰鬥不能、Shadow／位置修正、裝備武器、消滅動畫、多重行動、動畫戰鬥
# 圖與 Mirror。Enemy 的 Screen Positioning Adjustment 會影響 SBS 畫面座標，與
# Troop Database 座標一起使用時要實機確認。
#
# State 可設定「附加後等待 Sequence」、擴充效果與 Slip Damage／Regeneration。
# Slip Damage 格式概念：[Type, Constant, %, POP?, AllowDeath]；Type 為 "hp" 或 "mp"。
# 固定值／百分比正數代表傷害、負數代表回復；POP? 控制數字；AllowDeath 為原作
# 註明不完全可靠的舊功能。若使用 Notetag Add-on，可用原 Notetag 字串，不能翻譯。
#
# Weapon#action：Weapon ID 對應 ACTION Key。
# Weapon#graphic：指定 Graphics/Characters 的獨立武器圖；"" 代表不用。
# Weapon#flygraphic：指定投擲時飛行圖形，例如弓與箭分開時使用。
#
# Skill#action：Skill ID → ACTION Key；此處只能指定 ACTION Key，不能直接指定 ANIME。
# Skill Extension 常見識別字：
#   PERFECTHIT    必中且不可閃避
#   IGNOREREFLECT 忽略傷害反射
#   HELPHIDE      施放時不顯示 Help Window
#   TARGETALL     同時作用敵我全體
#   RANDOMTARGET  隨機目標（Scope 必須搭配全體敵／全體友方）
#   OTHERS        不作用施術者自身
#   NOOVERKILL    目標 HP 已 0 後不再追加傷害
#   NOFLASH       行動時 Battler 不閃白
#   NONE          無額外效果／預設
# Skill#flygraphic：技能飛行圖形，通常讀 Graphics/Characters。
#
# Item Extension 與 Skill 類似，可用 PERFECTHIT、IGNOREREFLECT、HELPHIDE、TARGETALL、
# RANDOMTARGET、OTHERS、NOOVERKILL、NOFLASH 等識別字。
# Item#flygraphic：物品飛行圖形。
#
# 【Notetag Add-on 通用詞】
# 若專案啟用 Tankentai Notetag Add-on，原文中的 key／value／value%／id／type／
# filename 都是參數說明；Notetag 本身必須保持英文識別字與格式，**不可翻成中文**。
#
# 【範例：建立 Pose 與 Sequence】
#   ANIME = {
#     "MY_POSE" => [1, 0, 5, 2, 0, -1, 0, true, ""],
#   }
#   ACTION = {
#     "MY_ATTACK" => ["MY_POSE", "DAMAGE_ANIME", "RESET"],
#   }
# 實際 Key 應使用專案已定義的 Damage／Reset Hash，以上只示意資料結構。
#
# 【維護規則】
# 1. 中文化只改說明，不改任何 ANIME／ACTION Key、字串、陣列數值或方法。
# 2. 新增 Action 時，在腳本開頭同步補用途、參數與最小可用範例。
# 3. 任何 Key 更名先全域搜尋：SBS、ATB、Database Skill/Item Note、FS Hero Action。
# 4. 原作者、版本、網址與 Credits 保留；原英文技術解說已整理到本中文手冊。
