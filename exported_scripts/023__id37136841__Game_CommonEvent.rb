# ** Game_CommonEvent
#------------------------------------------------------------------------------
#  這個類專門用來操控全域事件。同時包攬了隨行處理事件的執行任務。
#  這個類作為 Game_Map 類（$game_map）的內部類使用。
#==============================================================================

class Game_CommonEvent
  #--------------------------------------------------------------------------
  # * 物件初始化
  #     common_event_id : 全域事件編號
  #--------------------------------------------------------------------------
  def initialize(common_event_id)
    @common_event_id = common_event_id
    @interpreter = nil
    refresh
  end
  #--------------------------------------------------------------------------
  # * 獲取全域事件名
  #--------------------------------------------------------------------------
  def name
    return $data_common_events[@common_event_id].name
  end
  #--------------------------------------------------------------------------
  # * 獲取觸發資訊
  #--------------------------------------------------------------------------
  def trigger
    return $data_common_events[@common_event_id].trigger
  end
  #--------------------------------------------------------------------------
  # * 獲取控制全域事件的開關的編號
  #--------------------------------------------------------------------------
  def switch_id
    return $data_common_events[@common_event_id].switch_id
  end
  #--------------------------------------------------------------------------
  # * 獲取待執行的事件指令清單
  #--------------------------------------------------------------------------
  def list
    return $data_common_events[@common_event_id].list
  end
  #--------------------------------------------------------------------------
  # * 更新內容資訊
  #--------------------------------------------------------------------------
  def refresh
    if self.trigger == 2 and $game_switches[self.switch_id] == true
      @interpreter = Game_Interpreter.new if @interpreter == nil
    else
      @interpreter = nil
    end
  end
  #--------------------------------------------------------------------------
  # * 更新幀
  #--------------------------------------------------------------------------
  def update
    if @interpreter != nil                # 啟用了隨行處理？
      unless @interpreter.running?        # 事件指令未執行？
        @interpreter.setup(self.list)     # 應用設置
      end
      @interpreter.update                 # 更新直譯器內容資訊
    end
  end
end
